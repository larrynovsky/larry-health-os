def test_run_one_hands_vcf_to_its_pipeline_and_names_foreign_genome(tmp_path, monkeypatch):
    """VCF идёт в vcf_import_pipeline своим процессом; чужой геном человек видит словами."""
    import subprocess
    import genome_intake as gi, infra_config
    told, calls = [], []
    monkeypatch.setattr(gi, "_tell", told.append)
    monkeypatch.setattr(infra_config, "is_primary", lambda: True)
    v = tmp_path / "wgs.vcf.gz"
    v.write_bytes(b"\x1f\x8b")
    gi._set_state(v, status="queued", format="vcf", member=None)

    def ok(args, **kw):
        calls.append(args)
        return subprocess.CompletedProcess(args, 0)
    monkeypatch.setattr(gi.subprocess, "run", ok)
    assert gi.run_one(v)["status"] == "done"
    assert calls[0][-4:] == ["--phase", "all", "--vcf", str(v)]
    assert "полный геном" in told[0] and "разобран" in told[-1]

    def foreign(args, stdout=None, **kw):
        stdout.write("vcf_import_pipeline.GenomeIdentityError: 900 из 1000 позиций\n")
        return subprocess.CompletedProcess(args, 1)
    gi._set_state(v, status="queued", format="vcf", member=None)
    monkeypatch.setattr(gi.subprocess, "run", foreign)
    assert gi.run_one(v)["status"] == "failed"
    assert "другого человека" in told[-1]


def test_chip_identity_fallback_mirrors_the_seed(db, monkeypatch):
    """Порог «чужой геном» живёт в system_config (решение владельца 29.09); резерв в коде —
    ЗЕРКАЛО сида, не вторая норма: разойдись они — при живой БД одно поведение, без неё другое."""
    import genome_intake as gi
    import health_db
    monkeypatch.setenv("ALLOW_WRITE_NONPRIMARY", "1")
    health_db.init_db()                  # сид пишет миграция init_db, фикстура её не зовёт
