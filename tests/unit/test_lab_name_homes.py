# Выборка из глоссария (замер 2026-07-28). Это данные-улика, а не порог:
# они фиксируют наблюдавшееся расхождение, чтобы тест краснел по конкретной паре,
# а не по абстракции. Полный список — в шапке файла.
# Имя константы намеренно НЕ «CONFIRMED_BY_HUMAN»: все пять пар из `SEED_ALIASES`,
# человека там не было (см. поправку в шапке). Имя, которое лжёт, — тот же дефект,
# что и `confirmed=1` без провенанса.
SEEDED_PAIRS = [
    ("Total Cholesterol", "Cholesterol_Total"),
    ("Total Bilirubin", "Bilirubin_total"),
    ("Vitamin B12", "Vitamin_B12"),
    ("P-amylase", "Amylase_pancreatic"),
    ("NT-pro BNP i.S.", "NT_proBNP"),
    ("Methylmalonsäure i.S.°", "Methylmalonic_acid"),
]
# 2026-07-29: значения приведены к ПОСЛЕ-миграционным. Владелец выбрал конвенцию «явное
# имя lab_canon без исключений», расхождений в глоссарии не осталось ни одного.
# Тест перестал быть характеризацией дефекта и стал регрессионным сторожем: он держит
# шесть имён неподвижными точками. Пометку `xfail` сняли вместе с дефектом — оставить её
# значило бы объявлять красным то, что зелёное.

# Каноническое имя, добавляемое только в синтетический глоссарий теста.
GLOSSARY_ONLY_CANONICAL = "Holotranscobalamin"


@pytest.fixture
def isolated_shared_vocab(tmp_path, monkeypatch):
    """Общий межтенантный словарь — в tmp. Иначе тест пишет в домашний каталог машины."""
    monkeypatch.setattr(lab_backfill, "_SHARED_VOCAB_DB", tmp_path / "lab_vocab.db")
    return tmp_path


@pytest.mark.xfail(strict=True, reason=(
    "F-09: словарь распознавателя собирается из `_VOCAB` ∪ общего `lab_vocab`, а "
    "`lab_name_aliases` (единственный дом с подтверждением человека) в него не входит. "
    "Зелёным станет в Области 2."))
def test_a10_recognizer_vocab_includes_human_confirmed_names(isolated_shared_vocab, monkeypatch):
    """A10 — словарь распознавателя обязан включать имена, утверждённые человеком.

    Контракт: если человек через ревью подтвердил, что `Holo-TC` — это
    `Holotranscobalamin`, распознаватель обязан иметь возможность выбрать это имя.
    Иначе подтверждение человека не влияет ни на что: модель получает словарь без
    этого имени, отдаёт `canonical_name=null`, и строка уходит в канон под сырым
    именем из документа — то есть под РАЗНЫМИ именами в разных документах.

    Baseline: `_load_vocab()` собирает `_VOCAB ∪ lab_vocab.db` и в `lab_name_aliases`
    не заглядывает. Подтверждение человека в этот путь не входит.

    ОРАКУЛ объявлен до тела: утверждённое имя присутствует в `_load_vocab()`.
    """
    monkeypatch.setattr(
        lab_backfill.labs_db, "get_all_canonical_names",
        lambda: [GLOSSARY_ONLY_CANONICAL], raising=False,
    )
    vocab = lab_backfill._load_vocab()
    assert GLOSSARY_ONLY_CANONICAL in vocab, (
        f"{GLOSSARY_ONLY_CANONICAL!r} подтверждён человеком в lab_name_aliases, но "
        "распознаватель его не увидит: словарь собирается из _VOCAB и общего lab_vocab, "
        "а глоссарий канона в этот путь не входит ни одним каналом"
    )


@pytest.mark.parametrize("raw_name", [
    "Тропонин-1", "тропонин 1", "Troponin I", "тропонин i", "Troponin-I",
])
def test_troponin_i_is_not_troponin_t(raw_name):
    """Тропонин I не сводится к тропонину T. ЗЕЛЁНЫЙ с 2026-07-29.

    До этой правки `lab_canon._SYNONYMS["Troponin"]` содержал и `troponin i`, и
    `тропонин-1`, поэтому два РАЗНЫХ белка ложились в одно имя и в один тренд.
    Тропонины I и T — разные белки. Общая статья для них смешивала бы
    разные величины независимо от написания или формата документа.

    ГРАНИЦА: голое «Тропонин»/«Troponin» намеренно осталось у T, и это ОТКРЫТЫЙ вопрос
    (какой белок печатает лаборатория без уточнения — знает бланк, не этот тест).
    """
    got = lab_canon.normalize(raw_name)
    assert got == "Troponin_I", (
        f"{raw_name!r} канонизирован как {got!r} — тропонин I снова слит с тропонином T; "
        "это разные белки с несопоставимыми референсами, один тренд для них невозможен"
    )


@pytest.mark.parametrize("raw_name,expected", [
    # Процентная колонка бланка несёт «%» прямо в имени — суффикс переживает извлечение.
    ("Neutrophils /ნეიტროფილები %", "Neutrophils_pct"),
    ("Lymphocytes %", "Lymphocytes_pct"),
    pytest.param("Basophilis %", "Basophils_pct", marks=pytest.mark.xfail(strict=True, reason=(
        "F-09 в чистом виде: опечатка лаборатории «Basophilis» живёт ТОЛЬКО в глоссарии, "
        "а `lab_canon` его не читает. Чинить это в `lab_canon` нельзя — это значило бы "
        "скопировать глоссарий в код, то есть узаконить тот самый второй дом. Зелёным "
        "станет, когда глоссарий подключат к канонизации (Область 2)."))),
    # Абсолютная колонка помечена «Abs», но перенос строки в PDF отрывает суффикс,
    # и распознаватель видит голое имя. Значит голое имя здесь — АБСОЛЮТ.
    ("Neutrophils Abs", "Neutrophils_abs"),
    ("Neutrophils", "Neutrophils_abs"),
    ("Eosinophils", "Eosinophils_abs"),
])
def test_leukocyte_family_reading_matches_the_source_form(raw_name, expected):
    """Прочтение семейства лейкоцитов сверено с БЛАНКОМ, а не с догадкой.

    Источник: формат бланка synevo (значения ниже — синтетика
    той же формы). Бланк печатает обе колонки и обе помечает — процентную суффиксом «%», абсолютную суффиксом «Abs»:

        Neutrophils /ნეიტროფილები %      60     %       50 - 75
        Neutrophils
        Abs/ნეიტროფილებიაბს              4.10   10^9/L  2.25 - 7.91

    ГОЛОГО имени в бланке НЕТ. Такие строки — это «… Abs», разорванные переносом
    при извлечении текста. Поэтому голое `Neutrophils`, которое видит распознаватель,
    означает абсолют, а не процент.

    Это опровергает сид `("Neutrophils", "Neutrophils_pct")`, который жил в
    `health_db.SEED_ALIASES` и утверждал обратное. Пара убрана; тест держит прочтение,
    чтобы догадка не вернулась.

    ГРАНИЦА: вывод верен для ФОРМАТА synevo. Другая лаборатория может печатать голое
    имя как процент — тогда это будет её пара в глоссарии, а не смена этого правила.
    """
    got = lab_canon.normalize(raw_name)
    assert got == expected, (
        f"{raw_name!r} прочитан как {got!r} вместо {expected!r} — прочтение разошлось "
        "с бланком synevo (см. докстринг: формат источника)"
    )


@pytest.mark.parametrize("composite", [
    "Albumin/Globulin", "Cholesterol/HDL", "Neutrophils/Lymphocytes Ratio", "Chol/dHDLc",
    "Кальций/Фосфор", "НЕЙТРОФИЛЫ/ЛИМФОЦИТЫ", "Альбумин/Глобулин",
])
def test_slash_stripping_does_not_eat_composite_names(composite):
    """Позитивный контроль к срезанию двуязычного хвоста: составное имя не теряет вторую часть.

    Срезание всего после «/» ввёл я 2026-07-29, чтобы «Neutrophils /ნეიტროფილები %»
    сопоставлялось. Первая версия правила срезала хвост, если в нём нет ЛАТИНИЦЫ, — и
    молча съедала русские составные имена: «Кальций/Фосфор» стал бы «Кальций». То есть
    правка против расщепления имён сама вводила расщепление. Поймано этим контролем;
    правило ужесточено до «ни латиницы, ни кириллицы».

    ОРАКУЛ объявлен до тела: либо имя разрешилось в известный канон (значит вторая часть
    участвовала), либо осталось нетронутым. Чего быть не должно — молчаливой потери
    хвоста с превращением в первый член.
    """
    got = lab_canon.normalize(composite)
    head = composite.split("/")[0].strip()
    assert got != head, (
        f"{composite!r} превратилось в {got!r} — хвост составного имени срезан, "
        "аналит подменён своим первым членом"
    )


def test_bare_troponin_still_goes_to_t_family():
    """Позитивный контроль обратной стороны: разрыв НЕ утащил семейство T за собой."""
    for raw in ("Troponin T hs", "Troponin T", "тропонин"):
        assert lab_canon.normalize(raw) == "Troponin", (
            f"{raw!r} перестал быть Troponin — разрыв тропонинов задел семейство T"
        )


@pytest.mark.parametrize("raw_name,canonical", SEEDED_PAIRS)
def test_a11_glossary_canonical_is_a_fixed_point(raw_name, canonical):
    """A11 — имя, объявленное каноническим в глоссарии, канонизатор менять не должен.

    ЗЕЛЁНЫЙ с 2026-07-29. Был красным (характеризация F-09): 11 пар из 71, потом 6 из 66.
    Закрыт двумя миграциями — по источнику (бланк) и по вердикту владельца о конвенции.
    Теперь это регрессионный сторож: вернётся расхождение — покраснеет здесь и в
    `tests/consistency/test_lab_name_homes_ratchet.py` (там множество пустое).

    Это и есть тест «имя — функция». Если глоссарий говорит «`Total Cholesterol` — это
    `Cholesterol`», а `lab_canon.normalize("Cholesterol")` отвечает `Cholesterol_Total`,
    то у одного аналита два канонических имени, и какое попадёт в `lab_results`,
    зависит от маршрута документа, а не от документа.

    Если писатели расходятся по компонентам ключа (date, source, test_name),
    дедуп не объединит повторную обработку одного документа.

    ГРАНИЦА: тест НЕ утверждает, что прав глоссарий. Он утверждает, что двух ответов
    быть не может. Какой из двух верен — вердикт владельца (Область 2, оракул-методолог).

    ОРАКУЛ объявлен до тела: `normalize(canonical) == canonical`.
    """
    got = lab_canon.normalize(canonical)
    assert got == canonical, (
        f"глоссарий утверждает {canonical!r} (из {raw_name!r}), а lab_canon.normalize "
        f"немедленно переименовывает его в {got!r} — у аналита два канонических имени, "
        "и выбор между ними делает маршрут документа, а не документ"
    )
