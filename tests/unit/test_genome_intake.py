"""genome_intake: геном из входящих тенанта → genome_pipeline (нить document-intake, 24.09).

Форматы — по описаниям производителей (замер 24.09): 23andMe TSV, AncestryDNA (две колонки
аллелей, хромосомы 23–26, «0» = нет вызова), MyHeritage/FTDNA (CSV в кавычках), tellmeGen
(zip с CSV, пропуск «–»). Данные синтетические.
"""
from __future__ import annotations

import zipfile
from pathlib import Path

import pytest

pytestmark = pytest.mark.unit

N = 30


def _23andme(p: Path, double_tab=False) -> Path:
    sep = "\t\t" if double_tab else "\t"
    body = "".join(f"rs{i}{sep}1\t{1000 + i}\tAG\n" for i in range(N))
    p.write_text("# This data file generated by 23andMe\n# file_id: X1\n"
                 "# rsid\tchromosome\tposition\tgenotype\n" + body + "i700\tMT\t50\tA\n")
    return p


def _ancestry(p: Path) -> Path:
    body = "".join(f"rs{i}\t23\t{i + 5}\tA\tG\n" for i in range(N))
    p.write_text("#AncestryDNA raw data\nrsid\tchromosome\tposition\tallele1\tallele2\n"
                 + body + "rs999\t26\t77\t0\t0\n")
    return p


def _myheritage(p: Path) -> Path:
    body = "".join(f'"rs{i}","2","{i + 9}","CT"\n' for i in range(N))
    p.write_text('# MyHeritage DNA raw data.\nRSID,CHROMOSOME,POSITION,RESULT\n' + body)
    return p


def _tellmegen_zip(p: Path, member="tellmegen_raw.csv") -> Path:
    body = "".join(f"rs{i},X,{i + 3},GG\n" for i in range(N))
    with zipfile.ZipFile(p, "w", zipfile.ZIP_DEFLATED) as zf:
        zf.writestr(member, "rsid,chromosome,position,genotype\n" + body + "rs998,1,5,–\n")
    return p


@pytest.mark.parametrize("make,fmt,first", [
    (_23andme, "23andme_like", ("rs0", "1", 1000, "AG")),
    (_ancestry, "ancestry", ("rs0", "X", 5, "AG")),
    (_myheritage, "myheritage_ftdna", ("rs0", "2", 9, "CT")),
    (_tellmegen_zip, "tellmegen_csv", ("rs0", "X", 3, "GG")),
])
def test_formats_recognized_and_normalized(tmp_path, make, fmt, first):
    import genome_intake as gi
    src = make(tmp_path / "raw.bin")
    k = gi.sniff(src)
    assert k and k["supported"] and k["format"] == fmt, k
    out = tmp_path / "norm.txt"
    rows, file_id = gi._normalize(src, k["member"], out)
    assert rows >= N and file_id.startswith("sha256:")
    import genome_parser
    parsed = genome_parser.parse_tsv(out)           # тот самый парсер конвейера S1
    assert len(parsed) == rows
    assert (parsed[0]["rsid"], parsed[0]["chromosome"], parsed[0]["position"],
            parsed[0]["genotype"]) == first
    nocalls = [r for r in parsed if r["rsid"] in ("rs999", "rs998")]
    assert all(r["genotype"] == "--" for r in nocalls)
    assert {r["chromosome"] for r in parsed if r["rsid"] == "rs999"} <= {"MT"}


def test_double_tab_23andme(tmp_path):
    import genome_intake as gi
    src = _23andme(tmp_path / "g.txt", double_tab=True)
    rows, _ = gi._normalize(src, None, tmp_path / "n.txt")
    assert rows == N + 1


