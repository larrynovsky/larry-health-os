def _norm_unit(unit: str) -> str:
    """Единицу к латинскому канону: г/л→g/l, ммоль/л→mmol/l, μ(мю)→u, нг/мл→ng/ml,
    счётные нотации клеток к ОДНОЙ величине (10^3/ul, 10^6/ul)."""
    u = (unit or "").strip().lower().replace("µ", "u").replace("μ", "u").replace("ё", "е")
    for a, b in (# мг/100 мл ≡ мг/дл (дециллитр и есть 100 мл) — эквивалент записи,
                 # не пересчёт. ДО «мг/л», иначе хвост «мл» съедается раньше.
                 ("мг/100 мл", "mg/dl"), ("мг/100мл", "mg/dl"),
                 ("mg/100 ml", "mg/dl"), ("mg/100ml", "mg/dl"),
                 ("мкг/л", "ug/l"), ("мг/л", "mg/l"),          # ДО г/л (иначе мг/л→мg/l)
                 ("мкмоль/л", "umol/l"), ("ммоль/л", "mmol/l"),
                  # Транслитерированное обозначение той же единицы:
                 ("mkmol/l", "umol/l"),
                 ("мкг/дл", "ug/dl"), ("мг/дл", "mg/dl"),
                 ("нг/мл", "ng/ml"),
                  # Различие письменности не должно создавать разные единицы.
                  # Длинные обозначения заменяются раньше коротких.
                 ("мкме/мл", "uiu/ml"), ("мкед/мл", "uiu/ml"),  # ДО ед/мл и ме/л
                  # мМЕ/л заменяется до ме/л, чтобы не оставить гибрид алфавитов.
                 ("мме/мл", "miu/ml"),                          # ДО мме/л
                 ("мме/л", "miu/l"),
                 # Секунды коагулограммы (PT, aPTT, тромбиновое) печатаются и «sec»,
                 # и «сек.» — расхождение письменности, не шкалы. Точка ДО без точки.
                 ("сек.", "sec"), ("сек", "sec"),
                  # Полное обозначение клеток заменяется до сокращённого.
                 ("клеток/грамм", "кл/г"), ("клеток/г", "кл/г"),
                 ("пмоль/л", "pmol/l"), ("нмоль/л", "nmol/l"),
                 ("пг/мл", "pg/ml"),                            # ДО пг
                 ("ед/мл", "u/ml"), ("ед/л", "u/l"), ("ме/л", "iu/l"),
                 ("мм/ч", "mm/hr"), ("фл", "fl"), ("пг", "pg"),
                 ("гр/л", "g/l"), ("г/л", "g/l"), ("gr/l", "g/l"),
                 ("г/дл", "g/dl")):
        u = u.replace(a, b)
    # Счётные единицы: 10e3 = ×10^3; 10^9/L = 10^3/µL; /mm^3 = /µL.
    # НЕ трогает аналиты с to_conventional (у счётчиков правил нет → без побочки конверсии).
    u = u.replace("10e3", "10^3").replace("10e6", "10^6")
    for a, b in (("10^9/l", "10^3/ul"), ("10^9/л", "10^3/ul"),
                 # 10^12/L = 10^12/(10^6 µL) = 10^6/µL — та же тождественность, что 10^9/L;
                 # RBC печатается обеими нотациями. НЕ трогаем «кл/мкл»: там магнитуда
                 # отличается в тысячу раз — это правило конверсии, а не письменность.
                 ("10^12/l", "10^6/ul"), ("10^12/л", "10^6/ul"),
                 ("10^3/mm^3", "10^3/ul"), ("10^6/mm^3", "10^6/ul")):
        u = u.replace(a, b)
    # µU/mL ≡ µIU/mL (для TSH/инсулина «I» в IU опускают): унификация нотации, НЕ конверсия значения
    u = u.replace("uu/ml", "uiu/ml")
    # СОЭ: «mm/h» и «mm/hr» — одна величина. Точное совпадение, а не replace:
    # replace("mm/h") съел бы и «mm/hr» → «mm/hrr».
    if u == "mm/h":
        u = "mm/hr"
    return u


def to_conventional(canonical: str, value, unit: str):
    """СИ → conventional по canonical+unit. Возвращает (value, unit). Если не
    знаем единицу/аналит — без изменений."""
    if value is None or not unit:
        return value, unit
    rules = _TO_CONVENTIONAL.get(canonical)
    if not rules:
        return value, unit
    u = _norm_unit(unit)
    for si_sub, (factor, target) in rules.items():
        if si_sub in u:
            try:
                return round(float(value) * factor, 4), target
            except (TypeError, ValueError):
                return value, unit
    return value, unit


def to_conventional_range(canonical: str, ref_low, ref_high, unit: str):
    """Референс — той же шкалы, что значение. Возвращает (ref_low, ref_high).

    Отдельный публичный вход, а не «вызови to_conventional дважды»: пересчёт
    ГРАНИЦ обязан идти тем же правилом и в тот же момент, что пересчёт значения,
    иначе строка собирается из двух верных по отдельности чисел в неверную картину.
    Если перевести только значение, а референс оставить в прежней шкале,
    читатель может приписать строке ошибочный статус.

    Границы конвертируются ТОЛЬКО вместе: если правило применилось к одной, оно
    обязано примениться к обеим. Частично пересчитанный диапазон хуже непересчитанного —
    он выглядит правдоподобно.
    """
    lo, _u1 = to_conventional(canonical, ref_low, unit)
    hi, _u2 = to_conventional(canonical, ref_high, unit)
    return lo, hi


