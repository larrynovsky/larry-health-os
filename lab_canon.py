# Кириллические буквы, неотличимые на глаз от латинских. Фолдим В СТОРОНУ ЛАТИНИЦЫ
# и ТОЛЬКО одиночный буквенный токен (с необязательной цифрой): «Витамин А» → «Витамин A»,
# «В1» → «B1», «К2» → «K2». Узость правила обязательна: фолди мы слово целиком,
# «Сорбит» превратился бы в «Copбит» — детерминированно, но нечитаемо, а имя аналита
# читает человек. Токен из одной буквы почти всегда обозначение (витамин, фракция,
# субъединица, пищевая добавка), и там латиница — форма оригинала.
# Фолдинг предотвращает дубли из визуально одинаковых букв разных алфавитов.
_HOMOGLYPH = str.maketrans("АВЕКМНОРСТУХаеорсух", "ABEKMHOPCTYXaeopcyx")
_SINGLE_LETTER = re.compile(r"(?<![^\W\d_])([АВЕКМНОРСТУХаеорсух])(\d*)(?![^\W\d_])")


def _fold_homoglyphs(name: str, keep_prepositions: bool = True) -> str:
    """Одиночные кириллические буквы → латиница. Слова целиком НЕ трогает.

    `keep_prepositions=True` (для ИМЁН, которые читает человек): строчная буква,
    окружённая пробелами с обеих сторон, — русский ПРЕДЛОГ, а не обозначение.
    Без исключения «Тестостерон, связанный с альбумином» превращался в
    «связанный c альбумином». Обозначения так не пишут: у них рядом цифра
    («C0», «M2», «E355»), дефис («а-аминоадипиновая») или скобка
    («Липопротеин (а)»), либо они заглавные («Витамин А», «Бисфенол А»).

    `keep_prepositions=False` (для КЛЮЧЕЙ словаря): фолдим всё подряд. Ключи
    хранятся в нижнем регистре, и признак «заглавная» там уже потерян — с
    исключением «хромогранин а» перестал бы сводиться к «хромогранин a», и
    латинское написание не нашло бы свою же статью. Ключ читает машина,
    предлог в нём испортить нечего.
    """
    s = name or ""

    def _repl(m):
        ch, digits = m.group(1), m.group(2)
        if keep_prepositions and not (ch.isupper() or digits):
            left = s[m.start() - 1] if m.start() else " "
            right = s[m.end()] if m.end() < len(s) else " "
            if left.isspace() and right.isspace():
                return m.group(0)          # предлог — не трогаем
        return ch.translate(_HOMOGLYPH) + digits

    return _SINGLE_LETTER.sub(_repl, s)


