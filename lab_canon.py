def microscopy_count(text: str, canonical: str) -> dict | None:
    """Счёт клетки `canonical` из предложения микроскопии.

    Возвращает {"value": верхняя граница, "value_op": "<=" при диапазоне | None,
    "unit": MICROSCOPY_UNIT} для «N-M <клетка>» / «N <клетка>» / «<клетка> N-M»,
    либо {"token": rare|many|not_detected} для слова-квалификатора перед клеткой,
    либо None — «не разбираю» (безопасная сторона: строка остаётся человеку).

    Для диапазона сохраняется верхняя граница с value_op="<=", а не
    выдуманная середина; нижняя остаётся в staging. Клетка ищется по канону
    строки. Незнакомый канон → None.
    """
    cells = _MICROSCOPY_CELLS.get(canonical or "")
    if not cells or not (text or "").strip():
        return None
    t = _fold_value(text)
    cell_re = "(?:%s)[a-zа-яё]*" % "|".join(re.escape(_fold_value(c)) for c in cells)
    # `_fold_value` уже заменил дефис пробелом: «2-3» → «2 3»; en-dash оставляем опцией.
    num = r"(\d+)(?:\s*[-–]?\s*(\d+))?"
    for pat in (rf"{num}\s*{cell_re}", rf"{cell_re}\s*:?\s*{num}"):
        m = re.search(pat, t)
        if m:
            lo, hi = int(m.group(1)), int(m.group(2) or m.group(1))
            lo, hi = min(lo, hi), max(lo, hi)
            return {"value": float(hi), "value_op": "<=" if hi != lo else None,
                    "unit": MICROSCOPY_UNIT}
    for token, words in _MICRO_QUALIFIERS.items():
        q = "|".join(re.escape(_fold_value(w)) for w in words)
        if re.search(rf"(?:{q})[a-zа-яё]*\s+{cell_re}", t) or \
                re.search(rf"{cell_re}\s+(?:{q})", t):
            return {"token": token}
    return None


def normalize_value(printed: str) -> str | None:
    """Напечатанный нечисловой результат → канонический токен, либо None.

    None означает «этого значения нет в словаре» и НЕ означает «мусор»: строка
    уезжает человеку на ревью вместе с сырым текстом, а в канон не едет
    (fail-closed, §13 ступень 2). Пополнение словаря — решение человека, а не
    догадка кода: молча принять незнакомое слово значило бы вернуть свободный
    текст через заднюю дверь.
    """
    return _QUAL_LOOKUP.get(_fold_value(printed))


def result_violation(value, value_text) -> str | None:
    """ЕДИНСТВЕННЫЙ дом правила «что такое результат». None = строка законна.

    Ровно одно из полей value и value_text должно быть непустым.
    Оба пусты — нет результата; оба заполнены — возможное смешение результата
    и референса, при котором текстовый читатель и числовой ряд расходятся.
    `check_specialized_lab_health` требует panel_type и хотя бы одно значение;
    здесь проверяется исключительность представления для `lab_results`.
    """
    has_num = value is not None and str(value).strip() != ""
    has_txt = bool((value_text or "").strip())
    if has_num and has_txt:
        return "и число, и текст: скорее всего в текст уехал референс"
    if not has_num and not has_txt:
        return "ни числа, ни текста: строка без результата"
    return None


