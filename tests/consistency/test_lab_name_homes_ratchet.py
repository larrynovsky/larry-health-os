"""tests/consistency/test_lab_name_homes_ratchet.py — ратчет расхождений между домами имени аналита.

ЗАЧЕМ. У имени аналита в системе несколько домов (нить `data-ingestion`, Область 2). Два из
них умеют утверждать канон независимо друг от друга:
  · `lab_name_aliases` — глоссарий в БД, привязан к формату;
  · `lab_canon._SYNONYMS/_LOOKUP` — канонизатор в коде.

ВАЖНАЯ ПОПРАВКА 2026-07-29. Первая формулировка этого файла называла глоссарий «домом с
подтверждением человека». Замер это опроверг: из 71 строки через ревью (`field_reviews_db`,
поле `source_example`) прошла ОДНА — `HomocysteineNew → Homocysteine`. Остальные 70 вставлены
`health_db.SEED_ALIASES` напрямую с `confirmed=1`, двумя пачками 2026-06-01 (54) и 2026-06-15
(17) — то есть датами миграций, а не ревью. Значит `confirmed=1` НЕ различает «человек
посмотрел» и «код засеял», а спор двух домов — это спор двух списков в одном и том же коде,
написанных в разное время. Классический дубль значения, не реплика.
Когда они расходятся, у аналита ДВА канонических имени, и какое попадёт в `lab_results`,
решает маршрут документа, а не документ. Именно так разошлась немецкая панель: промоушен и
прямой писатель дали разные `test_name`, дедуп по `(date, source, test_name)` не сработал.

ПОЧЕМУ РАТЧЕТ, А НЕ ПОЧИНКА. Какое из двух имён каноническое — `Bilirubin` или
`Bilirubin_total` — вердикт владельца-методолога, машинно невыводимый. Пока вердикта нет,
правильное поведение не «выбрать победителя», а «не дать множеству расхождений вырасти
молча». Это §13, ступень 2: безопасного авто-действия нет, но зафиксировать состояние можно.

ПОЧЕМУ НЕ WARN В НОЧНОМ ТРИАЖЕ. Одиннадцать известных расхождений сделали бы датчик
хронически жёлтым, а хронический жёлтый читается как фон (§13, banner-blindness). Ратчет
зелёный, пока множество ТО ЖЕ, и краснеет ровно в двух случаях — и оба требуют человека:
  · появилось новое расхождение → правка глоссария или `lab_canon` создала второе имя;
  · расхождение исчезло → вердикт вынесен, вычеркни строку отсюда и из плана нити.

ЧЕГО НЕ ДОКАЗЫВАЕТ. Что оставшиеся 60 пар СОГЛАСОВАНЫ по существу: неподвижная точка
означает лишь, что канонизатор не переименовывает имя, а не что имя верно клинически.
И не покрывает остальные два дома (`lab_backfill._load_vocab`, `lab_fuzzy`) — они не
УТВЕРЖДАЮТ канон, а выбирают из него; их расхождение проявляется иначе (A10, A17.3).

СРЕДА. Тест читает канонический `lab_name_aliases` только на чтение и только агрегатами —
ни одного значения пациента. Поэтому помечен `owner_env`: в tenant-staging прогоне
(`scripts/test_on_studio.sh`) он пропускается, а в ночном на каноне идёт.
"""
from __future__ import annotations

import pytest

import health_db
import lab_canon

# Две защиты, потому что они закрывают РАЗНЫЕ промахи среды:
#   · `owner_env` — исключает тест в tenant-staging прогоне (`scripts/test_on_studio.sh`),
#     где `lab_name_aliases` пуст и «исчезли все 11» было бы ложным красным;
#   · `skipif not _is_primary()` — на MacBook канона нет вовсе, и без этого тест падал бы
#     от ОТСУТСТВИЯ БД, то есть краснел бы про среду, а не про расхождение домов.
pytestmark = [
    pytest.mark.consistency,
    pytest.mark.owner_env,
    pytest.mark.skipif(
        not health_db._is_primary(),
        reason="ратчет судит канонический глоссарий; вне Studio канона нет",
    ),
]


# Расхождения на живом каноне. Формат: (format_id, raw_name, канон_глоссария,
# во_что_переименовывает_lab_canon). Менять только вместе с вердиктом владельца.
#
# 2026-07-28: было 11.
# 2026-07-29 (первая миграция): стало 6. Пять «X Abs» закрыты ПО ИСТОЧНИКУ — бланк synevo
# CR/10000000001.PDF показал, что абсолютная колонка помечена «Abs», а голого имени в
# бланке нет вовсе. Снапшот `health_preop_glossary_20260729.db`.
# 2026-07-29 (вторая миграция): стало 0. Владелец выбрал конвенцию «явное имя lab_canon,
# без исключений»; шесть строк глоссария и четыре строки канона переименованы. Снапшот
# `health_preop_names_20260729.db`. Побочно сведены два уже расщеплённых тренда
# (холестерин 13+1→14, амилаза 1+1→2) и `NT_proBNP` впервые получил строки — до этого
# `lab_freshness_twotier` мониторил имя, под которым в каноне не было ничего.
#
# ПУСТОЕ МНОЖЕСТВО — это не «ратчет больше не нужен», а самое сильное его состояние:
# теперь ЛЮБОЕ расхождение между глоссарием и канонизатором красное с первой строки.
# Ратчет краснел на обеих миграциях и оба раза требовал решения человека, а не
# пересчёта — это и есть доказательство, что он работает.
KNOWN_DISAGREEMENTS: set[tuple] = set()


def _live_disagreements() -> set[tuple]:
    """Пары глоссария, чей канон не является неподвижной точкой `lab_canon.normalize`."""
    with health_db.get_conn(read_only=True) as conn:
        rows = conn.execute(
            "SELECT format_id, raw_name, canonical FROM lab_name_aliases WHERE confirmed=1"
        ).fetchall()
    out = set()
    for fmt, raw, canon in rows:
        norm = lab_canon.normalize(canon)
        if norm != canon:
            out.add((fmt, raw, canon, norm))
    return out


def test_name_home_disagreements_match_declared_set():
    got = _live_disagreements()

    appeared = sorted(got - KNOWN_DISAGREEMENTS)
    resolved = sorted(KNOWN_DISAGREEMENTS - got)

    assert not appeared and not resolved, (
        "множество расхождений между глоссарием и канонизатором изменилось.\n"
        + (f"  ПОЯВИЛОСЬ (правка глоссария или lab_canon создала аналиту ВТОРОЕ каноническое "
           f"имя — это регрессия, а не рост словаря): {appeared}\n" if appeared else "")
        + (f"  ИСЧЕЗЛО (вердикт вынесен → вычеркни строку отсюда и из плана нити; либо "
           f"строку глоссария удалили, и тогда вопрос, куда делось подтверждение "
           f"человека): {resolved}\n" if resolved else "")
        + "  Оба случая требуют решения человека, а не правки только этого теста."
    )
