# ─── GEN:TEST_COVERAGE ─────────────────────────────────────────────────────

def _latest_summary() -> tuple[Path, dict] | None:
    """Самый свежий tests/reports/YYYY-MM-DD/summary.json."""
    if not REPORTS_DIR.exists():
        return None
    dirs = sorted(
        [p for p in REPORTS_DIR.iterdir() if p.is_dir() and p.name[:4].isdigit()],
        reverse=True,
    )
    for d in dirs:
        s = d / "summary.json"
        if s.exists():
            try:
                return s, json.loads(s.read_text(encoding="utf-8"))
            except Exception:
                continue
    return None


def build_test_coverage(lang="ru", *, descriptions=None) -> str:
    text = _TEXT[lang]
    found = _latest_summary()
    lines = [
        "<!-- GEN:TEST_COVERAGE:START -->",
        "",
        text["coverage"],
        text["coverage_header"],
        "",
    ]
    if found is None:
        lines += [
            text["no_data"],
            "",
            "<!-- GEN:TEST_COVERAGE:END -->",
        ]
        return "\n".join(lines)
    path, data = found
    when = data.get("date", path.parent.name)
    total = data.get("total", {})
    per = data.get("per_layer", {})
    overall_exit = data.get("overall_exit", "?")

    lines += [
        text["date"].format(when=when, overall_exit=overall_exit),
        "",
        text["coverage_columns"],
        "|---|---:|---:|---:|---:|",
    ]
    for layer in sorted(per.keys()):
        d = per[layer]
        lines.append(
            f"| {layer} | {d.get('tests', 0)} | {d.get('failures', 0)} "
            f"| {d.get('errors', 0)} | {d.get('skipped', 0)} |"
        )
    lines.append(
        f"| **TOTAL** | **{total.get('tests', 0)}** | **{total.get('failures', 0)}** "
        f"| **{total.get('errors', 0)}** | **{total.get('skipped', 0)}** |"
    )
    lines += ["", "<!-- GEN:TEST_COVERAGE:END -->"]
    return "\n".join(lines)


# ─── GEN:XFAIL_LIST ────────────────────────────────────────────────────────

def _scan_xfails() -> list[tuple[str, int, str]]:
    """AST-сканер: ищет @pytest.mark.xfail в tests/. Возвращает [(rel_path, line, reason)]."""
    out: list[tuple[str, int, str]] = []
    tests_dir = REPO / "tests"
    if not tests_dir.exists():
        return out
    for py in sorted(tests_dir.rglob("*.py")):
        try:
            src = py.read_text(encoding="utf-8")
            tree = ast.parse(src)
        except Exception:
            continue
        for node in ast.walk(tree):
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                for dec in node.decorator_list:
                    if _is_xfail_decorator(dec):
                        reason = _extract_reason(dec)
                        out.append((str(py.relative_to(REPO)), node.lineno, reason))
                        break  # один маркер на функцию достаточно
    return out


def _is_xfail_decorator(dec: ast.AST) -> bool:
    """Распознаёт @pytest.mark.xfail и @pytest.mark.xfail(reason=...)."""
    target = dec
    if isinstance(dec, ast.Call):
        target = dec.func
    # pytest.mark.xfail — Attribute(value=Attribute(value=Name('pytest')), attr='xfail')
    if isinstance(target, ast.Attribute) and target.attr == "xfail":
        inner = target.value
        if isinstance(inner, ast.Attribute) and inner.attr == "mark":
            outer = inner.value
            if isinstance(outer, ast.Name) and outer.id == "pytest":
                return True
    return False


def _extract_reason(dec: ast.AST) -> str:
    if not isinstance(dec, ast.Call):
        return ""
    for kw in dec.keywords:
        if kw.arg == "reason" and isinstance(kw.value, ast.Constant) and isinstance(kw.value.value, str):
            # Полная первая строка; лимит применяется после перевода.
            return kw.value.value.strip().splitlines()[0]
    return ""


def build_xfail_list(lang="ru", *, descriptions=None) -> str:
    text = _TEXT[lang]
    descriptions = descriptions or DescriptionText(lang)
    xfails = _scan_xfails()
    lines = [
        "<!-- GEN:XFAIL_LIST:START -->",
        "",
        text["xfail"],
        text["xfail_header"],
        "",
    ]
    if not xfails:
        lines += [text["empty"], "", "<!-- GEN:XFAIL_LIST:END -->"]
        return "\n".join(lines)

    lines += [
        text["total"].format(count=len(xfails)),
        "",
        text["xfail_columns"],
        "|---|---|",
    ]
    for path, line, reason in xfails:
        loc = f"`{path}:{line}`"
        lines.append(f"| {loc} | {descriptions.cell(reason, limit=120) if reason else text['no_reason']} |")
    lines += ["", "<!-- GEN:XFAIL_LIST:END -->"]
    return "\n".join(lines)


