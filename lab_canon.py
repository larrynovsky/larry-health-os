def _fold_value(printed: str) -> str:
    """Напечатанное значение → ключ поиска в словаре качественных.

    ОТДЕЛЬНО от `_key` для имён, и это не дублирование, а разные предметы. У имён
    свои правила (гомоглифы, скобки, проценты, размерность), и от `_key`/`normalize`
    зависят сохранённые канонические имена. Изменение нормализации имён ради
    значений может сломать поиск существующих записей.

    Главная беда здесь другая: турецкая заглавная `İ`. `"NEGATİF".lower()` даёт
    `negati` + U+0307 (combining dot above) + `f`, и наивное сравнение с `negatif`
    промахивается. Проект уже платил за этот класс алиасом AFP. Поэтому снимаем
    комбинирующие знаки, а не перечисляем варианты.

    Побочный эффект снятия комбинирующих на кириллице: `й`→`и`, `ё`→`е`. Для
    закрытого словаря из шести токенов это безвредно и даже полезно (`ё`/`е`
    печатают вперемешку); для произвольного русского текста было бы неверно —
    поэтому функция приватная и применяется только к значениям словаря.
    """
    import unicodedata
    s = unicodedata.normalize("NFD", (printed or "").strip().lower())
    s = "".join(ch for ch in s if not unicodedata.combining(ch))
    s = s.replace("ı", "i")                      # турецкая i без точки
    return re.sub(r"[\s.,;:()\[\]«»\"'-]+", " ", s).strip()


