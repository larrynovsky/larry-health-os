"""Записка нити не имеет права утверждать то, что опровергает соседний файл.

Что случилось 14.09. Звонок «нити без движения» позвал владельца к четырём нитям.
Проверка по коду показала: у `fdr-online` записка объявляла «следующий этап
(не начат)» про план, у которого шаги Ш1–Ш5 давно помечены закрытыми с
коммитами — исполнителем была соседняя нить, закрытая месяц назад. У
`brief-neutralization` записка ждала «вердикта владельца» по развилке, вердикт по
которой вписан в код и в `INDEX.md` двумя днями позже паузы. Обе записки
читались как живой фронт работ, и ни одна не была таковым.

Почему сторож, а не дисциплина. Правило «закрыл чужой пункт — обнови чужую
записку» уже существует (§18, §22) и за два месяца нарушено четырежды. Молчание
git его не ловит по построению: звонок измеряет ДАТУ последнего коммита нити, а
не правдивость её текста. Сторож закрывает ровно тот зазор.

ГРАНИЦА, названная вслух. Он проверяет НЕ «правдива ли записка», а два
машинно-сопоставимых противоречия:

1. записка говорит «не начат(о)» про файл плана, в котором есть отметка о
   закрытии хотя бы одного шага;
2. статус нити в её `LATEST.md` расходится со статусом в `INDEX.md` — два дома
   одного факта.

Всё остальное (устаревший якорь, снятая развилка, пункт, закрытый без следа в
плане) он не видит и видеть не может. Ратчет покрытия держит второе: если
переписать записку так, что статус перестанет распознаваться, сторож обязан
покраснеть, а не молча сократить периметр.
"""
from __future__ import annotations

import pathlib
import re

import pytest

pytestmark = pytest.mark.consistency

ROOT = pathlib.Path(__file__).resolve().parents[2]
HANDOFF = ROOT / "docs" / "handoff"
INDEX = HANDOFF / "INDEX.md"

# ПОКРЫТИЕ ОБЪЯВЛЕНО СПИСКОМ, А НЕ ЧИСЛОМ (16.09). До этого здесь стоял ратчет
# «распознано не меньше 38», и он терпел молчаливую дыру: записок 49, распознанных
# 47 — то есть две могли годами быть невидимы сторожу, а его молчание читалось как
# «расхождений нет». Именно так и было: `diagnosis-hardcode` и `fdr-online` писали
# статус в форме «Статус: **`closed`**», где между словом и значением ПЯТЬ
# не-словесных символов, а регулярка допускала четыре.
# Теперь: статус обязан распознаться у КАЖДОЙ записки; законное исключение
# объявляется здесь ПОИМЁННО и с причиной. Пустой словарь = исключений нет.
STATUS_EXEMPT: dict[str, str] = {}

_STATUS = re.compile(r"[Сс]тату[сc]\W{0,4}(closed|paused|open|active|blocked)", re.IGNORECASE)
_NOT_STARTED = re.compile(r"не\s+начат", re.IGNORECASE)
_PLAN_REF = re.compile(r"(plans/[A-Za-z0-9_\-.]+\.md)")
# Отметка закрытия шага в плане: галочка или слово в верхнем регистре рядом с ним.
_STEP_CLOSED = re.compile(r"(✅|ЗАКРЫТ|закрыт\b|ИСПОЛНЕН|готово\b)", re.IGNORECASE)


def _latest_files() -> list[pathlib.Path]:
    return sorted(HANDOFF.glob("*/LATEST.md"))


def _status_of(text: str) -> str | None:
    """Статус записки — по СОДЕРЖАНИЮ, а не по разметке вокруг него.

    Markdown-шум (`*`, `` ` ``, `_`) снимается ДО сопоставления. Считать его
    «не-словесными символами» и подбирать им допуск — это гонка за формами:
    `статус: closed`, `Статус:** closed`, «Статус: **`closed`**» отличаются только
    украшением, и каждая новая форма молча выводила бы записку из-под сторожа.
    """
    очищенный = re.sub(r"[*`_]+", "", text)
    m = _STATUS.search(очищенный)
    return m.group(1).lower() if m else None


def _index_statuses() -> dict[str, str]:
    """slug → статус из последней колонки таблицы INDEX.md."""
    out = {}
    for line in INDEX.read_text(encoding="utf-8").splitlines():
        if not line.startswith("|"):
            continue
        cells = [c.strip() for c in line.strip("|").split("|")]
        if len(cells) < 2:
            continue
        slug = cells[0].strip("` ")
        st = cells[-1].strip("` *").lower()
        if slug and st in ("closed", "paused", "open", "active", "blocked"):
            out[slug] = st
    return out


def test_note_does_not_call_a_finished_plan_unstarted():
    """⭐ «Не начат» про план, в котором шаги уже закрыты, — ложный фронт работ."""
    bad = []
    for f in _latest_files():
        text = f.read_text(encoding="utf-8")
        if not _NOT_STARTED.search(text):
            continue
        for rel in set(_PLAN_REF.findall(text)):
            plan = ROOT / rel
            if not plan.exists():
                continue
            head = "\n".join(plan.read_text(encoding="utf-8").splitlines()[:60])
            if _STEP_CLOSED.search(head):
                bad.append(f"{f.parent.name} → {rel}")
    assert not bad, (
        "записка нити зовёт к работе, которая по своему же плану закрыта — "
        "обнови записку или объясни расхождение в ней самой: " + str(sorted(bad)))


@pytest.mark.owner_data
def test_thread_status_has_one_home():
    """Статус нити в LATEST.md и в INDEX.md — один факт; расхождение = split-brain."""
    idx = _index_statuses()
    mismatched = []
    for f in _latest_files():
        slug = f.parent.name
        mine = _status_of(f.read_text(encoding="utf-8"))
        theirs = idx.get(slug)
        if mine and theirs and mine != theirs:
            mismatched.append(f"{slug}: LATEST={mine} ≠ INDEX={theirs}")
    assert not mismatched, (
        "два дома статуса нити разошлись — читатель INDEX и читатель записки "
        "увидят разное: " + str(sorted(mismatched)))


def unjudged(notes: dict[str, str], exempt: dict) -> list[str]:
    """Чистое ядро: записки, чей статус не распознан и не объявлен исключением."""
    return sorted(slug for slug, text in notes.items()
                  if not _status_of(text) and slug not in exempt)


def test_every_note_is_judged_or_exempt_by_name():
    """Непрочитанная записка называется ПОИМЁННО, а не растворяется в числе.

    Прежняя редакция держала ратчет «распознано ≥ 38» при 49 записках: одиннадцать
    могли выпасть из-под надзора, и его молчание читалось как «расхождений нет».
    Замер 16.09 показал, что дыра не гипотетическая — две записки
    (`diagnosis-hardcode`, `fdr-online`) писали статус в форме «Статус: **`closed`**»
    и не распознавались. Теперь периметр — это СПИСОК: судятся все, исключение
    объявляется поимённо с причиной.
    """
    невидимые = unjudged({f.parent.name: f.read_text(encoding="utf-8")
                          for f in _latest_files()}, STATUS_EXEMPT)
    assert not невидимые, (
        f"статус не распознан у записок: {sorted(невидимые)}. Сторож их не судит, "
        f"и его молчание про них означает «не знаю», а не «расхождений нет». "
        f"Либо поправь форму статуса в записке, либо внеси слаг в STATUS_EXEMPT "
        f"С ПРИЧИНОЙ — но не оставляй молча.")


def exempt_problems(mapping: dict) -> list[str]:
    """Чистое ядро: слаги, объявленные исключением БЕЗ причины."""
    return sorted(slug for slug, причина in mapping.items() if not (причина or "").strip())


def test_exempt_list_carries_a_reason():
    """Исключение без причины — тихое сужение периметра, оформленное как решение."""
    assert not exempt_problems(STATUS_EXEMPT), (
        f"в STATUS_EXEMPT есть слаги без причины: {exempt_problems(STATUS_EXEMPT)}")


def test_exempt_predicate_is_not_blind():
    """Негативный контроль: предикат обязан НАХОДИТЬ пустую причину.

    Сегодня STATUS_EXEMPT пуст, поэтому тест выше зелёный при ЛЮБОМ предикате —
    «нарушений ноль» неотличимо от «осмотрено ноль». Урок соседней нити
    (`closing-condition`), и он стоил ей отдельной находки: проверяется предикат
    на рукодельном входе, а не состояние данных.
    """
    assert exempt_problems({"нить-без-причины": "", "вторая": "   "}) == [
        "вторая", "нить-без-причины"]
    assert exempt_problems({"нить": "причина названа"}) == []


def test_unjudged_predicate_is_not_blind():
    """⭐ НЕГАТИВНЫЙ КОНТРОЛЬ, и он появился здесь не от аккуратности.

    Первая редакция проверки покрытия судила СОСТОЯНИЕ ДАННЫХ («невидимых записок
    нет»), а невидимых после починки распознавания стало ноль. Мутация «считать
    любую невидимую записку законной» её НЕ уронила: зелёный означал «осмотрено
    ноль», а не «нарушений ноль». Поймано собственным прогоном мутаций 16.09 —
    ровно тот класс, который эта же нить неделю назад нашла у соседа.

    Поэтому предикат проверяется на рукодельном входе, где невидимая записка есть.
    """
    notes = {
        "с-статусом": "# LATEST\n\n- Статус: **`closed`** — всё сделано\n",
        "без-статуса": "# LATEST\n\nпросто текст без слова о состоянии нити\n",
        "объявлена-исключением": "# LATEST\n\nтоже без статуса\n",
    }
    exempt = {"объявлена-исключением": "черновик чужой нити, статуса ещё нет"}
    assert unjudged(notes, exempt) == ["без-статуса"], (
        "предикат покрытия слеп: он не находит записку без статуса")


def test_status_is_read_through_markdown_decoration():
    """Форма записи не должна выводить записку из-под сторожа.

    Три формы встречаются в живых записках одновременно; «Статус: **`closed`**»
    (пять не-словесных символов между словом и значением) не распознавалась прежней
    регуляркой, и две нити были невидимы. Позитив на каждую форму.
    """
    формы = {
        "статус: closed": "closed",
        "Статус:** closed": "closed",
        "- Статус: **`closed`** — the-end 2026-07-18": "closed",
        "статус **paused**": "paused",
        "· статус: `open`": "open",
    }
    for строка, ожидание in формы.items():
        assert _status_of(f"# LATEST\n\n{строка}\n") == ожидание, (
            f"форма {строка!r} не распознана — записка выпала бы из-под надзора")
