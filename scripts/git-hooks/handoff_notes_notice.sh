#!/bin/bash
# handoff_notes_notice.sh — доставка записок соседних нитей при коммите.
#
# ЗАЧЕМ. Замерено 13.09.2026: `docs/handoff/` не назван в read-first НИ В ОДНОМ
# из двух сводов — ни в §B health_scripts, ни в ХУК #1 соседнего проекта (грепом ноль
# упоминаний). Значит записка, оставленная одной сессией для другой,
# доставлялась привычкой читателя, а не механизмом. Цена промаха измерена в тот
# же день: две сессии написали ОДИН модуль на 167 строк под одни шесть строк БД,
# потому что каждая не знала про вторую.
#
# ПОЧЕМУ ЭТО ЗОВЁТ pre-commit. Инструментального канала между задачами Cowork
# нет — `ListAgents` пуст, проверено обеими сторонами независимо. Общий
# репозиторий единственный канал, а pre-commit — единственное место, которое
# прошёл КАЖДЫЙ коммит: 84 за неделю, шесть сессий, все до одной.
#
# ПОЧЕМУ ОТДЕЛЬНЫЙ ФАЙЛ. Блок жил дословной копией в двух хуках двух
# репозиториев. Копии разошлись бы молча и именно в опасную сторону:
# `core.quotepath=false` — уже найденная правка, и применить её к одной копии,
# забыв вторую, значило бы потерять доставку кириллических нитей, не узнав об
# этом. Дом один, зовут двое.
#
# WARN, НЕ БЛОК: непрочитанная записка — не вина этого коммита, а блокирующий
# датчик из-за чужой работы выучат обходить (§13). Выход всегда 0.
#
# ── ПЕРЕСБОРКА 14.09 ПО ВНЕШНЕМУ РЕВЬЮ: две правки, обе по замеру ────────────
#
# (1) ЧИТАЕМ ВСЕ РЕПЛИКИ, А НЕ СВОЮ. `git log` без ревизий обходит HEAD, а в
# дереве нити HEAD — это ветка нити. Записка, закоммиченная соседом на ЕГО
# ветке, не доходила ни до кого: ревьюер воспроизвёл это двумя параллельными
# нитями. Формально конструкция была кворумом без перекрытия: читали одну
# реплику (NR=1) при записи в свою и только свою (Nw=1), а реплик три
# (главная копия плюс два живых дерева) — NR+Nw > N не выполнялось, значит
# пропуск записи следовал из устройства, а не из невезения. Лечение прямое:
# опрашиваем ВСЕ реплики, список которых отдаёт сам git.
# Горькая ирония замера: чем строже соблюдают §21 (нить в своём дереве), тем
# меньше работала доставка — две половины подсистемы гасили друг друга.
#
# (2) ПЕЧАТАЕМ ДЕЛЬТУ, А НЕ СОСТОЯНИЕ. Замер 13-14.09: список печатался 51 и 43
# раза в сутки, а менялся 12 и 12 — то есть три четверти печатей не несли ни
# одной новости, и длина списка росла (8 нитей утром, 12 к полудню при 42
# каталогах). Порог «не длиннее N» был отвергнут: N — литерал, выбранный из
# головы, и он лечит симптом. Дискриминатор не длина, а НОВИЗНА для этого
# читателя. Ключ — путь ПЛЮС последний коммит, который его тронул: иначе
# повторная правка той же записки была бы принята за уже прочитанную.
# Отметка лежит в служебном каталоге ДЕРЕВА (`git rev-parse --git-dir`), не в
# репозитории: не коммитится, не делится, умирает вместе с деревом, а §21
# делает «одно дерево ≈ одна сессия».
# ГРАНИЦА ВСЛУХ: у главной копии служебный каталог общий, поэтому две сессии,
# работающие обе в main, гасят отметку друг другу. Лечения без идентичности
# сессии у этого предела нет, и выдумывать его здесь нечем.
#
# core.quotepath=false обязателен, а не косметика: без него git ЭКРАНИРУЕТ
# не-ASCII пути, строка перестаёт заканчиваться на LATEST.md, и фильтр её молча
# теряет. Найдено оракулом при первом же прогоне, а не чтением.
#
# Оракул: tests/unit/test_handoff_note_delivery.py (health_scripts) исполняет
# ЭТОТ файл в одноразовых репозиториях. У зовущих репозиториев свои оракулы на
# сам вызов.
set -uo pipefail

# ── ОДНО СОБЫТИЕ: post-commit (15.09, после двух заходов) ───────────────────
#
# ЧТО БЫЛО. 14.09 печать и отметка стояли в pre-commit. Обычный `git commit`
# без -m, выход из редактора без сообщения — коммит отменён, отметка записана,
# записка соседа не покажется больше НИКОГДА. Регрессию внесла правка «печатать
# дельту»: до неё список печатался каждый раз и отменённая попытка ничего не
# теряла. Внешнее ревью это нашло.
#
# ПЕРВАЯ ПОЧИНКА БЫЛА СЛОЖНЕЕ НУЖНОГО. Я развёл печать (pre-commit) и зачёт
# (post-commit) через файл `.pending`. Оракул на `--no-verify` показал дыру,
# которую эта конструкция создаёт своим существованием: `--no-verify` пропускает
# pre-commit, но НЕ post-commit, поэтому `.pending`, оставленный отменённой
# попыткой, засчитывался коммитом, который записку не печатал. Чинить это
# значило бы связывать два хука общим идентификатором попытки — которого git не
# даёт.
#
# ПОЧЕМУ ОДИН ХУК ПРАВИЛЬНЕЕ ДВУХ. Замерено (git 2.54): post-commit печатает
# видимо и срабатывает РОВНО на состоявшихся коммитах — включая `--no-verify`,
# включая `--amend`. То есть событие «коммит случился» у git уже есть, отдельно
# собирать его из двух половин не нужно. Печать и отметка снова стоят рядом,
# одной операцией: показать нечего — нечего и засчитывать, коммита нет —
# ни печати, ни отметки. Отменённая попытка не доходит сюда вовсе.
#
# ЦЕНА, НАЗВАННАЯ ВСЛУХ. Записка приходит ПОСЛЕ коммита, а не перед. Для WARN
# (§13: блокирующий датчик из-за чужой работы выучат обходить) это ровно тот же
# момент по смыслу. И: merge/rebase/cherry-pick post-commit НЕ зовут — записка
# там не теряется, а доживает до следующего обычного коммита.
#
# Имена переменных ЛАТИНИЦЕЙ: bash не принимает не-ASCII идентификаторы
# (корпус C-40; наступил на это третий раз за сутки — правило в корпусе
# не удержало, удержал оракул).
_SEEN_DIR="$(git rev-parse --git-dir 2>/dev/null)"

# Все реплики: ветки всех рабочих деревьев плюс текущий HEAD. Отсоединённое
# дерево ветки не имеет — берём его HEAD по sha.
_REFS=()
while IFS= read -r _L; do
    case "$_L" in
        branch\ *) _REFS+=("${_L#branch }") ;;
        HEAD\ *)   _LAST_SHA="${_L#HEAD }" ;;
        worktree\ *) _LAST_SHA="" ;;
        "") [[ -n "${_LAST_SHA:-}" ]] && _REFS+=("$_LAST_SHA"); _LAST_SHA="" ;;
    esac
done < <(git worktree list --porcelain 2>/dev/null; echo "")
[[ ${#_REFS[@]} -eq 0 ]] && _REFS=(HEAD)

# ── ДВА АДРЕСА, А НЕ ОДИН (16.09) ────────────────────────────────────────────
# Записка соседа теперь кладётся в `docs/handoff/<нить>/inbox/<отправитель>.md`,
# а не в тело чужого LATEST.md. Причина измерена, а не выведена: за 30 дней до
# 16.09 закрытий нитей было 21, из них 5 упёрлись в настоящий конфликт, и в
# ДВУХ из пяти конфликтовал ровно чужой LATEST — одна сторона автор нити,
# переписывающий свой снимок, вторая сосед с запиской (a40ebde: error-channel
# против agent-coordination; a5efde1: night-cycle против brief+handoff), 30 и
# 45 строк ручного разбора. Экспозиция: 74 правки LATEST за месяц, 15 чужой
# рукой. Это write-write конфликт, и он исчезает не разрешателем, а единственным
# владельцем файла: у LATEST остаётся один писатель — автор нити.
# СТАРЫЙ АДРЕС ПРОДОЛЖАЕТ ДОСТАВЛЯТЬСЯ: записка в теле LATEST печатается как
# прежде. Иначе переход стоил бы ровно того, против чего вся подсистема —
# молчания канала.
_PATHS=$(git -c core.quotepath=false log --since="48 hours ago" \
    --name-only --format="" "${_REFS[@]}" \
    -- 'docs/handoff/*/LATEST.md' 'docs/handoff/*/inbox/*' 2>/dev/null \
    | grep -E 'docs/handoff/[^/]+/(LATEST\.md|inbox/.+)$' | sort -u)

# Ключ новизны: путь + последний тронувший его коммит.
_KEYS=""
while IFS= read -r _P; do
    [[ -n "$_P" ]] || continue
    _SHA=$(git -c core.quotepath=false log -1 --format='%h' "${_REFS[@]}" -- "$_P" 2>/dev/null)
    _KEYS="${_KEYS}${_P} ${_SHA}"$'\n'
done <<< "$_PATHS"

_SEEN="${_SEEN_DIR}/handoff_seen"
_NEW=""
while IFS= read -r _K; do
    [[ -n "$_K" ]] || continue
    if [[ ! -f "$_SEEN" ]] || ! grep -qxF "$_K" "$_SEEN" 2>/dev/null; then
        _NEW="${_NEW}${_K%% *}"$'\n'
    fi
done <<< "$_KEYS"

if [[ -n "${_NEW//[$'\n' ]/}" ]]; then
    echo ""
    echo "📬 НОВЫЕ ЗАПИСКИ НИТЕЙ (с твоего прошлого коммита):"
    # Печатаем ПУТЬ записки из inbox целиком, а не только имя нити: адресату
    # нужно знать, КТО написал, чтобы ответить в его inbox, а не в общий файл.
    echo "$_NEW" \
        | sed 's|^docs/handoff/||; s|/inbox/\(.*\)\.md$|  ← записка от: \1|; s|/inbox/\(.*\)$|  ← записка от: \1|; s|/LATEST.md$||' \
        | sed '/^$/d' | sed 's/^/     /'
    echo "     Записка соседа: docs/handoff/<нить>/inbox/<отправитель>.md"
    echo "     Свой снимок:    docs/handoff/<нить>/LATEST.md (читай ХВОСТ)"
    echo "     Записка может лежать на ВЕТКЕ соседа — тогда:"
    echo "       git show <ветка>:docs/handoff/<нить>/inbox/<отправитель>.md"
    echo "     Отвечай в inbox адресата (файл со СВОИМ именем — у LATEST один"
    echo "     писатель, его автор) и перечнем ФАЙЛОВ, а не именем нити —"
    echo "     сталкиваются файлы (docs/how-to/thread_worktree.md)."
fi

# Отметку пишем ВСЕГДА, включая пустой список: иначе «прочитано» не имеет
# писателя и первая же записка печаталась бы вечно.
#
# Пишем ЧЕРЕЗ ВРЕМЕННЫЙ ФАЙЛ И mv. Обрыв посреди `>` оставил бы обрезанный
# список: часть записок молча стала бы «непрочитанной» навсегда — то есть
# вернулся бы шум, ради устранения которого дельта и сделана. mv в пределах
# одного каталога атомарен.
#
# Отказ записи называем вслух ОДИН раз: молча выключенная дельта возвращает
# ровно тот шум, ради которого она сделана (F8 внешнего ревью).
if [[ -n "$_SEEN_DIR" ]]; then
    if ! { printf '%s' "$_KEYS" > "${_SEEN}.tmp$$" 2>/dev/null \
           && mv -f "${_SEEN}.tmp$$" "$_SEEN" 2>/dev/null; }; then
        rm -f "${_SEEN}.tmp$$" 2>/dev/null
        echo "⚠️  записки: не могу записать ${_SEEN} — дельта выключена," >&2
        echo "     список будет печататься целиком, пока каталог не станет записываемым." >&2
    fi
fi

exit 0
