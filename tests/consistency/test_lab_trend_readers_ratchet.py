def _census(root: pathlib.Path) -> set[str]:
    out = set()
    for p in sorted(root.rglob("*.py")):
        rel = p.relative_to(root)
        if any(part in _SKIP for part in rel.parts):
            continue
        src = p.read_text(errors="ignore")
        if "lab_results" in src and re.search(r"test_name", src):
            out.add(str(rel))
    return out


def test_no_new_reader_bypasses_the_mapping():
    root = pathlib.Path(__file__).resolve().parents[2]
    got = _census(root)
    new = got - KNOWN_NAME_READERS
    gone = KNOWN_NAME_READERS - got
    assert not new, (
        "Новый читатель анализов по НАШЕМУ имени, мимо lab_name_loinc: "
        + ", ".join(sorted(new))
        + ".\nРеши одно из двух: (1) читать через labs_db.get_lab_trend_by_component "
          "— тогда тренд собирается по веществу, а не по написанию; (2) если имя "
          "здесь уместно (запись, триаж, свежесть — не тренд), впиши файл в "
          "KNOWN_NAME_READERS этим же коммитом. Список — не формальность: он и есть "
          "мера того, насколько дом имени ещё не единственный."
    )
    assert not gone, (
        "Из переписи исчезли: " + ", ".join(sorted(gone))
        + ". Если модуль перешёл на отображение — вычеркни строку здесь, и это "
          "хорошая новость. Если файл переименован — впиши новое имя."
    )
