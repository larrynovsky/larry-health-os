# `lab_results` и `specialized_lab_results` — два дома одного измерения. Граница
# объявлена в docstring обоих писателей (`lab_promote`: «только кровь идёт в
# lab_results») и до сегодняшнего дня не стереглась НИЧЕМ: константа `BLOOD`
# в промоуте определена и не использована ни разу. Оба предиката ниже чистые —
# вход два списка словарей, БД не трогают, поэтому проверяемы без неё.
#
# Ключ границы обязан нести материал: иначе разные образцы с одной датой
# и именем ошибочно считаются конфликтующими значениями одного измерения.


def _boundary_names(spec_row: dict) -> set:
    """Имена спец-строки в ТРЁХ формах — сырой, канонической и вычисленной.

    Канонизация спец-слоя может быть частичной. Сравнение только сырого имени
    с test_name пропустит совпадение разных написаний. Поэтому проверяются
    сырой, сохранённый канонический и вычисленный нормализацией варианты.
    Иначе датчик границы может сообщить об отсутствии пересечений,
    когда совпадения скрыты несовместимыми формами имени.

    Гомоглифы — часть той же слепоты и лечатся тем же вызовом: «Е210» кириллицей
    против «E210» латиницей сводит `normalize`, прямое сравнение строк — нет.

    `normalize` зовётся, а не копируется: сведение имени к канону имеет ОДИН дом,
    и второй развёлся бы с ним молча.
    """
    out = set()
    for k in ("analyte_raw", "analyte_canonical"):
        v = (spec_row.get(k) or "").strip()
        if v:
            out.add(v)
    return out | {normalize(v) for v in out if v}


def domain_boundary_violations(canon_rows: list, spec_rows: list) -> list:
    """Строки, лежащие в ОБОИХ домах одновременно. Пусто = граница цела.

    canon_rows: словари с `date` · `source` · `specimen` · `test_name`.
    spec_rows:  словари с `date` · `source` · `specimen` · `analyte_raw` ·
                `analyte_canonical` · `panel_type`.

    Ключ — (дата, источник, МАТЕРИАЛ, имя). Материал в ключе обязателен, см.
    шапку раздела. Возврат отсортирован, чтобы диф двух прогонов читался.
    """
    index = {}
    for r in canon_rows:
        key = ((r.get("date") or ""), (r.get("source") or ""),
               (r.get("specimen") or ""), (r.get("test_name") or "").strip())
        index.setdefault(key, []).append(r)
    out = []
    for s in spec_rows:
        base = ((s.get("date") or ""), (s.get("source") or ""),
                (s.get("specimen") or ""))
        hit = None
        for name in _boundary_names(s):
            for c in index.get(base + (name,), []):
                # ADR (имя+материал+размерность): фракция Albumin в «%» и
                # биохимический Albumin г/дл — РАЗНЫЕ измерения; флаг «два дома»
                # на них ложный (замер 2026-08-13). Несовместимость доказывается
                # только вынесенными решениями identity_name по ОБЕИМ единицам;
                # незнание единиц оставляет прежнее поведение — датчик не имеет
                # права ослепнуть от пустой колонки unit.
                if _dimension_incompatible(name, s.get("unit"), c.get("unit")):
                    continue
                hit = name
                break
            if hit:
                out.append({"date": base[0], "source": base[1],
                            "specimen": base[2], "name": hit,
                            "panel_type": s.get("panel_type")})
                break          # одна спец-строка = одно нарушение, не два имени
    return sorted(out, key=lambda d: (d["panel_type"] or "", d["date"], d["name"]))


def _dimension_incompatible(name: str, spec_unit, canon_unit) -> bool:
    """Размерности двух строк ДОКАЗУЕМО разводят одно имя на разные измерения.

    Один дом правила — identity_name (ADR adr_analyte_identity_lives_in_name);
    здесь оно применяется к обеим сторонам границы. True только когда обе единицы
    названы и идентичность даёт РАЗНЫЕ ответы (включая «не берусь судить» против
    решённого — голый % на не-процентном аналите). Любое незнание → False:
    прежнее слепое к единицам поведение сохраняется, иначе датчик, нашедший 116
    нарушений после лечения слепоты имён, ослеп бы от разнобоя написаний единиц."""
    if not (spec_unit or "").strip() or not (canon_unit or "").strip():
        return False
    nm = normalize(name or "")
    if nm not in CANONICALS:
        return False
    return identity_name(nm, spec_unit) != identity_name(nm, canon_unit)


def same_measurement_two_dates(canon_rows: list, spec_rows: list) -> list:
    """Одно измерение (источник, материал, имя) под РАЗНЫМИ датами в двух домах.

    Оракул вердикта владельца 4 (2026-07-31). Ловит не гипотетическую проблему,
    а измеренную: `specialized_lab_results` — застывший снимок staging, автосинка
    у него нет, и правка дат в staging оставляет слой позади МОЛЧА. 31.07 это уже
    случилось — слой наполнен в 09:50, миграция дат легла в 17:33.

    Дата здесь — предмет, а не часть ключа: в `domain_boundary_violations` она в
    ключе и потому этот класс скрывает. Два предиката, два вопроса.
    """
    index = {}
    for r in canon_rows:
        key = ((r.get("source") or ""), (r.get("specimen") or ""),
               (r.get("test_name") or "").strip())
        index.setdefault(key, set()).add(r.get("date") or "")
    out = []
    for s in spec_rows:
        sdate = s.get("date") or ""
        base = ((s.get("source") or ""), (s.get("specimen") or ""))
        for name in _boundary_names(s):
            dates = index.get(base + (name,))
            if dates and sdate not in dates:
                out.append({"source": base[0], "specimen": base[1], "name": name,
                            "date_specialized": sdate,
                            "dates_canon": sorted(dates),
                            "panel_type": s.get("panel_type")})
                break
    return sorted(out, key=lambda d: (d["panel_type"] or "", d["name"]))


# ── Материал и класс строки: общий предок двух писателей (работа B, 2026-08-01) ─
