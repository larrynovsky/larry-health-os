"""Материал биопробы и роль страницы — из САМОГО бланка, а не из названия панели.

Публичный вход один: `page_facts(pdf_path)` → {страница: {specimen, specimen_source,
role}}. Модуль НИЧЕГО не классифицирует: он отдаёт сырую строку из документа
(«Кровь с ЭДТА», «мазке из зева», «Serum»). Сведение сырой строки к классу
(blood/urine/…) живёт в `lab_promote._specimen` и остаётся там — второй дом
материала завёл бы ровно то расхождение, которое эта нить лечила у имени аналита.

ПОЧЕМУ модуль появился (замер 2026-07-31 по бланку ДНКОМ, 70 стр.):
шапка «Биоматериал:» стоит на 40 страницах из 70; прежнее правило наследовало её
безусловно и приписывало материал соседней, ПОСТОРОННЕЙ заявки. 143 строки отчёта
«маркеры микроорганизмов в мазке из зева» (стр. 64–66) получали «Кровь с ЭДТА» от
микроэлементов со стр. 63. Материал не измерялся, а назначался.

ЛЕСТНИЦА (первая сработавшая ступень выигрывает, ступень записывается в строку):
  read_header   — на странице своя шапка «Биоматериал: X» / «Sample type: X»;
  read_footer   — подвал отчёта другой вёрстки называет материал сам
                  («Анализ микробиоты … микробных маркеров в крови / в мазке из зева»);
  continuation  — страница объявляет себя продолжением ТОЙ ЖЕ заявки, что и
                  последняя страница со своей шапкой (номер заявки сверяется);
  unknown       — материала в бланке нет. Это законный ответ. Прежнее правило
                  вместо него отвечало «как у соседа».

РОЛЬ СТРАНИЦЫ — отдельный вопрос от материала. График может показывать
производную исходных значений или повторять таблицу в другой форме.
Чтение высоты столбика не заменяет исходного числа. Такие страницы
не импортируются как самостоятельные измерения.

Подписи диаграмм — это ВЁРСТКА бланка (§9, закрытый список п. 3 «структура/
представление»), не клиническое знание: они не дрейфуют по возрасту, состоянию
или методологии. Тот же приём и по той же причине уже применён в
`lab_specialized._NAME_OVERRIDE`. В `doc_patterns` им не место: там тип ДОКУМЕНТА,
а здесь роль СТРАНИЦЫ внутри документа — другой предмет.
"""
from __future__ import annotations

import re

# Ступень 1: страница называет материал своей шапкой.
_HEADER = (
    re.compile(r"Биоматериал\s*:\s*([^\n;]+)"),
    re.compile(r"Sample\s*(?:type|material)\s*:\s*([^\n;]+)", re.I),
)
# Ступень 2: подвал отчёта другой вёрстки называет материал сам.
_FOOTER = (
    re.compile(r"маркеров\s+в\s+([^\n.]{2,40})", re.I),
)
# Ступень 3: страница-продолжение и номер заявки, с которым сверяем.
_ORDER = re.compile(r"Заявка\s*№\s*:?\s*(\d+)")
_CONT = re.compile(r"продолжение,\s*стр\.?\s*\d+\s*из\s*\d+")

# Дата взятия отличается от даты выполнения. Результаты одной пробы
# могут дописываться в разные дни; тренд должен отражать забор, а не расписание.
_TAKEN = re.compile(r"Взятие\s+биоматериала\s*:\s*(\d{2})\.(\d{2})\.(\d{4})")

# Роль страницы: подпись графики. Ключ — то, что на странице напечатано.
_DERIVED_CHART = (
    re.compile(r"Диаграмма\s+дисбиоза", re.I),
    re.compile(r"Индивидуальные\s+профили\s+иммунореактивности", re.I),
)

# СТРАНИЦА-ТЕКСТ: врачебный комментарий или сводка имён без значений. Найдено
# 2026-07-31 ГЛАЗАМИ по требованию владельца «посмотри бланк» — в текстовом слое
# такая страница выглядит как обычные строки и потому прошла мимо всех проверок.
#   «Комментарии к пробе:» — проза вида «Снижение количества <таксон>»,
#     «Выявлены <таксон> в количестве N». Распознаватель взял
#     из ПРЕДЛОЖЕНИЯ число и завёл аналит; фразы про снижение попали в
#     канон как имена показателей.
#   «Заключение по пробе:» — две колонки ИМЁН без значений вовсе.
# Ни одна из них не результат измерения, и обе не ловились правилом графики.
_NARRATIVE = (
    re.compile(r"Комментарии\s+к\s+пробе", re.I),
    re.compile(r"Заключение\s+по\s+пробе", re.I),
)

# НАЗВАНИЕ ИССЛЕДОВАНИЯ. Стоит на фиксированном месте вёрстки — между строкой
# «Взятие биоматериала» и шапкой таблицы «Показатель». Замер 2026-07-31: есть на
# 40 страницах из 70, 29 разных названий («Стероидный профиль (ЖХ-МС/МС)» на
# стр. 21 против «Андрогенный статус» на стр. 36 — один забор, один материал,
# одна дата, два прибора и два разных результата тестостерона).
_STUDY = re.compile(r"Взятие биоматериала:[^\n]*\n(.+?)\n\s*Показатель", re.S)

# Строки шапки и подвала — они не заголовки секций и не результаты.
_CHROME = re.compile(
    r"Заявка|Заказчик|Исполнитель|Ф\.И\.О|Фамилия|Дата рождения|"
    r"Регистрация биоматериала|Биоматериал|Взятие биоматериала|"
    r"Показатель|Результат|Референсные значения|Ед\. изм|"
    r"Исследования выполнены|Результаты одобрил|Дата выполнения|^Стр\.\s*\d+$|^\*\s")
# Число, интервал или цензурированное значение. Пробел внутри числа — не опечатка:
# бланк печатает разряды через пробел («50,0 - 4 600,0»), и без этого референс
# притворялся заголовком секции и уводил под себя соседний аналит.
_NUMLIKE = re.compile(r"^[<>≤≥]?\s*[-+]?[\d.,\s]+(-\s*[-+]?[\d.,\s]+)?$")

# Метод может быть указан в имени строки точнее, чем в общей секции.
# Поэтому имя проверяется до секции.
_METHOD_IN_NAME = (
    (re.compile(r"по\s+Фонио", re.I), "подсчёт по Фонио"),
    (re.compile(r"по\s+Вестергрену", re.I), "по Вестергрену"),
)

UNKNOWN = "unknown"


def page_texts(pdf_path) -> list[str]:
    """Текст страниц PDF, по одной строке списка на страницу.

    Стала публичной 2026-07-31 по факту, а не по вкусу: у неё появился ВТОРОЙ
    читатель снаружи — миграция метода открывает документ один раз и передаёт
    тексты и в `page_facts`, и в `method_facts`. Оставить имя приватным значило
    бы либо открывать один PDF дважды, либо объявить приватность, которую никто
    не соблюдает — а это уже было в этой нити с `lab_backfill._resolve`.
    """
    import fitz  # PyMuPDF — уже зависимость lab_recognizer, новой не добавляем
    doc = fitz.open(pdf_path)
    try:
        return [pg.get_text() for pg in doc]
    finally:
        doc.close()


# Алиас для прежних читателей: имя было приватным, и грепом по коду его могли
# звать. Снимать без переписи читателей нельзя — своё же правило, нарушенное
# в этой нити днём раньше.
_page_texts = page_texts


def page_facts(pdf_path, texts: list[str] | None = None) -> dict[int, dict]:
    """{номер страницы (с 1): {'specimen': сырая строка|None,
                               'specimen_source': read_header|read_footer|continuation|unknown,
                               'role': 'data'|'derived_chart'}}

    `texts` — сеам для теста: список текстов страниц вместо чтения PDF. Без него
    читается сам файл. Не-PDF вход сюда не приходит: у вызывающего есть суффикс.
    """
    texts = _page_texts(pdf_path) if texts is None else texts
    out: dict[int, dict] = {}
    last_header_specimen: str | None = None
    last_header_order: str | None = None
    last_header_taken: str | None = None
    last_taken_order: str | None = None

    for i, t in enumerate(texts, start=1):
        specimen, source = None, UNKNOWN

        for rx in _HEADER:
            m = rx.search(t)
            if m:
                specimen, source = m.group(1).strip(), "read_header"
                break

        if specimen is None:
            for rx in _FOOTER:
                m = rx.search(t)
                if m:
                    specimen, source = m.group(1).strip(), "read_footer"
                    break

        order = (_ORDER.search(t).group(1) if _ORDER.search(t) else None)

        # ДАТА ВЗЯТИЯ идёт той же лестницей и по той же причине: своя шапка
        # старше наследования, наследование — только внутри СВОЕЙ заявки.
        # Разводить два правила чтения одной шапки значило бы завести им шанс
        # разойтись; они читают один и тот же блок текста.
        mt = _TAKEN.search(t)
        taken = f"{mt.group(3)}-{mt.group(2)}-{mt.group(1)}" if mt else None
        taken_source = "read_header" if taken else UNKNOWN

        if source == "read_header":
            last_header_specimen, last_header_order = specimen, order
        elif specimen is None and _CONT.search(t) and order is not None \
                and order == last_header_order and last_header_specimen:
            # наследуем ТОЛЬКО внутри одной заявки: страница сама объявила себя
            # продолжением, и номер совпал. Иначе — unknown, а не «как у соседа».
            specimen, source = last_header_specimen, "continuation"

        if taken:
            last_header_taken, last_taken_order = taken, order
        elif order is not None and order == last_taken_order and last_header_taken:
            # Дата наследуется по НОМЕРУ ЗАЯВКИ, а не по признаку «продолжение»:
            # у бланка есть страницы своей заявки без слова «продолжение», и на
            # них дата взятия та же — забор был один. Материал так наследовать
            # нельзя (одна заявка = разные пробирки), а дата забора у заявки одна.
            taken, taken_source = last_header_taken, "same_order"

        role = "data"
        for rx in _DERIVED_CHART:
            if rx.search(t):
                role = "derived_chart"
                break
        else:
            for rx in _NARRATIVE:
                if rx.search(t):
                    role = "narrative"
                    break

        m = _STUDY.search(t)
        # ПЕРВАЯ строка блока, а не весь блок. Между «Взятие биоматериала» и
        # «Показатель» бланк печатает и название исследования, и первый подзаголовок
        # («ОБЩИЙ АНАЛИЗ КРОВИ» + «Эритроцитарные параметры»; «Иммунный статус» +
        # «Клеточный иммунитет»). Склеенное «A | B» было бы методом, которого в
        # бланке нет; подзаголовок остаётся секцией и достаётся строкам под ним.
        study = None
        if m:
            # …и не строка шапки. На части страниц между «Взятие биоматериала» и
            # «Показатель» вклинивается номер заявки, и без этой проверки методом
            # семи строк становилось «Заявка №: 1000000001».
            parts = [x.strip() for x in m.group(1).split("\n")
                     if x.strip() and not _CHROME.search(x.strip())]
            study = parts[0] if parts else None

        out[i] = {"specimen": specimen, "specimen_source": source, "role": role,
                  "study": study, "taken": taken, "taken_source": taken_source}
    return out


def heading_shaped(value: str) -> bool:
    """Похоже ли на НАЗВАНИЕ раздела: начинается с прописной буквы.

    Публично, потому что читателей двое: `sections` (не пускает мусор внутрь) и
    миграция чистки канона (убирает уже записанный). Один дом правила —
    иначе конвейер писал бы по одному условию, а чистка судила бы по другому,
    и разъехались бы они молча.
    """
    return bool(value[:1].isalpha() and value[:1].isupper())


def sections(text: str, known_names, known_units, known_values=None) -> list[tuple[int, str]]:
    """Заголовки секций страницы: [(номер строки, заголовок)] в порядке текста.

    Заголовок определяется НЕ по вёрстке, а по дополнению: секция — это строка,
    которая не является ни именем, ни единицей ни одной ИЗВЛЕЧЁННОЙ строки, не
    число и не шапка. Мы уже знаем, что извлекли; всё лишнее — заголовки. Это
    дешевле и честнее, чем угадывать шрифт и отступы, которых в текстовом слое
    нет.

    Заголовок отличается от обломка строки положением среди чисел:
    перед ним и после него не должно быть числа. Это защищает от принятия
    потерянного имени или единицы результата за заголовок секции.
    """
    lines = [x.strip() for x in (text or "").split("\n") if x.strip()]
    # Дополнение работает только на таблице результатов: проза и сноски
    # не должны превращаться в методы измерений.
    # Признак настоящей таблицы — её собственная шапка, напечатанная бланком.
    if not any(l.startswith("Показатель") for l in lines):
        return []
    names = {n for n in (known_names or ()) if n}
    units = {(u or "").strip() for u in (known_units or ())}
    # Текстовый результат тоже часть строки; числового фильтра недостаточно,
    # чтобы отличить его от заголовка.
    values = {(v or "").strip() for v in (known_values or ())}
    out = []
    for i, ln in enumerate(lines):
        if (ln in names or ln in units or ln in values
                or _NUMLIKE.match(ln) or _CHROME.search(ln)):
            continue
        # Заголовок не заканчивается двоеточием или запятой — так выглядит
        # оборванная прозаическая строка, а не название раздела.
        # Скобка на конце РАЗРЕШЕНА и это не мелочь: половина настоящих названий
        # ею и кончается («Микроэлементы (ИСП-МС)», «Витамины (ВЭЖХ-МС)»).
        # Мусор отличается НЕПАРНОЙ скобкой — «проводится лечащим врачом)»,
        # «2009/04551 от 23.03.2009)»: это хвост абзаца, разорванного вёрсткой.
        # Первая версия правила резала по любой скобке и убила бы «Стероидный
        # профиль (ЖХ-МС/МС)» — ровно тот заголовок, ради которого всё делалось.
        if ln.endswith((":", ",")) or len(ln) > 60:
            continue
        if ln.count(")") > ln.count("("):
            continue
        # ЗАГОЛОВОК — ЭТО НАЗВАНИЕ, а название бланк печатает с прописной.
        # Постраничный список values не охватывает значения с других страниц.
        # Проверка формы заголовка дополняет этот фильтр.
        # Правило узкое намеренно: настоящие методы, читаемые из ИМЕНИ строки
        # («по Вестергрену», «подсчёт по Фонио»), с прописной не начинаются — и
        # они сюда не попадают, у них своя ступень лестницы.
        if not heading_shaped(ln):
            continue
        nxt = lines[i + 1] if i + 1 < len(lines) else ""
        prv = lines[i - 1] if i else ""
        if _NUMLIKE.match(nxt) or _NUMLIKE.match(prv):
            continue
        out.append((i, ln))
    return out


def method_facts(text: str, rows: list[dict], study: str | None) -> dict:
    """{id строки: {'method': …, 'method_source': …}} — метод из САМОГО бланка.

    ЛЕСТНИЦА (первая сработавшая выигрывает, ступень записывается в строку):
      read_name    — метод напечатан в имени строки («Тромбоциты по Фонио»);
      read_section — ближайший заголовок секции выше строки («Микроскопическое
                     исследование», «Подсчет тромбоцитов по Фонио»);
      read_study   — название исследования страницы («Андрогенный статус»);
      unknown      — метода в бланке нет. Законный ответ, а не повод угадать.

    Имя приоритетнее секции: одна секция может содержать разные методы.
    Секция приоритетнее названия исследования: общий заголовок менее точен.

    Если имя не находится в текстовом слое дословно, ступень секции
    пропускается. Это сохраняет честную неопределённость вместо догадки
    о позиции строки, например при добавленной распознавателем единице.
    """
    lines = [x.strip() for x in (text or "").split("\n") if x.strip()]
    pos = {}
    for i, ln in enumerate(lines):
        pos.setdefault(ln, i)
    # Название исследования — тоже строка-не-строка, и в кандидаты секций оно
    # попадает. Исключаем: иначе ступень `read_study` не наступила бы НИКОГДА, и
    # провенанс врал бы про то, откуда взят метод, оставаясь верным по значению.
    heads = [(i, h) for i, h in sections(text, [r.get("raw_name") for r in rows],
                                         [r.get("unit") for r in rows],
                                         [r.get("value_text") for r in rows])
             if h != (study or "")]
    out = {}
    for r in rows:
        name = (r.get("raw_name") or "").strip()
        method, src = None, UNKNOWN

        for rx, label in _METHOD_IN_NAME:
            if rx.search(name):
                method, src = label, "read_name"
                break

        if method is None:
            i = pos.get(name)
            if i is not None:
                above = [h for j, h in heads if j < i]
                if above:
                    method, src = above[-1], "read_section"

        if method is None and study:
            method, src = study, "read_study"

        out[r["id"]] = {"method": method, "method_source": src}
    return out
