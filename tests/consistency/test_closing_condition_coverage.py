"""У открытого обещания есть записанное УСЛОВИЕ ЗАКРЫТИЯ (решение владельца 15.09).

ЗАЧЕМ ЭТОТ ФАЙЛ. Замер 15.09: 22 инварианта со статусом не-holds, у четырёх есть проба,
у НУЛЯ — условие закрытия. Значит единственный механизм закрыть открытое обещание —
что кто-то про него вспомнит и спросит владельца. Двадцать два таких вопроса владелец
поштучно не рассудит и сам об этом сказал. Условие закрытия переносит его суждение с
«закрываем ли это» на «что считается доказательством» — один раз на обещание, а не
каждый раз при встрече.

ЧТО ИМЕННО СТЕРЕЖЁТСЯ, тремя разными вопросами:
  1. охват — у каждого не-holds есть непустое `closes_when`;
  2. форма — условие говорит, что должно стать ПРАВДОЙ, а не КОГДА вернуться. Календарный
     срок запрещён по замеру 14.09: «год тишины» ничего не измерял и создавал иллюзию,
     что через год будет ответ (BL-QUESTION-DISCARD-1, пункт 2);
  3. авторство — `closes_when_by` из закрытого списка. Условие, предложенное агентом, и
     критерий, названный владельцем, — разные вещи, и смешивать их значит отмывать
     авторство суждения.

ЧЕГО ЭТОТ ФАЙЛ НЕ ДЕЛАЕТ. Он не судит, ХОРОШЕЕ ли условие: это суждение человека, и
машинного оракула у него нет. Условие «закрывается, когда я так решу» пройдёт формально.
Защита тут не в гейте, а в том, что условие лежит в реестре и его видно.

УРОК ОХВАТА, взятый у соседа (`test_probe_coverage`): сторож, сообщающий «нарушений 0»,
неотличим от сторожа, осмотревшего 0 кандидатов. Поэтому число осмотренных проверяется
отдельным тестом с ратчетом — он покраснеет, если предикат вдруг перестанет находить
кандидатов.
"""
from __future__ import annotations

import re

import pytest

import intent_registry as ir

pytestmark = pytest.mark.consistency

# Ратчет ОХВАТА, не долга: столько не-holds инвариантов реестр содержал 15.09. Число
# может расти (новые честные «открыто» — норма) и может падать (обещание закрыли), но
# упасть РЕЗКО оно может только если сломался предикат. Нижняя граница ловит именно это.
RATCHET_OPEN_SEEN = 20

# Долг: сколько не-holds ЖИВЁТ без условия закрытия. На 15.09 заполнены все 22.
RATCHET_WITHOUT_CONDITION = 0

AUTHORS = {"claude", "owner"}

# Календарь в условии — запрещённая форма. Ловим и явную дату, и словесный срок.
_CALENDAR = re.compile(
    r"\b\d{4}-\d{2}-\d{2}\b"
    r"|\bчерез\s+\w+\s*(год|года|лет|месяц|месяца|месяцев|недел|дн)"
    r"|\b(ежегодно|раз в год|через год|спустя год)\b",
    re.IGNORECASE)


def _open_invariants() -> list[tuple[str, dict]]:
    out = []
    for entry in ir.load_registry():
        for inv in entry.get("invariants") or []:
            if (inv.get("status") or "holds") != "holds":
                out.append((entry["id"], inv))
    return out


def test_predicate_still_sees_candidates():
    """Сторож обязан сначала доказать, что ему есть на что смотреть.

    Без этого теста «нарушений 0» ниже читалось бы как успех и в том случае, когда
    `_open_invariants` перестал находить открытые обещания — например, после правки
    формата реестра. Ровно этот класс поймал сосед по каталогу в июле.
    """
    seen = len(_open_invariants())
    assert seen >= RATCHET_OPEN_SEEN, (
        f"открытых обещаний найдено {seen} при ратчете {RATCHET_OPEN_SEEN} — "
        f"скорее всего сломался предикат, а не закрылись 22 обещания разом")


def test_every_open_promise_declares_how_it_closes():
    """Охват: у каждого не-holds есть непустое условие закрытия."""
    missing = [f"{sub}::{inv['id']} ({inv.get('status')})"
               for sub, inv in _open_invariants()
               if not str(inv.get("closes_when") or "").strip()]
    assert len(missing) <= RATCHET_WITHOUT_CONDITION, (
        f"открытых обещаний без условия закрытия: {len(missing)} при ратчете "
        f"{RATCHET_WITHOUT_CONDITION}. Каждое такое обещание может закрыться только "
        f"вопросом владельцу, а он сказал, что поштучно их не рассудит. "
        f"Допиши `closes_when` либо осознанно подними ратчет с обоснованием: {missing}")


def test_condition_says_what_becomes_true_not_when_to_return():
    """Форма: условие — событие, а не календарь.

    Срок не измеряет ничего: через год владелец либо вспомнит, либо нет, и ни то ни
    другое не говорит, выполнено обещание или нет. Замер, из-за которого правило
    появилось, — снятый 14.09 срок «год тишины».
    """
    calendar = [(f"{sub}::{inv['id']}", str(inv.get("closes_when")))
                for sub, inv in _open_invariants()
                if _CALENDAR.search(str(inv.get("closes_when") or ""))]
    assert not calendar, (
        "условие закрытия названо КАЛЕНДАРЁМ, а не событием — срок не измеряет, "
        f"выполнено обещание или нет: {calendar}")


def test_authorship_of_the_criterion_is_declared():
    """Авторство: чей это критерий — предложение агента или слово владельца.

    Поле обязательно именно у тех, у кого есть условие: без него предложение агента
    через месяц читается как согласованный критерий, а это подмена того же класса, что
    «решено умолчанием» без автора.
    """
    bad = [(f"{sub}::{inv['id']}", inv.get("closes_when_by"))
           for sub, inv in _open_invariants()
           if str(inv.get("closes_when") or "").strip()
           and str(inv.get("closes_when_by") or "") not in AUTHORS]
    assert not bad, (
        f"у условия закрытия не объявлено авторство из {sorted(AUTHORS)}: {bad}")
