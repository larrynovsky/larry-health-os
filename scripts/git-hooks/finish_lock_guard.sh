#!/bin/bash
# Замок главной копии на время закрытия нити (2026-09-23, нить finish-lock).
#
# ЗАЧЕМ. Главная копия одна на все сессии, а закрытие нити меняет её отрезками:
# пробное слияние, настоящее слияние, коммиты журнала и якоря. 23.09 якорь
# закрытия first-miss лёг внутрь пробного слияния onboarding-launchd — и git
# сделал из него merge-коммит ЧУЖОЙ нити (d15f91d). Воспроизведено песочницей:
# tests/unit/test_thread_lifecycle.py::test_якорь_соседа_не_уносит_чужое_слияние
# (два окна — пробное и настоящее слияние; во втором чужой индекс уезжает в
# коммит с одним родителем, и это не было известно до замера).
#
# ОДИН ДОМ имени и пути замка — этот файл:
#   --path   → печатает путь файла замка (его берёт thread_finish.sh);
#   без арг. → суд для pre-commit: коммит в ГЛАВНОЙ копии отбит, пока замок
#              держит чужое закрытие. Своё закрытие несёт THREAD_FINISH_HOLDS_LOCK.
#
# ПОЧЕМУ flock ЯДРА, а не файл-флаг или каталог с pid: ядро снимает замок само,
# когда умирает процесс-держатель, — упавшая сессия не запирает закрытия всем.
# Прецедент в репо: longitudinal_analysis._acquire_run_lock.
#
# ГРАНИЦА. Стережёт коммиты. `git stash`, `reset`, `checkout` соседа в главной
# копии мимо замка проходят — хука у них нет. Метка в окружении — договор между
# своими процессами, не защита от злого умысла.
set -uo pipefail

_common="$(git rev-parse --git-common-dir 2>/dev/null)" || exit 0
_common="$(cd "$_common" && pwd)"
LOCK="$_common/thread_finish.lock"

if [[ "${1:-}" == "--path" ]]; then
    printf '%s\n' "$LOCK"
    exit 0
fi

# Судим только главную копию: у дерева нити свой индекс и свой HEAD.
_gitdir="$(cd "$(git rev-parse --git-dir)" && pwd)"
[[ "$_gitdir" == "$_common" ]] || exit 0
[[ -n "${THREAD_FINISH_HOLDS_LOCK:-}" ]] && exit 0
[[ -e "$LOCK" ]] || exit 0

_PY=""
for _CAND in /opt/homebrew/bin/python3.11 python3.11 python3; do
    command -v "$_CAND" >/dev/null 2>&1 && { _PY="$_CAND"; break; }
done
# Без python судить нечем. Отбивать коммит из-за отсутствия интерпретатора —
# хуже дыры (закрытие без python и так не работает: thread_finish код 9).
[[ -n "$_PY" ]] || exit 0

if "$_PY" -c '
import fcntl, sys
f = open(sys.argv[1], "a")
try:
    fcntl.flock(f, fcntl.LOCK_EX | fcntl.LOCK_NB)
except BlockingIOError:
    sys.exit(1)
' "$LOCK"; then
    exit 0
fi
echo "⛔ [замок закрытия] сейчас идёт закрытие чужой нити в главной копии." >&2
echo "   Коммит сюда унёс бы её слияние или индекс в твой коммит (d15f91d, 23.09)." >&2
echo "   Подожди и повтори: на время прогона тестов замок отпускается, держится" >&2
echo "   только на слиянии, журнале, якоре и деплое." >&2
exit 1
