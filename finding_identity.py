    # 23.09 (решение владельца «да»: инженерное со стола — вон). Четыре метки, по
    # которым он получал карточки, хотя оракул у них не он: чинит сессия. Карточка
    # 14.09 спрашивала его «сохранить файл в общую систему?», 15.09 — «твой ли файл в
