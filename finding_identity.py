def finding_key(label: str, explicit: str | None = None) -> str:
    """Устойчивое имя находки. `explicit` (если датчик его дал) побеждает текст.

    Устойчиво к изменению ЛЮБЫХ чисел в метке — счётчиков, возрастов, порогов:
    именно они меняются ежедневно, а предмет остаётся тем же."""
    if explicit:
        return str(explicit).strip()
    s = _LEAD.sub("", str(label or "")).strip().lower()
    s = _DIGITS.sub("N", s)
    return _SPACE.sub(" ", s).strip()


def finding_class(label: str, explicit: str | None = None) -> str:
    """Класс находки. `explicit` побеждает; неизвестное → decide (fail-closed)."""
    if explicit in CLASSES:
        return explicit
    low = str(label or "").lower()
    for sub, cls in CLASS_BY_SUBSTRING.items():
        if sub in low:
            return cls
    return DEFAULT_CLASS


if __name__ == "__main__":  # характеризация под рукой: python3.11 finding_identity.py "метка"
    import sys
    for a in sys.argv[1:]:
        print(f"{finding_key(a)!r}  [{finding_class(a)}]")
