"""Срок молчания в коде и в how-to обязан быть ОДНИМ числом.

Зачем отдельный сторож. За этот срок система принимает решение ЗА человека — это
единственное число в проекте, чья рассинхронизация с документацией означает, что
владелец ждал одного, а получил другое, и узнал об этом постфактум. Правило §9
(«число живёт одним домом») здесь исполняется не запретом литерала, а тем, что
второй его носитель — рецепт для человека — сверяется машинно.

Граница: тест судит СОВПАДЕНИЕ, а не правильность срока. Две недели — решение
владельца от 2026-09-13; оракул величины — он, не этот файл.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

import night_cycle  # noqa: E402

HOWTO = ROOT / "docs" / "how-to" / "night_cycle_respond.md"


def test_silence_days_matches_howto():
    text = HOWTO.read_text(encoding="utf-8")
    m = re.search(r"Срок молчания — (\d+) дн", text)
    assert m, "в how-to пропала строка «Срок молчания — N дней» — человеку негде прочитать срок"
    assert int(m.group(1)) == night_cycle.SILENCE_DAYS, (
        f"how-to обещает {m.group(1)} дней, код ждёт {night_cycle.SILENCE_DAYS} — "
        "владелец рассчитывает на один срок, система применяет другой")
