"""project_context.staged — когерентный снимок ИНДЕКСА (будущего коммита).

ЗАЧЕМ. Гейт судит КОММИТ, а читал пять источников из ДВУХ хранилищ: новый модуль — из индекса,
а сайдкары, тесты, проектную политику и индекс модулей (`indexer.build`) — из рабочего дерева.
Поэтому содержимое будущего коммита можно было не менять вовсе, а вердикт переворачивался:
DG-01 (застейджен только модуль — гейт зачитывает untracked сайдкар и тест) и DG-14 (K3
промахивается, когда чужой модуль удалён из дерева, но остался в индексе). Обе пробы —
в `plans/verify_dispgate_findings_2026-07-26.py`, обе были красными до этого модуля.

КАК. Индекс материализуется в одноразовый каталог, и все читатели работают ПРОТИВ НЕГО. Это
статическое устранение конфликта (Таненбаум §7.5.4): рассинхрон не детектируется в рантайме, а
становится невозможным — второго хранилища у гейта просто нет. Динамическая альтернатива
(«предупреждай, если дерево разошлось с индексом», §7.5.3) отвергнута осознанно: она добавляет
режим «предупредил и пропустил», то есть ещё один fail-open вместо снятого.

ГРАНИЦА, КОТОРУЮ НЕЛЬЗЯ ПОТЕРЯТЬ. Снимок — это СОДЕРЖИМОЕ РЕПОЗИТОРИЯ. Движковый чек-лист
одноразовости в него не входит и входить не должен: он ИНСТРУМЕНТ суждения, а не судимое
содержимое, и читается из установленного пакета единственным ридером
`indexer.disposability_policy()`. Иначе проект с пакетом вне репозитория (соседний проект) перестал бы
судить вовсе. Асимметрия намеренная, не небрежность.
(Имя движкового файла здесь не пишется буквально СОЗНАТЕЛЬНО: source-guard
`test_project_context.py::test_disposability_single_reader_source_guard` грепает по имени, и
упоминание в прозе он от чтения в обход ридера отличить не может. Ослаблять греп ради удобства
докстринга — менять живую защиту на комфорт; правильная ссылка тут и так на ридера, а не на файл.)

ПОЧЕМУ КАТАЛОГ, А НЕ СЛОВАРЬ path→текст. Словарь потребовал бы новых параметров-инъекций у
`indexer.build`, `contract_sidecars`, `disposability_policy` и у обхода `tests/` — то есть
расширения ЧУЖОЙ публичной поверхности ради нужды одного гейта. Каталог оставляет всех читателей
нетронутыми и вдобавок отнимает саму возможность случайно прочитать рабочее дерево: путь, который
они получают, — не дерево.

ЕДИНСТВЕННЫЙ ЧИТАТЕЛЬ GIT. Потребитель снимка не имеет права звать git сам — иначе появится
второй ответ на вопрос «что такое staged», и они разъедутся молча. Замер 2026-07-27 по AST:
`git diff --cached` зовут `receipt`, `dupgate`, `scripts/git-hooks/pre_commit_check` и этот модуль,
плюс сам shell-хук `pre-commit`; `dispgate` из этого списка вышел, когда перешёл на снимок.
Миграция соседей отложена осознанно: они читают git для других целей и живут в двух работающих
гейтах. Дубль-гейт проекта этот класс дубля НЕ видит по конструкции (его модель способности —
имя и таблица данных), поэтому автоматического принуждения здесь нет и оно записано как открытый
инвариант `disposability_gate::staged_readers_duplicated` в реестре замысла.

ЦЕНА. Материализация делается ТОЛЬКО когда в индексе есть новые файлы; коммит без новых файлов
не платит ничего. Материализуются лишь `*.py`, `contracts/*` и `project_context.json` — объединение
того, что читают потребители (~700 файлов, ~7 МБ), а не весь репозиторий. Замер на этом
репозитории: медиана ~1.36 с, p95 ~1.41 с (внешнее ревью 2026-07-27).

ЧЕГО СНИМОК НЕ ГАРАНТИРУЕТ (названо, не закрыто).
· `git checkout-index` восстанавливает **symlink как symlink**: в снимке лежит ИМЯ, а байты могут
  жить снаружи и меняться без индекса. «Один каталог» поэтому означает одну версию ПУТЕЙ, но не
  одну версию всех байтов. Материализовать собственное blob-дерево ради этого несоразмерно модели
  «один доверенный писатель»; ограничение записано в §15 как известная дыра.
· «Каталог живёт ровно на время суждения» верно для нормального и ошибочного выхода, но НЕ для
  убийства процесса сигналом: `__exit__` тогда не зовётся и `pc-index-*` остаётся. Ограниченной
  уборки по возрасту нет — она заводится, если реальные протечки появятся, а не заранее.
"""
import os
import shutil
import subprocess
import tempfile

# Объединение того, что читают потребители снимка. Данные, доки и бинарники не нужны никому из
# них — за них не платим временем хука. 2026-08-07: intentgate стал потребителем — добавлены
# артефакты закрытия (plans/, docs/handoff/) и реестр замысла: квитанция судится против
# реестра ТОЙ ЖЕ версии индекса; вторым хранилищем был бы worktree — ровно снятый класс DG-01.
_PATHSPEC = ("*.py", "contracts/*", "project_context.json",
             "plans/*.md", "docs/handoff/*", "subsystem_intent.yaml")


class _Snapshot:
    """Результат `snapshot()`. Контекстный менеджер: каталог живёт ровно на время суждения.

    root  — каталог снимка. None означает «судить нечего или снимок недостоверен»; проверять
            надо `ok` и `added`, а не `root`.
    added — пути файлов со статусом `A` в индексе, относительно корня репозитория.
    ok    — индекс прочитан достоверно. False — инструмент отказал, а не ритуал пропущен;
            политику выхода на этот случай решает потребитель, не снимок.
    why   — человекочитаемая причина: почему `ok=False` либо почему снимок пуст.
    """

    def __init__(self, root=None, added=(), ok=False, why=""):
        self.root = root
        self.added = tuple(added)
        self.ok = ok
        self.why = why

    def __enter__(self):
        return self

    def __exit__(self, *_exc):
        if self.root:
            shutil.rmtree(self.root, ignore_errors=True)
            self.root = None
        return False


def snapshot(root="."):
    """Снимок индекса репозитория `root`. Единственный публичный вход модуля.

    Всегда возвращает объект, никогда не бросает: отказ git — это состояние (`ok=False`), а не
    исключение, потому что решение «блокировать или пропустить при отказе инструмента» принимает
    потребитель. Использовать как контекстный менеджер, иначе каталог снимка останется на диске.
    """
    try:
        # Корень репозитория, а не переданный путь. git находит индекс вверх по дереву, но
        # относительные пути потом резолвились от cwd — тот же нарушитель из подкаталога получал
        # чистый вердикт (ревью 2026-07-27, F-09). Хук от этого защищён собственным cd, ручной
        # запуск — нет, и молчаливое «чисто» опаснее ошибки.
        root = subprocess.check_output(["git", "rev-parse", "--show-toplevel"],
                                       cwd=root, stderr=subprocess.DEVNULL).decode().strip()
        raw = subprocess.check_output(
            ["git", "diff", "--cached", "--name-only", "--diff-filter=A", "-z"],
            cwd=root, stderr=subprocess.DEVNULL)
    except Exception as e:  # noqa: BLE001 — тип отказа неважен, важен факт: индекса нет
        return _Snapshot(ok=False, why=f"индекс не прочитан ({type(e).__name__})")

    added = tuple(p for p in raw.decode("utf-8", "replace").split("\0") if p)
    if not added:
        return _Snapshot(ok=True, why="в индексе нет новых файлов")

    try:
        # Внутри try: отказ выделения каталога — такая же ошибка инструмента, как отказ git, и
        # обязан выражаться результатом. Строка стояла ВЫШЕ try и бросала наружу вопреки
        # собственному контракту «никогда не бросает» (ревью 2026-07-27, F-06).
        tmp = tempfile.mkdtemp(prefix="pc-index-")
    except Exception as e:  # noqa: BLE001
        return _Snapshot(ok=False, why=f"каталог снимка не создан ({type(e).__name__}: {e})")
    try:
        names = subprocess.check_output(["git", "ls-files", "-z", "--", *_PATHSPEC],
                                        cwd=root, stderr=subprocess.DEVNULL)
        done = subprocess.run(
            ["git", "checkout-index", "-z", "--stdin", "--prefix=" + tmp + os.sep],
            cwd=root, input=names, stdout=subprocess.DEVNULL, stderr=subprocess.PIPE)
        if done.returncode != 0:
            raise RuntimeError(done.stderr.decode("utf-8", "replace")[:200])
    except Exception as e:  # noqa: BLE001
        shutil.rmtree(tmp, ignore_errors=True)
        return _Snapshot(ok=False, why=f"снимок индекса не построен ({type(e).__name__}: {e})")

    return _Snapshot(root=tmp, added=added, ok=True)
