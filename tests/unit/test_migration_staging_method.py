def test_страница_без_шапки_таблицы_секций_не_даёт():
    """Проза без шапки таблицы не создаёт секций метода.
    Иначе фрагменты примечаний произвольно дробили бы тренд."""
    assert LS.sections(ПРОЗА, ["Clostridium perfringens"], [""]) == []


def test_название_со_скобкой_на_конце_остаётся_заголовком():
    """Первая версия фильтра резала любую строку со скобкой на конце и убила бы
    «Стероидный профиль (ЖХ-МС/МС)» — ровно тот заголовок, ради которого весь
    шаг. Мусор отличается НЕПАРНОЙ скобкой («проводится лечащим врачом)»)."""
    heads = [h for _i, h in LS.sections(СТР_СТЕРОИДЫ, ["Тестостерон"], ["нмоль/л"])]
    assert "Стероидный профиль (ЖХ-МС/МС)" in heads


def test_текстовое_значение_не_заголовок():
    """«не обнаружено» и «отрицательно» — результаты качественного анализа.
    Числовой фильтр их не ловит: они не числа."""
    txt = ("Показатель\nРезультат\nВолчаночный антикоагулянт\nне обнаружено\n"
           "Гемостазиограмма\nАЧТВ\n31,0\n")
    heads = [h for _i, h in LS.sections(
        txt, ["Волчаночный антикоагулянт", "АЧТВ"], [""], ["не обнаружено"])]
    assert "не обнаружено" not in heads
