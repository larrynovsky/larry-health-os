class DescriptionText:
    """One rendering pass: exact translation keys, collected sources, missing occurrences.

    Shared by the three generators with data-derived descriptions. RU collection uses
    the same rendering path without consulting translation memory or calling a model.
    """
    def __init__(self, lang="ru"):
        if lang not in ("ru", "en"):
            raise ValueError(f"Unsupported language: {lang}")
        self.lang = lang
        self.texts = []
        self.untranslated = 0

    def text(self, source, *, limit=None):
        """Collect and translate the full source, then apply the rendering limit."""
        source = str(source)
        if re.search(r"[А-Яа-яЁё]", source):
            self.texts.append(source)
        if self.lang == "ru":
            return source[:limit]
        translated = desc_translation.english(source)
        if translated is None:
            self.untranslated += 1
            return source[:limit] + " ⟨untranslated⟩"
        return translated[:limit]

    def cell(self, source, *, limit=None):
        """Escape table separators after lookup, without changing the memory key."""
        value = self.text(source, limit=limit)
        if self.lang == "en":
            return re.sub(r"(?<!\\)\|", lambda match: r"\|", value)
        return value


def blueprint_descriptions():
    """Full Russian first lines, before the 80/65-character rendering limits."""
    descriptions = DescriptionText()
    _build_arch_registry(descriptions=descriptions)
    return descriptions.texts


def _first_line(s: str) -> str:
    return s.splitlines()[0].strip() if s else ""


def _build_arch_registry(lang="ru", *, descriptions=None) -> str:
    text = _TEXT[lang]
    descriptions = descriptions or DescriptionText(lang)
    today = date.today().isoformat()  # time-inject: ok
    lines = [
        text["heading"],
        text["header"].format(today=today),
        "",
    ]
    for layer, files in _ARCH_LAYERS:
        layer = dict(zip(_TEXT["ru"]["layers"], text["layers"]))[layer]
        lines += [f"### {layer}", "```", ""]
        for fname in files:
            path = ROOT / fname
            if not path.exists():
                lines += [f"{fname}  # {text['missing']}", ""]
                continue
            doc_first, funcs = "", []
            if fname.endswith(".py"):
                try:
                    tree = ast.parse(path.read_text())
                    doc_first = _first_line(ast.get_docstring(tree) or "")
                    seen: set = set()
                    for node in ast.walk(tree):
                        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                            if node.name.startswith("_") or node.name in seen:
                                continue
                            seen.add(node.name)
                            args = [a.arg for a in node.args.args
                                    if a.arg not in ("self", "cls")]
                            fd_s = _first_line(ast.get_docstring(node) or "")
                            pfx  = "async " if isinstance(node, ast.AsyncFunctionDef) else ""
                            funcs.append((f"  {pfx}{node.name}({', '.join(args[:4])})", fd_s))
                        elif isinstance(node, ast.ClassDef):
                            if not node.name.startswith("_") and node.name not in seen:
                                seen.add(node.name)
                                funcs.append((f"  class {node.name}", ""))
                except Exception:
                    pass
            lines.append(f"{fname}  # {descriptions.text(doc_first, limit=80)}" if doc_first else fname)
            # Translate outside the AST error handler: a memory failure must not drop functions.
            lines.extend(signature + (" — " + descriptions.text(doc, limit=65) if doc else "")
                         for signature, doc in funcs)
            lines.append("")
        lines += ["```", ""]
    return "\n".join(lines)


def update_arch_snapshot(lang="ru", *, descriptions=None) -> bool:
    """Перезаписывает раздел МОДУЛЬНЫЙ РЕЕСТР в ARCH_SNAPSHOT.md между GEN-маркерами."""
    target = ARCH_SNAPSHOT if lang == "ru" else ARCH_SNAPSHOT.with_name("ARCH_SNAPSHOT.en.md")
    if not target.exists():
        print(f"{target.name} не найден: {target}")
        return False
    content = target.read_text(encoding="utf-8")
    if _ARCH_START not in content or _ARCH_END not in content:
        print(f"GEN-маркеры не найдены в {target.name} — пропускаем")
        return False
    new_body    = _ARCH_START + "\n\n" + _build_arch_registry(lang, descriptions=descriptions) + "\n" + _ARCH_END
    pattern     = re.escape(_ARCH_START) + r".*?" + re.escape(_ARCH_END)
    # Preserve the legacy RU replacement semantics; EN text can contain backslashes.
    replacement = new_body if lang == "ru" else lambda match: new_body
    new_content = re.sub(pattern, replacement, content, flags=re.DOTALL)
    if new_content == content:
        print(f"{target.name} не изменился.")
        return False
    if DRY_RUN:
        print(f"--- DRY RUN: {target.stem} не записан ---")
        return False
    target.write_text(new_content, encoding="utf-8")
    print(f"✅ {target.name} обновлён ({len(new_content.splitlines())} строк)")
    return True


