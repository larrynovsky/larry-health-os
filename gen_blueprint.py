def main(argv=None):
    parser = argparse.ArgumentParser()
    parser.add_argument("--lang", choices=("ru", "en"), default="ru")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args(argv)
    global DRY_RUN
    DRY_RUN = args.dry_run
    descriptions = DescriptionText(args.lang)
    changed = update_arch_snapshot(args.lang, descriptions=descriptions)
    if changed:
        target = "ARCH_SNAPSHOT.md" if args.lang == "ru" else "ARCH_SNAPSHOT.en.md"
        print(f"Добавь в коммит:  git add {target}")
    if args.lang == "en":
        print(f"untranslated: {descriptions.untranslated}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
