# Токен — ключ самому себе: normalize_value должна быть идемпотентной.
# Печатная форма и уже нормализованный токен должны приниматься одинаково;
# совпадение токена с одним из синонимов не является достаточной гарантией.
#
# Цена отсутствия: любая проверка «всё ли в каноне из словаря» краснела бы на верных
# строках, то есть датчик указывал бы не туда, куда надо смотреть.
