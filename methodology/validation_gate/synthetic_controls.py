from __future__ import annotations

from functools import lru_cache
from pathlib import Path

import numpy as np

SPEC_DATE = "2026-08-01"

# Длины периодов задаются входной спецификацией отдельно от алгоритма генерации.
# Изменение разбиения требует повторного согласования и калибровки контролей.
# Изменение манифеста эпох не обновляет эту спецификацию автоматически.
# Для публичной демонстрации разбиение следует конструировать независимо.
SPEC_PATH = Path(__file__).with_name("synthetic_spec.yaml")


@lru_cache(maxsize=None)
def _periods() -> tuple:
    import yaml
    if not SPEC_PATH.exists():
        raise FileNotFoundError(
            f"{SPEC_PATH.name}: нет спецификации синтетики — это данные установки (длины эпох "
            "того, на чьём ряду калибруется гейт). Без неё контроли не строятся.")
    d = yaml.safe_load(SPEC_PATH.read_text(encoding="utf-8")) or {}
    periods = tuple(int(x) for x in d.get("periods") or ())
    if str(d.get("spec_date")) != SPEC_DATE or not periods or min(periods) <= 0:
        raise ValueError(
            f"{SPEC_PATH.name}: спецификация синтетики разошлась (spec_date {d.get('spec_date')!r}, "
            f"ждём {SPEC_DATE}; периодов {len(periods)}). Числа пришли от автора критерия — "
            "менять их самостоятельно значит калибровать пороги на своих допущениях.")
    return periods


def __getattr__(name):   # PEP 562: PERIODS/N читаются лениво — импорт модуля не требует файла
    if name == "PERIODS":
        return _periods()
    if name == "N":
        return sum(_periods())
    raise AttributeError(name)


PHI = 0.8256                           # даёт N_eff ≈ 300 при 38% пропусков (§3-3 автора)
ALPHA = 0.7340                         # даёт ρ(X, Y) ≈ 0.35
MISS_FRAC = 0.38
MISS_MEAN_LEN = 3                      # геометрическая длина блока пропусков (MAR)
BETA = 1.2247                          # нагрузка общего фактора внутри периода инъекции
INJECT_PERIOD = 0                      # «Период 1» автора — первый (baseline)
TAUT_NOISE = 0.03                      # σ шума в Y тавтологического контроля

# Ожидания АВТОРА (редакция 2, после прогона первой). Держатся здесь, чтобы расхождение
# с прогоном было видно, а не забыто.
#
# ⚠️ ВСЕ ЕГО ЧИСЛА — ПИРСОНОВЫ. Установлено замером 2026-08-01, а не прочитано: Пирсон
# даёт 0.349 / 0.602 / 0.448 против его 0.35 / 0.60 / 0.44 — совпадение до второго знака
# во всех трёх контролях. Наш гейт судит СПИРМЕНОМ, и он систематически ниже: 0.334 /
# 0.584 / 0.378. На однородном ряду разница в пределах округления, но на Negative Control
# доходит до 0.07, потому что внутри периода инъекции дисперсия в 2.5 раза выше — ранги
# считаются глобально, и смесь режимов бьёт по ранговой корреляции сильнее, чем по
# линейной. Сверять его ожидания Спирменом = придумать себе расхождение.
#
# СЛЕДСТВИЕ ДЛЯ БУДУЩЕГО Gate 0.5: его порог 0.80 обоснован через R² > 0.64, то есть
# через долю объяснённой дисперсии — это ПИРСОН. Детектор подавления, когда его построят,
# обязан считать частную корреляцию Пирсона, иначе порог будет означать не то, что заявлен.
EXPECTED = {
    "positive_rho": 0.35,
    "negative_r_all": 0.44,
    "negative_r_inject": 0.60,
    "negative_r_other": 0.00,
    "tautological_raw_r": 0.47,
    "tautological_partial_r": 0.82,    # клетка, оборванная в первой редакции, восстановлена
    "tautological_ratio": 1.74,
}


def _assert_spec() -> None:
    """Сторож спецификации: длины периодов — чужое число, а не наше решение."""
    _periods()


def _ar1(n: int, phi: float, sd_innov: float, rng, mu: float = 0.0) -> np.ndarray:
    """AR(1) со СТАЦИОНАРНЫМ стартом: x0 ~ N(0, sd_innov² / (1 − φ²)).

    Старт из нуля при сильной автокорреляции занижает дисперсию начальных точек.
    Стационарный старт устраняет этот артефакт независимо от разбиения на периоды.
    """
    e = rng.normal(0.0, sd_innov, n)
    x = np.empty(n)
    x[0] = e[0] / np.sqrt(1.0 - phi * phi)
    for t in range(1, n):
        x[t] = phi * x[t - 1] + e[t]
    return x + mu


def _block_missing(n: int, rng) -> np.ndarray:
    """Маска пропусков MAR блоками геометрической длины — имитация периодов без прибора."""
    mask = np.zeros(n, dtype=bool)
    need = int(round(MISS_FRAC * n))
    guard = 0
    while mask.sum() < need and guard < 10 * n:
        start = int(rng.integers(0, n))
        mask[start:start + int(rng.geometric(1.0 / MISS_MEAN_LEN))] = True
        guard += 1
    return mask


def period_index(k: int) -> slice:
    """Границы k-го периода в сгенерированном ряду (k с нуля)."""
    p = _periods()
    start = sum(p[:k])
    return slice(start, start + p[k])


def _positive(rng, missing: bool):
    """5.1 — истинная связь средней силы через общий скрытый фактор."""
    N = sum(_periods())
    z = _ar1(N, PHI, 1.0, rng)
    x = ALPHA * z + _ar1(N, PHI, 1.0, rng)
    y = ALPHA * z + _ar1(N, PHI, 1.0, rng)
    if missing:
        m = _block_missing(N, rng)
        x, y = x.copy(), y.copy()
        x[m] = np.nan
        y[m] = np.nan
    return x, y


def _negative(rng, missing: bool):
    """5.2 — связи НЕТ нигде, кроме одного периода: общий скрытый фактор внутри него.

    РЕДАКЦИЯ 2 (автор, ответ на Дополнение 4). Первая редакция задавала сдвиг среднего;
    прогон показал, что постоянный сдвиг со-движения ВНУТРИ периода не создаёт, и автор
    согласился: контроль обязан проверять способность профиля находить ОДИН сильный
    период на фоне пустых, а сдвиг проверял другое (связь между периодами).

    Предмет контроля: агрегированная корреляция может пройти статистические ворота,
    но профиль обязан отклонить связь, сосредоточенную в одном из заданных периодов.
    """
    N = sum(_periods())
    x = _ar1(N, PHI, 1.0, rng)
    y = _ar1(N, PHI, 1.0, rng)
    f = _ar1(N, PHI, 1.0, rng)
    sl = period_index(INJECT_PERIOD)
    x[sl] += BETA * f[sl]
    y[sl] += BETA * f[sl]
    if missing:
        m = _block_missing(N, rng)
        x[m] = np.nan
        y[m] = np.nan
    return x, y


def _tautological(rng, missing: bool):
    """5.3 — вычислительная зависимость, маскируемая общим знаменателем.

    Z — аналог времени в постели, X — аналог общего сна, Y = X/Z — аналог эффективности.
    Дисперсия процесса задаётся через σ инноваций: σ_proc = σ_innov / sqrt(1 − φ²).
    """
    N = sum(_periods())
    z = _ar1(N, 0.5, 0.5, rng, mu=8.0)
    w = _ar1(N, 0.5, 0.3, rng)
    x = 0.85 * z + w
    y = x / z + rng.normal(0.0, TAUT_NOISE, N)
    if missing:
        m = _block_missing(N, rng)
        x[m] = np.nan
        y[m] = np.nan
    return x, y, z


_KINDS = {"positive": _positive, "negative": _negative, "tautological": _tautological}


def control_series(kind: str, seed: int, *, missing: bool = True):
    """Единственный вход. Возвращает (x, y, z_or_None) для контроля `kind`.

    Имя НЕ `generate`: так называется соседний `stage_b_twin.generate`, и разводить их
    пришлось не ради гейта имён, а потому что предметы разные — см. докстринг модуля.

    `z` не None только у tautological: детектор подавления фиксирует именно его, и
    отдавать наружу «найдите Z сами» значило бы вернуть ту неопределённость, которую
    автор закрыл жёсткой фиксацией Z = время в постели.

    seed: автор задал `42` для первого прогона и `42 + i` далее — номер прогона передаёт
    вызывающий, модуль своей нумерации не заводит.
    """
    _assert_spec()
    if kind not in _KINDS:
        raise ValueError(f"неизвестный контроль {kind!r}; есть {sorted(_KINDS)}")
    out = _KINDS[kind](np.random.default_rng(seed), missing)
    return out if len(out) == 3 else (out[0], out[1], None)
