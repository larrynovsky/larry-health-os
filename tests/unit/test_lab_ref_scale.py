"""Оракул датчика расхождения шкал значения и референса (loinc-name-home).

Если пересчитать значение и оставить границы в исходной единице,
совместное чтение будет ошибочным, хотя каждое число отдельно правдоподобно.
Синтетические контроли ниже отделяют рассогласование шкал от значения
вне согласованного референсного интервала.

Тест держит границу с ДВУХ сторон. Односторонний оракул зеленел бы и на правиле
«молчать всегда», и — что дороже — на правиле, которое глушит настоящую
патологию, объявляя её опиской шкалы. Второй режим отказа страшнее первого:
пропущенная находка стоит шума, проглоченная патология стоит диагноза.
"""
import integrity_tests as it


def _row(rid=1, name="Vitamin_D", value=23.36, lo=50.0, hi=75.0):
    return (rid, name, value, lo, hi)


# ── Позитивный контроль на независимо сконструированных строках ──

def test_витамин_d_значение_в_нг_границы_в_нмоль_покраснел():
    found = it.ref_scale_mismatch([_row()])
    assert len(found) == 1, "дефект формы 2026-07-30 обязан находиться"
    assert found[0][1] == "Vitamin_D"


def test_белок_креатинин_глюкоза_мочевая_тоже_покраснели():
    """Четыре аналита, четыре разных коэффициента — правило не про витамин D."""
    rows = [
        (1, "Total_Protein", 7.12, 64.0, 83.0),    # g/dL против g/L,   ×0.1
        (2, "Creatinine", 0.97, 72.0, 127.0),      # mg/dL против µmol/L, ÷88.4
        (3, "Glucose", 88.21, 3.9, 6.1),           # mg/dL против mmol/L, ×18.016
        (4, "Uric_acid", 5.43, 210.0, 420.0),      # mg/dL против µmol/L, ÷59.48
    ]
    assert len(it.ref_scale_mismatch(rows)) == 4


# ── граница с другой стороны: настоящая патология НЕ глушится ──

def test_настоящий_дефицит_витамина_d_остаётся_виден():
    """8 нг/мл при границах 30–100 нг/мл — это дефицит, а не описка шкалы.
    Если датчик проглотит такую строку, он не найдёт дефект, а спрячет болезнь."""
    assert it.ref_scale_mismatch([_row(value=8.0, lo=30.0, hi=100.0)]) == []


def test_настоящая_гипергликемия_остаётся_видна():
    assert it.ref_scale_mismatch([(1, "Glucose", 350.0, 70.0, 100.0)]) == []


def test_белок_втрое_ниже_нормы_не_объявляется_опиской():
    assert it.ref_scale_mismatch([(1, "Total_Protein", 2.5, 6.4, 8.3)]) == []


# ── законные отсевы ──

def test_одна_шкала_у_значения_и_границ_молчит():
    """Обе стороны в СИ — сочетание верное, датчику здесь делать нечего."""
    assert it.ref_scale_mismatch([(1, "Total_Protein", 73.0, 64.0, 83.0)]) == []


def test_норма_внутри_границ_молчит():
    assert it.ref_scale_mismatch([(1, "Creatinine", 0.97, 0.7, 1.2)]) == []


def test_аналит_без_правила_пересчёта_молчит():
    """Без коэффициента судить не о чем: вторая шкала неизвестна, и любая
    догадка была бы спекуляцией (ровно та, что запрещена в РФМК)."""
    assert it.ref_scale_mismatch([(1, "Ferritin", 11.9, 30.0, 400.0)]) == []


def test_строка_без_значения_или_без_границ_молчит():
    assert it.ref_scale_mismatch([_row(value=None)]) == []
    assert it.ref_scale_mismatch([_row(lo=None, hi=None)]) == []


def test_сырое_имя_приводится_к_канону():
    """Датчик читает канон, но имя туда попадает и по-русски — иначе находка
    зависит от того, чей бланк разобрали."""
    assert len(it.ref_scale_mismatch([(1, "витамин D", 23.36, 50.0, 75.0)])) == 1


def test_подтверждение_корпусом_гасит_ложное_срабатывание():
    """Синтетическое отклонение от референса не является ошибкой шкалы.
    Другой независимый документ подтверждает единицу и границы;
    одного попадания числа в пересчитанную полосу недостаточно."""
    rows = [
        (1, "Vitamin_D", 18.2, 30.0, 100.0, "нг/мл", "doc:lab_a.pdf"),
        (2, "Vitamin_D", 33.62, 30.0, None, "ng/ml", "doc:другой.pdf"),
    ]
    assert it.ref_scale_mismatch(rows) == []


def test_подтверждение_не_гасит_настоящую_находку():
    """Отрицательный контроль: синтетическая строка со смешанными шкалами
    остаётся находкой, когда другой документ её границы не подтверждает."""
    rows = [
        (1, "Vitamin_D", 23.36, 50.0, 75.0, "ng/mL", "doc:кривой.pdf"),
        (2, "Vitamin_D", 33.62, 30.0, 100.0, "ng/ml", "doc:другой.pdf"),
    ]
    assert len(it.ref_scale_mismatch(rows)) == 1


def test_один_документ_сам_себя_не_подтверждает():
    """Иначе подтверждением стал бы повтор одной и той же ошибки в одном бланке."""
    rows = [
        (1, "Vitamin_D", 23.36, 50.0, 75.0, "ng/mL", "doc:кривой.pdf"),
        (2, "Vitamin_D", 23.36, 50.0, 75.0, "ng/mL", "doc:кривой.pdf"),
    ]
    assert len(it.ref_scale_mismatch(rows)) == 2


# ── вторая сторона: значение настояще вне нормы, граница в чужой шкале (07.10) ──
# Синтетика по форме дефекта: значение пересчитано в мг/дл, граница «< 3,00» осталась
# в ммоль/л. Первая ветка молчит (154.7 > 3.0×38.67), читатель видит «154 при норме 3».

def _lipid_corpus():
    return [
        (10, "LDL", 105.0, 60.0, 160.0, "mg/dL", "doc:a.pdf"),
        (11, "LDL", 118.0, 50.0, 155.0, "mg/dL", "doc:b.pdf"),
        (12, "LDL", 131.0, 95.0, 135.0, "mg/dL", "doc:c.pdf"),
    ]


def test_граница_в_ммоль_при_значении_в_мг_и_настоящем_превышении_покраснела():
    rows = _lipid_corpus() + [(1, "LDL", 154.7, None, 3.0, "mg/dL", "doc:d.pdf")]
    found = it.ref_scale_mismatch(rows)
    assert [f[0] for f in found] == [1]


def test_граница_в_шкале_значения_при_превышении_молчит():
    """Отрицательный контроль: то же превышение, граница уже в мг/дл (116) — сочетание верное."""
    rows = _lipid_corpus() + [(1, "LDL", 154.7, None, 116.0, "mg/dL", "doc:d.pdf")]
    assert it.ref_scale_mismatch(rows) == []


def test_без_двух_других_документов_корпус_не_судит():
    """Один чужой документ — не корпус: редкий анализ не должен краснеть ночью."""
    rows = _lipid_corpus()[:1] + [(1, "LDL", 154.7, None, 3.0, "mg/dL", "doc:d.pdf")]
    assert it.ref_scale_mismatch(rows) == []


def test_другой_метод_той_же_сущности_в_разы_не_объявляется_опиской():
    """Высокочувствительный СРБ «< 1 мг/л» рядом с обычным «< 5 мг/л» — граница
    другого метода, в той же шкале. Расхождение в разы, не на порядок — молчим.
    Без этого датчик-assert краснел бы каждую ночь на верной строке."""
    rows = [
        (10, "CRP", 0.8, 0.0, 5.0, "mg/L", "doc:a.pdf"),
        (11, "CRP", 0.4, 0.0, 5.0, "mg/L", "doc:b.pdf"),
        (12, "CRP", 1.1, None, 5.0, "mg/L", "doc:c.pdf"),
        (1, "CRP", 12.4, None, 1.0, "mg/L", "doc:d.pdf"),
    ]
    assert it.ref_scale_mismatch(rows) == []
