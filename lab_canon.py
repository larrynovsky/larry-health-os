def is_dimensionless(name: str) -> bool:
    """Аналит безразмерен по природе (отношение/индекс) — пустая единица у него НЕ потеря.

    Имя канонизируется ВНУТРИ: сырое «коэффициент атерогенности» и каноническое
    `Chol_HDL_ratio` обязаны отвечать одинаково. Отдельная функция, а не голое
    `name in DIMENSIONLESS` у вызывающего, именно поэтому: забыть normalize —
    ровно тот промах сырого имени мимо канонического, на котором в этой же нити
    предикат дрейфа насчитал 2356 строк вместо 24.
    """
    return normalize(name) in DIMENSIONLESS


