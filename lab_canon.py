def dimension_key(canonical: str, unit: str) -> str:
    """Уточняет имя по размерности единицы: `Plasma_cells` + `%` → `Plasma_cells_pct`,
    `RDW` + `фл` → `RDW_SD`.

    Прочие аналиты возвращаются как есть — молча и без суффикса. Пустая единица
    тоже оставляет имя нетронутым: суффикс, выведенный из отсутствия данных, был
    бы догадкой, записанной как факт. Правило, вернувшее None, оставляет имя
    нетронутым по той же причине: неоднозначная единица — не основание.
    """
    ent = _DIMENSION_BY_UNIT.get(canonical)
    if not ent or not (unit or "").strip():
        return canonical
    suf = ent[1](unit.lower())
    return canonical if suf is None else "%s_%s" % (canonical, suf)


# Регистрация суффиксных имён в CANONICALS — из таблицы уточнений, без второго
# перечня. Суффиксы объявлены в самой записи (первый элемент кортежа) и есть
# множество значений правила; расхождение поймает тест
# `test_суффиксные_имена_известны_канону`.
CANONICALS |= {"%s_%s" % (c, s)
               for c, ent in _DIMENSION_BY_UNIT.items() for s in ent[0]}


# Голый процент у размерного аналита без объявленной abs/pct-пары
# сигнализирует о возможной другой величине под тем же именем.
_IDENTITY_BARE_PERCENT = frozenset({"%", "percent", "проц"})


def identity_name(name: str, unit: str) -> str | None:
    """Идентичность аналита: имя, уточнённое размерностью. ОДИН дом правила.

    ADR 2026-08-12 (docs/explanation/adr_analyte_identity_lives_in_name.md): одно измерение
    определяется тремя признаками — имя + материал + размерность. Материал
    живёт в соседней колонке `specimen` (второй дом ему заводить нельзя,
    урок specimen_key выше), поэтому эта функция несёт ДВА признака из трёх:
    сведённое имя, уточнённое суффиксом размерности. Ключ идентичности =
    (identity_name, specimen) у вызывающего.

    Возврат None = «не берусь судить», и это БЕЗОПАСНАЯ сторона: вызывающие
    (датчик комнаты ожидания, guard промоута `_in_canon`, предикат B миграции
    границы) по None НЕ признают строку дублем — она остаётся ждать человека.

    Гард против §17-слепоты `dimension_key`: голый `%` на аналите, чьё имя
    процентность не несёт (`_pct`) и чья пара abs/pct не объявлена, к
    идентичности не сводится — иначе датчик назвал бы РАЗНЫЕ величины
    «одним измерением» (мина Инсулин %). Аналиты, чья ЗАКОННАЯ единица — голый
    процент (ЭЛИ-Тест, P_LCR, PSA_free_index, Omega3_index), объявлены в
    `PERCENT_NATIVE` и гардом не задерживаются: для них % — идентичность
    (прежний предел «P_LCR получает None» снят 2026-08-13 вместе с этапом имён).

    Три вызывающих НАМЕРЕННО зовут одну функцию, а не держат копии: две копии
    правила у двух писателей — болезнь, которую лечит вся нить data-ingestion
    (§17, третий пример).
    """
    nm = normalize(name or "")
    if nm not in CANONICALS:
        return None
    refined = dimension_key(nm, unit or "")
    if refined != nm:
        return refined          # объявленная пара abs/pct: % здесь законен
    ul = (unit or "").strip().lower()
    if ul in _IDENTITY_BARE_PERCENT and not nm.endswith("_pct") \
            and not is_dimensionless(nm) and nm not in PERCENT_NATIVE:
        return None
    return nm


def specimen_key(canonical: str, unit: str) -> str:
    """УСТАРЕЛО (2026-07-31, шаг 8 нити loinc-name-home). Не звать в новом коде.

    Функция выводила материал ИЗ ЕДИНИЦЫ и приписывала его к ИМЕНИ аналита
    (`Methylmalonic_acid_serum`) — в то время как промоут писал тот же материал в
    КОЛОНКУ `lab_results.specimen` словом `blood`. Два дома одного факта с разными
    словарями: колонка говорила «кровь», имя — «сыворотка», и сойтись они не могли
    в принципе. Дом остался один — колонка.

    Оставлена как делегат: её звал `build_lab_history_context` (переведён на
    колонку) и зовут два теста. Снимать имя без переписи читателей нельзя — это
    правило проекта, нарушенное в этой же нити днём раньше.

    Прежнее поведение сохранено дословно, чтобы делегат не менял ответов.
    """
    fn = _SPECIMEN_BY_UNIT.get(canonical)
    if not fn:
        return canonical
    return "%s_%s" % (canonical, fn((unit or "").lower()))


def unit_convergence_gaps(analyte_units: dict) -> list:
    """Аналиты, чьи единицы НЕ сводятся к одной цели через _norm_unit+to_conventional.
    Косметика (µ/μ, регистр, кириллица) и конвертируемое сходятся → молчат; остаток =
    worklist канонизации (расширить _norm_unit ИЛИ добавить правило в _TO_CONVENTIONAL).
    Чистая/тестируемая: вход {canonical_name: набор единиц}, выход список находок
    (пусто = всё сходится). plan_consilium_under_manifest 2026-07-08 Фаза 1."""
    out = []
    for canon, units in sorted(analyte_units.items()):
        targets = set()
        for u in units:
            if not u:
                continue
            _, tgt = to_conventional(canon, 1.0, u)
            targets.add(_norm_unit(tgt))
        if len(targets) > 1:
            raw = sorted(u for u in units if u)
            out.append("%s: %s из %s" % (canon, sorted(targets), raw))
    return out


