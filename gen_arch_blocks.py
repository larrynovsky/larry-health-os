DOMAINS_INVENTORY = ["vagal_activation", "stress", "activity", "sleep", "nutrition"]


def build_domain_signals(lang="ru", *, descriptions=None, signals_by_domain=None) -> str:
    """Рендерит СОСТАВ domain_signals из system_config БД (метрика, смысл, перцентиль).

    Manual trigger: --only domain_signals. Источник правды — БД тенанта
    (`health_db.get_domain_signals(domain)`). Коэффициент r — корреляция по ряду тенанта:
    это его данные, в документ репозитория не выносится (BL-PUB-16 а, 27.09).
    """
    text = _TEXT[lang]
    descriptions = descriptions or DescriptionText(lang)
    if signals_by_domain is None:
        import health_db  # CLI guard has already run; tests supply synthetic input.
        signals_by_domain = {domain: health_db.get_domain_signals(domain) for domain in DOMAINS_INVENTORY}
    lines = [
        "<!-- GEN:DOMAIN_SIGNALS:START -->",
        "",
        text["domain"],
        text["domain_header"],
        text["domain_source"],
        "",
    ]
    for domain in DOMAINS_INVENTORY:
        signals = signals_by_domain.get(domain, [])
        if not signals:
            lines += [f"### {domain}", "", text["no_signals"].format(domain=domain), ""]
            continue
        rows = ["| metric | label | threshold_pct |", "|---|---|---:|"]
        for sig in signals:
            rows.append(f"| `{sig.get('metric', '?')}` | {descriptions.cell(sig.get('label', '?'))} | "
                        f"{sig.get('threshold_pct', '?')} |")
        lines += [f"### {domain}", ""] + rows + [""]
    lines.append("<!-- GEN:DOMAIN_SIGNALS:END -->")
    return "\n".join(lines)


