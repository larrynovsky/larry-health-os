# ЗАЧЕМ. Гейты merge-коммита (квитанция замысла, дубль, одноразовость, preflight)
# зовутся хуком pre-merge-commit, то есть ПРИ слиянии — ПОСЛЕ пятиминутного
# прогона. Их отказ стоил целого прогона. Замер первого живого закрытия 21.09:
# три прогона вместо одного, и один сгорел на гейте квитанции, который
# отвечает за секунды (за шесть дней ожидания сосед добавил инвариант в запись,
# и снимок нити устарел). Порядок «дорогое, потом дешёвое» платит за ошибки,
# ловимые дёшево.
#
# КАК. Пробное слияние без коммита в главной копии — ровно то состояние, в
# котором git позвал бы хук (MERGE_HEAD есть, индекс собран), — затем тот же
# хук через `git hook run` (git сам находит его путь, включая core.hooksPath;
# своего поиска не заводим), затем ВСЕГДА `merge --abort`. Хука нет — нечего и
# проверять: при настоящем слиянии гейтов не было бы тоже.
#
# ГРАНИЦА. Гейты судят ИНДЕКС, а он после ребейза тот же, что будет при
# настоящем слиянии, — поэтому предпроверка честная, а не похожая. Но это
# ПРЕДпроверка, не замена: настоящий хук при слиянии зовётся снова, и если
# между ними что-то изменится (дрейф ловится ниже отдельно), решит он.
