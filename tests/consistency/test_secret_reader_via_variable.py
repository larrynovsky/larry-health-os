"""Оракул: читатель секрета, собранный через переменную, перестал быть невидимым.

ЗАМЕР, РАДИ КОТОРОГО ЭТО ЕСТЬ (16.09.2026, BL-SECRET-READER-LITERAL-1).
`check_contracts` печатал WARN «секреты без читателя» на ШЕСТИ именах, и пять из них
были ЛОЖНЫМИ: `notify._email_settings` читает smtp_host/smtp_user/smtp_password/
smtp_port/email_to через локальную переменную (`s = secrets or owner_secrets_dir()`,
дальше `s / "smtp_host"`), а сканер видел только литералы. Предупреждение, где пять
строк из шести заведомо ложные, перестают читать — тот же яд, что ложно-красный датчик.

ГРАНИЦА, КОТОРУЮ СТЕРЕГУТ ТЕСТЫ НИЖЕ. Форма «переменная / "имя"» засчитывается только
когда выполнены ОБА условия: файл работает с каталогом секретов И имя объявлено в
реестре. Без первого любой `cfg / "logs"` выглядел бы чтением секрета; без второго
форма ловит 77 пар вне реестра (замер 16.09) и спрятала бы МЁРТВЫЙ секрет — ровно то,
ради чего WARN существует (`read_token`, найден 02.09; выведен из реестра 21.09 —
в фикстуре ниже он остаётся как образец мёртвого имени).
"""
from __future__ import annotations

import sys
from pathlib import Path

import pytest

pytestmark = pytest.mark.consistency
ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from secrets_paths import (SECRET_SCOPE, referenced_secret_names,  # noqa: E402
                           referenced_via_variable)

РЕЕСТР = {"smtp_host": "owner", "telegram_token": "tenant", "read_token": "owner"}

ФАЙЛ_С_СЕКРЕТАМИ = '''
def _email_settings(secrets=None):
    s = secrets or owner_secrets_dir()
    host = (s / "smtp_host").read_text().strip()
    return host
'''

ФАЙЛ_БЕЗ_СЕКРЕТОВ = '''
def build(cfg):
    return (cfg / "smtp_host").read_text()
'''


def test_чтение_через_переменную_засчитывается():
    """Главное утверждение: ложные пять строк из WARN ушли."""
    assert referenced_via_variable([ФАЙЛ_С_СЕКРЕТАМИ], РЕЕСТР) == {"smtp_host"}


def test_файл_без_каталога_секретов_не_считается_читателем():
    """Иначе `path / "что-нибудь"` где угодно в проекте выглядел бы чтением секрета."""
    assert referenced_via_variable([ФАЙЛ_БЕЗ_СЕКРЕТОВ], РЕЕСТР) == set(), (
        "форма засчитана в файле, который с секретами не работает — "
        "так WARN спрячет мёртвый секрет")


def test_имя_вне_реестра_не_считается():
    """Второе сужение: замер 16.09 — без него форма ловит 77 пар вне реестра."""
    исходник = ФАЙЛ_С_СЕКРЕТАМИ.replace("smtp_host", "logs")
    assert referenced_via_variable([исходник], РЕЕСТР) == set()


def test_мёртвый_секрет_остаётся_видимым():
    """⭐ НЕГАТИВНЫЙ КОНТРОЛЬ НА СМЫСЛ ПРАВКИ.

    Смягчение сканера имеет цену: если бы форма засчитывалась без сужений, имя,
    которое НИКТО не читает, всё равно нашлось бы «читателем» и WARN замолчал бы
    именно там, где он единственный. Проверяем на живом примере: `read_token`
    объявлен, в исходнике-читателе не упоминается — и обязан остаться ненайденным.
    """
    найдено = (referenced_secret_names([ФАЙЛ_С_СЕКРЕТАМИ])
               | referenced_via_variable([ФАЙЛ_С_СЕКРЕТАМИ], РЕЕСТР))
    без_читателя = sorted(n for n in РЕЕСТР if n not in найдено)
    assert "read_token" in без_читателя, (
        "мёртвый секрет перестал быть виден — смягчение сканера съело его предмет")


def test_живой_репозиторий_без_мёртвых_секретов():
    """Живая лента, а не стенд: WARN схлопнулся с шести имён до одного (16.09), а после
    вывода `read_token` из реестра (21.09) — до нуля. Смысл пустоты держит негативный
    контроль выше: сканер по-прежнему видит мёртвое имя, просто в реестре его больше нет.

    Числа не из памяти — они пересчитываются здесь же. Если их станет больше,
    это либо новый мёртвый секрет (находка), либо новая форма чтения (чинить сканер).
    """
    from secrets_paths import GUARDED_SUFFIXES
    # Периметр — ровно тот же, что у check_contracts: rglob от корня ЭТОГО дерева.
    # Первая редакция отбрасывала пути с `.worktrees`, и в дереве нити (оно само
    # лежит в ~/.worktrees/...) отбросила ВСЕ файлы: читателей ноль, «без читателя»
    # восемнадцать. Тест покраснел и был прав — фильтр судил путь дерева, а не файл.
    исходники = [f.read_text(encoding="utf-8", errors="ignore")
                 for suf in GUARDED_SUFFIXES for f in ROOT.rglob(f"*{suf}")
                 if "__pycache__" not in str(f)]
    объявлено = {n for n, sc in SECRET_SCOPE.items() if sc != "state"}
    без_читателя = sorted(объявлено - (referenced_secret_names(исходники)
                                       | referenced_via_variable(исходники)))
    assert без_читателя == [], (
        f"секрет без читателя в реестре: {без_читателя} — новый мёртвый секрет (находка) "
        f"или новая форма чтения (чинить сканер)")
