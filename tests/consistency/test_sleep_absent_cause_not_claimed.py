"""Одна пропущенная ночь — отсутствие ДАННЫХ; причину система не называет.

Что стерегут. 14.09 в брифе жила строка «Oura не прислал ночь (кольцо не
синхронизировало)» — утверждение о механизме, которого никто не наблюдал.
Замер, из-за которого её и завели в остаток нити: ночь пропала при НАДЕТОМ
кольце, причиной был лаг выгрузки Oura. То есть владельцу каждый такой день
объявляли причину, выбранную за него, и она была ложной. Класс тот же, что
у `gp_context.absent_claims_contradicted`: «не видел» превращается в «не было».

Где проходит граница. Право назвать причину даёт УЛИКА, а не догадка: N ночей
молчания подряд — это уже улика, и ветка эскалации ею пользуется, хеджируя
(«похоже, кольцо снято или разряжено»). Одиночная ночь улики не даёт, и там
причина не называется вовсе.

Поэтому правило сторожа сформулировано не как «запрещённые слова», а как
«упоминание кольца обязано нести хедж»: оно переживает переписывание текста
и не запрещает законную ветку. Позитивный контроль обязателен — без него
сторож зеленел бы на блоке, где про кольцо не сказано вообще ничего.

Второй дом (`morning_report.py`) удалён 30.09 — сторож судит один.
"""
from __future__ import annotations

import pathlib
import re

import pytest

import gp_agent

pytestmark = pytest.mark.consistency

_RING = re.compile(r"кольц", re.IGNORECASE)
_HEDGE = re.compile(r"похоже", re.IGNORECASE)
# «синхронизировал(о|ось)» — утверждение о ЧУЖОМ механизме (устройство, выгрузка),
# наблюдать который отсюда нечем ни в одной ветке.
_SYNC_CLAIM = re.compile(r"синхронизир", re.IGNORECASE)


def _sleep_absent_claims() -> list[str]:
    """Утверждения канала sleep_absent — по одному на вызов `context_lines.append`.

    Режем ТЕКСТОМ, а не обходом AST, сознательно: реестр каналов и его периметр
    уже вычисляет `test_brief_channel_registry`, и второй экземпляр того обхода
    разъехался бы с первым молча. Здесь нужен один свой участок, а не периметр.

    Единица суждения — ВЫЗОВ, а не строка файла (замер 14.09: первая редакция
    судила построчно и назвала ложью законную ветку — её хедж «похоже» стоял на
    предыдущей физической строке, потому что литерал перенесён). Утверждение,
    разорванное переносом, остаётся одним утверждением.

    Комментарии выброшены до склейки: они объясняют код читателю, а не едут
    владельцу в промпт, и судить их значило бы запретить это самое объяснение.
    """
    src = pathlib.Path(gp_agent.__file__).read_text(encoding="utf-8")
    start = src.index("# channel: sleep_absent")
    rest = src[start + 1:]
    nxt = rest.find("# channel:")
    block = rest[:nxt] if nxt != -1 else rest
    code = "\n".join(ln for ln in block.splitlines() if not ln.strip().startswith("#"))
    return [c for c in code.split("context_lines.append(")[1:]]


def test_single_missing_night_does_not_claim_a_cause():
    """⭐ Любое упоминание кольца в канале живёт только рядом с хеджем."""
    unhedged = [c.strip()[:120] for c in _sleep_absent_claims()
                if _RING.search(c) and not _HEDGE.search(c)]
    assert not unhedged, (
        "в канале sleep_absent причина отсутствия сна утверждается без хеджа — "
        "система называет владельцу причину, которой не наблюдала: " + str(unhedged[:3]))


def test_escalation_branch_still_names_the_hedged_cause():
    """Позитивный контроль: ветка с уликой (N ночей) причину НАЗЫВАЕТ, хеджируя.
    Без него предыдущий тест зеленел бы на блоке, где про кольцо нет ни слова."""
    hedged = [c for c in _sleep_absent_claims() if _RING.search(c) and _HEDGE.search(c)]
    assert hedged, ("ветка эскалации перестала называть причину — тогда первый тест "
                    "зелен потому, что проверять стало нечего")
