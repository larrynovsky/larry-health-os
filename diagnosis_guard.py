"""diagnosis_guard.py — страж рецидива зашитого диагноза (нить diagnosis-hardcode).

Северная звезда: «человек с диагнозом/медисторией — в ДАННЫХ; в коде и промпте
НИКОГДА не зашито». Phase 1 (2026-07-17) вычистил онко-РАМКУ из промпт-билдеров
(hai_core / consult_prep / wellally / lifestyle-коучи). Этот модуль — ЧИСТОЕ ядро
детектора рецидива: скан конкретных снятых литералов в конкретных файлах.

Почему отдельный модуль, а не функция в integrity_tests:
  integrity_tests выполняет все check(...) на импорте (сайд-эффекты + импорт
  health_db с §8-гардом пути). Чистое ядро здесь импортируется юнит-тестом
  дёшево, без запуска всей ночной сюиты. Публичный вход — один: scan().

Scope НАМЕРЕННО узкий: это не общий линтер §9 («любое осмысленное число/имя —
данные»), а якорь на уже-починенные сайты — «чтобы не вернулось» (RST).

Принцип владельца (2026-07-17): НИЧЕГО в промпте не должно быть диагнозозависимым —
важность маркеров/тем приходит из истории болезни тенанта, не из литерала. Поэтому
в список включены и пограничные, ПОСЛЕ починки их сайтов: «онкомаркер» (consult_prep —
значимость маркеров теперь выводится из истории болезни) и слова-отпечатки терапии (lifestyle —
заменены на «сердечные ограничения»; сами слова — в приватном словаре, класс treatment). Правило добавления термина:
сперва почини живой сайт, ПОТОМ добавь термин — иначе страж падёт на живой строке.
"""

from pathlib import Path

import pii_census as _pii_census

_TREATMENT = [t.lower() for t in _pii_census.literals(["treatment"])]

# rel-путь → список запрещённых литералов (case-insensitive, substring).
SITES: dict[str, list[str]] = {
    # .py: сканируем код БЕЗ комментариев (line.split('#')[0]) — иначе tombstone-
    # комментарии дают ложный хит.
    "hai_core.py":         ["онкологический статус", 'f"диагноз:'],
    "consult_prep.py":     ["статуса ремиссии", "в ремиссии", "онкомаркер"],
    "wellally_consult.py": ["пациент в ремиссии"],
    # A3 (фамилии врачей и владельца в health_db) с 2026-09-23 стережёт pii_census по ВСЕЙ
    # публичной зоне, включая комментарии: литералы в этом списке сами ехали бы в открытый
    # репозиторий. Здесь — только диагнозозависимые общие слова, не личные.
    # A2-full: drug-search вынесен в БД (cpic_reference_db). Ре-хардкод фенотип-списка
    # вернул бы диплотипы в код (утечка генотипа всем тенантам). Комменты
    # срезаются (# ...), tombstone безопасен. Сами диплотипы тенантов — в приватном
    # словаре (класс genotype): литерал в стороже публиковал бы то, что он стережёт
    # (решение владельца 30.09 «генотип прятать»). Нет словаря — стережётся только имя константы.
    "dashboard_routers/views.py": ["_cpic_drug_gene"] + [t.lower() for t in _pii_census.literals(["genotype"])],
    # .md: весь файл — промпт, сканируем целиком. Отпечатки терапии тенанта — класс treatment
    # приватного словаря (решение владельца 30.09 «подробности лечения прятать»): литерал здесь
    # публиковал бы то, что страж стережёт.
    # (диагнозозависимо, реш. владельца 2026-07-17: ничего в промпте не должно быть диагнозозависимым).
    "specialists/lifestyle_sleep.md":    ["онколог", "ремисси", "после лечения"] + _TREATMENT,
    "specialists/lifestyle_movement.md": ["онколог", "ремисси", "после лечения"] + _TREATMENT,
    "specialists/lifestyle_stress.md":   ["онколог", "ремисси", "после лечения"] + _TREATMENT,
    "specialists/lifestyle_energy.md":   ["онколог", "ремисси", "после лечения"] + _TREATMENT,
    # symptom-intake (WP2): движок домен-агностичен; промпт и код НЕ называют
    # областей медицины/болезней (§9: домен — данные в visual_domains, не в коде).
    # Сентинелы — образцы конкретных диагнозов/зон, которые не должны просочиться.
    "specialists/symptom_intake_system.txt": ["меланом", "дерматит", "кариес", "конъюнктивит", "экзема"],
    "symptom_intake.py":                     ["меланом", "дерматит", "кариес", "конъюнктивит", "экзема"],
}


def scan(root: Path | str | None = None) -> list[str]:
    """Возвращает список нарушений вида 'файл:строка: «термин»'. Пусто = чисто.

    Отсутствие сайт-файла — тоже нарушение (страж не может проверить сайт →
    liveness: тихо-удалённый файл не должен давать ложно-зелёное, ср. §14)."""
    base = Path(root) if root else Path(__file__).resolve().parent
    hits: list[str] = []
    for rel, terms in SITES.items():
        p = base / rel
        if not p.exists():
            hits.append(f"{rel}: ФАЙЛ ОТСУТСТВУЕТ (страж не может проверить сайт)")
            continue
        is_py = rel.endswith(".py")
        for i, raw in enumerate(p.read_text(encoding="utf-8").splitlines(), 1):
            line = raw.split("#", 1)[0] if is_py else raw
            low = line.lower()
            for t in terms:
                if t in low:
                    hits.append(f"{rel}:{i}: «{t}»")
    return hits
