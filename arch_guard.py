# ── Главный поток ─────────────────────────────────────────────────────────────

def main(argv=None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--lang", choices=("ru", "en"), default="ru")
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--pre-commit", action="store_true")
    args = parser.parse_args(argv)
    global DRY_RUN
    DRY_RUN = args.dry_run
    try:
        return _run(args.lang)
    finally:
        if args.lang == "en":
            print("untranslated: 0")


def _run(lang):
    today = datetime.now().strftime("%Y-%m-%d")  # time-inject: ok

    # 1. Строим текущий граф
    current_graph = build_graph()

    if DRY_RUN:
        print("=== ТЕКУЩИЙ ГРАФ ЗАВИСИМОСТЕЙ ===")
        print(format_graph(current_graph, lang))
        return 0

    # 2. Загружаем сохранённый снимок
    # Independent cursors: generating RU must not consume an EN event (or vice versa).
    cache = GRAPH_CACHE if lang == "ru" else GRAPH_CACHE.with_name(".arch_graph.en.json")
    stored_graph: dict = current_graph if lang == "en" else {}
    if cache.exists():
        try:
            stored_graph = json.loads(cache.read_text())
        except Exception:
            stored_graph = {}

    # 3. Сравниваем
    changes = diff_graphs(stored_graph, current_graph, lang)

    if not changes and lang == "ru":
        print("arch_guard: граф не изменился.")
        return 0

    # 4. Документируем
    summary = "; ".join(changes[:4])
    if len(changes) > 4:
        summary += _TEXT[lang]["more"].format(count=len(changes) - 4)

    print(f"arch_guard: обнаружены изменения архитектуры ({len(changes)}):")
    for c in changes:
        print(f"  • {c}")

    written = update_arch_snapshot(current_graph, summary, today, lang)
    if lang == "en" and not written:
        return 2  # Do not consume an event before the English document accepts it.

    # 5. Сохраняем новый снимок
    if not DRY_RUN:
        cache.write_text(json.dumps(current_graph, indent=2, ensure_ascii=False))

    # 6. Предупреждения о незарегистрированных модулях
    warns = check_unregistered(current_graph)
    for w in warns:
        print(w)

    return 0


if __name__ == "__main__":
    try:
        code = main()
    except Exception as e:
        _log(f"ERROR: {e}")
        # В режиме хука — никогда не блокируем коммит
        code = 0
    sys.exit(0 if PRE_COMMIT else code)
