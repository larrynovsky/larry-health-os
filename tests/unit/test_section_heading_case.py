"""Заголовок секции — это НАЗВАНИЕ, а не результат и не референс.

read_section должен отличать название секции от слов результата и референса.
Иначе читатель принимает содержимое строки за метод исследования.
Тесты именованы утверждениями о структуре бланка.
"""


def _sec(text, names=(), units=(), values=()):
    import lab_specimen
    return [h for _i, h in lab_specimen.sections(text, names, units, values)]


ШАПКА = "Показатель Результат Референс Ед.изм.\n"


def test_название_раздела_с_прописной_остаётся():
    txt = ШАПКА + "Стероидный профиль (ЖХ-МС/МС)\nКортизол\n120\n"
    assert "Стероидный профиль (ЖХ-МС/МС)" in _sec(txt, names={"Кортизол"})


def test_результат_качественного_анализа_заголовком_не_становится():
    # «не обнаружено» печатается в колонке результата; строчная буква и есть
    # признак, отличающий его от названия раздела.
    txt = ШАПКА + "не обнаружено\nЛямблии\nобнаружено\n"
    assert _sec(txt, names={"Лямблии"}) == []


def test_референсный_диапазон_заголовком_не_становится():
    txt = ШАПКА + "10^9-10^12\nБифидобактерии\nне более 10^4\n"
    assert _sec(txt, names={"Бифидобактерии"}) == []


def test_строка_начинающаяся_с_цифры_заголовком_не_становится():
    txt = ШАПКА + "10^12\nЛактобактерии\n"
    assert _sec(txt, names={"Лактобактерии"}) == []


def test_правило_не_трогает_метод_из_имени_строки():
    """«по Вестергрену» — настоящий метод, но приходит из ИМЕНИ строки
    (ступень read_name), а не из секции. Правило прописной его не касается:
    здесь проверяется, что оно и не должно его ловить как заголовок."""
    txt = ШАПКА + "по Вестергрену\nСОЭ\n12\n"
    assert "по Вестергрену" not in _sec(txt, names={"СОЭ"})


if __name__ == "__main__":
    import lab_specimen
    orig = lab_specimen.sections

    # Негативный контроль: без правила прописной мусор ВОЗВРАЩАЕТСЯ в заголовки.
    # Мутация — подмена предиката на всегда-истинный через исходник невозможна,
    # поэтому проверяем прямым утверждением о работе правила на живом входе.
    txt = ШАПКА + "не обнаружено\nЛямблии\n"
    before = orig(txt, {"Лямблии"}, (), ())
    assert before == [], f"правило не работает: {before}"
    txt_ok = ШАПКА + "Онкомаркеры\nCEA\n"
    assert [h for _i, h in orig(txt_ok, {"CEA"}, (), ())] == ["Онкомаркеры"], \
        "правило зарезало настоящий заголовок — позитивный контроль красный"
    for fn in (test_название_раздела_с_прописной_остаётся,
               test_результат_качественного_анализа_заголовком_не_становится,
               test_референсный_диапазон_заголовком_не_становится,
               test_строка_начинающаяся_с_цифры_заголовком_не_становится,
               test_правило_не_трогает_метод_из_имени_строки):
        fn()
    print("✅ правило режет мусор и НЕ режет настоящие заголовки")
