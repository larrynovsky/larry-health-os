"""
tests/unit/test_lab_promote_glossary.py — характеризация F-14: глоссарий у промоушена отключён.

Нить: ремонт `data_ingestion`, аудит `data_ingestion@2026-07-27-b2306c4`, план v7 Область 2.
Фаза A (A18). Красные до ремонта Области 2.

ПОПРАВКА К АУДИТУ (замерено чтением кода, а не пересказом). Аудит формулирует F-14 как
«`lab_promote` зовёт `get_confirmed_aliases(0)` — формата нет, пустота = отказ». Замер:
разрыв ГЛУБЖЕ и починка «подставить правильный format_id» его не закроет.

  · `lab_promote.py:145` действительно берёт глоссарий константой `0`. На живом каноне
    (замер 2026-07-28) `lab_formats` содержит id=1 (synevo) и id=4242 (imd_berlin);
    строк с `format_id=0` — ноль. То есть вызов возвращает `{}` ВСЕГДА, а `except
    Exception: aliases = {}` рядом гасит и любую другую причину пустоты;
  · но `_canon(r, aliases)` (`lab_promote.py:48`) **не обращается к `aliases` ни разу**.
    Параметр принят и проигнорирован; имя выводится из `lab_canon` и модельного
    `canonical_name`. Глоссарий отключён СТРУКТУРНО, а не арифметически.

ПОЧЕМУ ПОРЯДОК ПОЧИНКИ ВАЖЕН (главное, что дал этот замер). Если «починить F-14» первым —
подставить настоящий format_id и подключить `aliases` к `_canon` — расхождение из A11
(11 подтверждённых пар из 71, где глоссарий и `lab_canon` называют аналит по-разному)
немедленно станет ЖИВЫМ: промоушен начнёт писать `Cholesterol`, прямой путь — `Cholesterol_Total`,
и канон расщепится по тому же механизму, что уже расщепил немецкую панель. Сейчас этого не
происходит ровно потому, что глоссарий отключён.
**Вывод: F-09/A11 (один дом имени) закрывается ДО F-14, а не после.**

ЧЕГО НЕ ДОКАЗЫВАЮТ:
  · какое имя правильное — вердикт владельца-методолога;
  · поведение `plan()` целиком: тесты бьют по `_canon` и по выбору формата, а не по
    промоушену как процессу. Промоушен `--execute` в тестах не вызывается никогда.

Изоляция: чистые вызовы + fixture `db` (tmp-файл со схемой). Ни сети, ни канона,
ни уведомлений.
"""
from __future__ import annotations

import pytest

import labs_db
import lab_promote


@pytest.mark.xfail(strict=True, reason=(
    "F-14: `_canon` принимает глоссарий аргументом и не читает его ни разу — "
    "подтверждение человека отключено структурно. Зелёным станет в Области 2."))
def test_a18_1_canon_follows_the_confirmed_glossary():
    """A18.1 — переданный глоссарий обязан влиять на итоговое имя.

    Человек подтвердил в `lab_name_aliases`, что `Total Cholesterol` — это `Cholesterol`.
    Промоушен получает этот глоссарий аргументом. Значит имя строки обязано следовать
    подтверждению, а не выводиться заново.

    Baseline: `_canon` игнорирует аргумент и отвечает `Cholesterol_Total` (из `lab_canon`).
    Красный здесь означает не «lab_canon неправ», а «подтверждение человека ни на что
    не влияет» — см. A11 про то, что домов два.

    ОРАКУЛ объявлен до тела: результат равен значению из глоссария.
    """
    aliases = {"total cholesterol": "Cholesterol"}
    row = {"raw_name": "Total Cholesterol", "canonical_name": None}
    got = lab_promote._canon(row, aliases)
    assert got == "Cholesterol", (
        f"глоссарий утверждает 'Cholesterol', промоушен вывел {got!r} — переданный "
        "аргумент `aliases` не читается функцией ни разу, глоссарий отключён структурно"
    )


@pytest.mark.xfail(strict=True, reason=(
    "F-14: глоссарий запрашивается константой `format_id=0`, а id форматов "
    "непредсказуемы (synevo=1, imd_berlin=4242). Зелёным станет в Области 2."))
def test_a18_2_glossary_is_requested_for_an_existing_format(db):
    """A18.2 — глоссарий запрашивается для формата, который существует.

    `lab_formats.id` непредсказуемы (`synevo=1`, `imd_berlin=4242`), поэтому константа
    в коде не может быть верной ни для одного формата, кроме случайно совпавшего.
    Тест сеет формат с подтверждённым алиасом и спрашивает глоссарий тем же способом,
    что и промоушен, — константой `0`.

    ОРАКУЛ объявлен до тела: глоссарий непуст, когда в базе есть подтверждённый алиас.

    ГРАНИЦА: тест бьёт по способу обращения, а не по `plan()` целиком. Он не докажет,
    что промоушен ПРИМЕНИТ полученный глоссарий, — это отдельно, в A18.1.
    """
    db.execute("INSERT INTO lab_formats(id, name) VALUES (4242, 'imd_berlin')")
    db.execute(
        "INSERT INTO lab_name_aliases(format_id, raw_name, canonical, confirmed) "
        "VALUES (4242, 'Holo-TC', 'Holotranscobalamin', 1)"
    )

    _PROMOTE_FORMAT_ID = 0   # ровно то, что стоит в lab_promote.py:145
    aliases = labs_db.get_confirmed_aliases(_PROMOTE_FORMAT_ID)

    assert aliases, (
        "в базе есть подтверждённый алиас, но промоушен получил пустой глоссарий: "
        f"он спрашивает format_id={_PROMOTE_FORMAT_ID}, а форматы имеют "
        "непредсказуемые id (synevo=1, imd_berlin=4242) — константа не может быть верной"
    )
