"""
tests/unit/test_recognizer_reconcile_scope.py — характеризация F-13 и границы ключа слияния.

Нить: ремонт `data_ingestion`, аудит `data_ingestion@2026-07-27-b2306c4`, план v7 Область 2.
Фаза A (A17). Красные до ремонта Области 2.

ЧТО ОХРАНЯЕТ. `lab_recognizer._reconcile` сливает два независимых прохода зрения (opus +
sonnet) и ставит строке `confidence`. Сегодня (`lab_recognizer.py:241-249`) согласие
считается ТОЛЬКО по `value`, а всё остальное — `unit`, `ref_low`, `ref_high`, `raw_name`,
`canonical_name` — берётся из ОДНОГО прохода (`base = dict(a or b)`) и не сверяется ни с чем.
При этом `confidence="high"` ставится СТРОКЕ ЦЕЛИКОМ.

Почему это не косметика — точная цепочка, прослеженная по коду (а не правдоподобная):
`value_agreement` (только value) → `stats["disagreements"]`/`stats["singles"]` →
`lab_backfill._route`: `full_agree and verdict=="green"` → `review="auto"`.
Маршрутизатор читает АГРЕГАТ `value_agreement`, а не построчный `confidence`, и решает судьбу
ВСЕГО ДОКУМЕНТА. Значит строка, где два прохода прочитали 5.2 mg/dL и 5.2 mmol/L, не просто
получает «high» — она не мешает документу целиком уехать мимо человека. А это разные величины
в ~18 раз (`lab_canon._TO_CONVENTIONAL["Glucose"]`). Согласие по значению выдаётся за
согласие по измерению, и цена ошибки — документ, а не строка.

Поле переименовано 29.07.2026: было `agreement`, стало `value_agreement`. Имя врало — оно
сравнивало только `value`, — а рядом теперь стоят `unit_agreement` и `ref_agreement`, на фоне
которых прежнее имя читалось бы как «согласие в целом», то есть врало бы сильнее. Колонка в
`lab_results_staging` переименована тем же ALTER, данные сохранены.

A17.3 про другое, но про тот же ключ. Слияние идёт по `_key(t)` =
`canonical_name or raw_name.lower()`. Если один проход узнал аналит в словаре, а второй
вернул canonical_name=null, ключи
РАЗНЫЕ, и одна физическая строка документа становится ДВУМЯ строками со статусом `single`.
То есть провал словаря превращается в удвоение строк, а не в честное «не узнал».

Частота расхождений измерима только при сохранении полей обоих проходов.
Изменение маршрута требует этих измерений; передача в недействующую
очередь ревью не заменяет исправление механизма.

Поэтому A17.1/A17.2 сменили ОРАКУЛ, а не были «починены»: раньше они требовали, чтобы
расхождение по единице ломало `value_agreement`; теперь требуют, чтобы оно ПОПАДАЛО В ДАННЫЕ
(`unit_agreement`/`ref_agreement`/`field_evidence`). Прежние node-id вычеркнуты из
`tests/consistency/test_data_ingestion_expected_red.py`. A17.4 — замок на вторую половину
решения: маршрут обязан остаться прежним, пока владелец не увидит числа.

ЧЕГО НЕ ДОКАЗЫВАЮТ:
  · что маршрут ПРАВИЛЬНЫЙ. A17.4 фиксирует текущее поведение как ОТЛОЖЕННОЕ решение,
    а не как желаемый конец: покраснеет он и тогда, когда кто-то заведёт расхождения в
    маршрут ОСОЗНАННО — в этом и смысл, решение должно быть названо, а не втечь правкой;
  · что число расхождений по единице ТОЧНО. `_unit_key` снимает косметику через
    `lab_canon._norm_unit`, но не знает всех нотаций — счёт будет ЗАВЫШЕН, и потому
    сырая пара кладётся в `field_evidence` для проверки глазами;
  · корректность самих значений относительно документа: сверяется внутренняя
    согласованность двух проходов, а не документ.

Изоляция: чистые вызовы `_reconcile`, без сети, БД и моделей.
"""
from __future__ import annotations

import json

import pytest

import lab_recognizer


def _t(**kw) -> dict:
    """Строка прохода зрения с дефолтами; в тесте переопределяем только спорное поле."""
    base = {"canonical_name": "Glucose", "raw_name": "Glucose", "value": 5.2,
            "unit": "mg/dL", "ref_low": 3.9, "ref_high": 5.5, "doc_flag": "N",
            "panel": "chemistry", "date": "2026-01-15", "page": 1}
    base.update(kw)
    return base


def test_a17_1_unit_disagreement_is_recorded():
    """A17.1 — расхождение проходов по ЕДИНИЦЕ попадает в данные, а не пропадает.

    5.2 mg/dL и 5.2 mmol/L — не одно измерение, а два разных, отличающихся в ~18 раз
    (`lab_canon._TO_CONVENTIONAL["Glucose"]`). До 29.07.2026 второй проход просто
    выбрасывался: `base = dict(a or b)` брал единицу из одного прохода, и о том, что
    другой прочитал иное, не оставалось следа НИГДЕ — ни в строке, ни в staging.

    ОРАКУЛ объявлен до тела: `unit_agreement == "disagree"` И сырая пара лежит в
    `field_evidence`. Улика обязательна: число расхождений без возможности посмотреть
    на пары — это вера, а не замер.
    """
    out = lab_recognizer._reconcile([_t(unit="mg/dL")], [_t(unit="mmol/L")])
    assert len(out) == 1, f"ожидалась одна слитая строка, получено {len(out)}"
    r = out[0]
    assert r["unit_agreement"] == "disagree", (
        f"проходы разошлись в ЕДИНИЦЕ (mg/dL vs mmol/L), а слияние записало "
        f"unit_agreement={r['unit_agreement']!r} — расхождение снова невидимо"
    )
    ev = json.loads(r["field_evidence"] or "{}")
    assert ev.get("unit") == ["mg/dL", "mmol/L"], (
        f"вердикт есть, а улики нет: field_evidence={r['field_evidence']!r}. "
        "Без сырой пары завышение из-за нотаций не отличить от настоящего расхождения"
    )


def test_a17_2_reference_disagreement_is_recorded():
    """A17.2 — расхождение референсного интервала тоже попадает в данные.

    Референс определяет, будет ли значение помечено как отклонение. Проходы разошлись
    в верхней границе — значит один из них прочитал не ту строку таблицы, и какая из
    двух попала в `base`, решал порядок словаря, а не качество чтения.

    ОРАКУЛ объявлен до тела: `ref_agreement == "disagree"` и обе границы в улике.
    """
    out = lab_recognizer._reconcile([_t(ref_high=5.5)], [_t(ref_high=99.0)])
    assert len(out) == 1, f"ожидалась одна слитая строка, получено {len(out)}"
    r = out[0]
    assert r["ref_agreement"] == "disagree", (
        f"проходы разошлись в РЕФЕРЕНСЕ (5.5 vs 99.0), а слияние записало "
        f"ref_agreement={r['ref_agreement']!r}"
    )
    ev = json.loads(r["field_evidence"] or "{}")
    assert ev.get("ref") == [[3.9, 5.5], [3.9, 99.0]], (
        f"обе границы обязаны лежать в улике, получено {r['field_evidence']!r}"
    )


def test_a17_4_field_disagreement_does_not_change_route():
    """A17.4 — ЗАМОК на вторую половину решения владельца: маршрут не тронут.

    Это не «так правильно». Это «так решено 29.07.2026 и до появления чисел менять
    нельзя молча». Цепочка, которую замок держит: `stats["disagreements"]`/`["singles"]`
    → `lab_backfill._route` → `review_status`. Расхождение по единице в эти два числа
    НЕ входит, поэтому документ с полным согласием значений по-прежнему уезжает в `auto`.

    Когда владелец увидит частоту и решит иначе — этот тест покраснеет. Так и задумано:
    он требует, чтобы решение было НАЗВАНО, а не втекло вместе с правкой маршрута.

    ОРАКУЛ объявлен до тела: `stats["disagreements"] == 0` и `_route(green, stats) == "auto"`
    при расхождении единиц.
    """
    import lab_backfill

    out = lab_recognizer._reconcile([_t(unit="mg/dL")], [_t(unit="mmol/L")])
    assert out[0]["unit_agreement"] == "disagree", "предпосылка теста не выполнена"

    # stats собирается в recognize(); здесь воспроизводим ровно те две строки, которые
    # читает маршрут — вызывать recognize() нельзя, он ходит в модели.
    stats = {
        "disagreements": sum(1 for t in out if t["value_agreement"] == "disagree"),
        "singles": sum(1 for t in out if t["value_agreement"] == "single"),
    }
    assert stats == {"disagreements": 0, "singles": 0}, (
        f"расхождение по единице просочилось в агрегаты маршрута: {stats}. "
        "Если это сделано осознанно — вычеркни A17.4 и назови решение в плане нити"
    )
    assert lab_backfill._route({"status": "green", "count": 0}, stats) == "auto", (
        "маршрут изменился: документ с расхождением ТОЛЬКО по единице поехал к человеку. "
        "Решение владельца 29.07 было обратным — сначала числа, потом маршрут"
    )


@pytest.mark.parametrize("u1,u2,expect", [
    ("mg/dL", "mg/dl", "agree"),        # регистр — косметика
    ("ммоль/л", "mmol/L", "agree"),     # кириллица — та же единица, _norm_unit её знает
    ("10e3/ul", "10^3/uL", "agree"),    # нотация счётных единиц
    ("mg/dL", "mmol/L", "disagree"),    # РАЗНЫЕ величины — расхождение настоящее
    ("mg/dL", "", "single"),            # один проход единицу не вернул
    ("", "", "absent"),                 # единицы нет ни у кого — свойство бланка
])
def test_a17_5_unit_verdict_separates_cosmetics_from_measurement(u1, u2, expect):
    """A17.5 — позитивный контроль: вердикт по единице ловит РАЗНИЦУ, а не написание.

    Без этого теста замер деградирует одинаково в обе стороны и незаметно: слишком
    слабая нормализация превращает «mg/dL vs mg/dl» в расхождение и топит настоящие
    случаи в шуме; слишком сильная — склеит mg/dL с mmol/L и обнулит весь смысл.

    `single` и `absent` разделены намеренно: первое — дефект ансамбля (один проход поле
    потерял), второе — свойство документа. Слить их значит потерять ровно то различие,
    ради которого колонки и заводились.
    """
    out = lab_recognizer._reconcile([_t(unit=u1)], [_t(unit=u2)])
    assert len(out) == 1, f"ожидалась одна слитая строка, получено {len(out)}"
    assert out[0]["unit_agreement"] == expect, (
        f"{u1!r} vs {u2!r}: ожидался вердикт {expect!r}, получен "
        f"{out[0]['unit_agreement']!r} (улика: {out[0]['field_evidence']!r})"
    )


def test_a17_3_unknown_canonical_does_not_split_one_row_into_two():
    """A17.3 — если один проход узнал аналит, а другой нет, строка остаётся ОДНОЙ.

    Ключ слияния — `canonical_name or raw_name.lower()`. Проход, вернувший `null`
    (имени нет в словаре — A10 показывает, что таких 23 из 71 подтверждённых),
    попадает под ДРУГОЙ ключ. Одна строка документа становится двумя, обе `single`,
    обе `low` — и обе поедут в staging как отдельные аналиты.

    То есть дыра в словаре не просто теряет имя, она РАЗМНОЖАЕТ строки. Это тот же
    механизм, что расщепил немецкую панель.

    ОРАКУЛ объявлен до тела: ровно одна строка на выходе.
    """
    known = _t(canonical_name="Holotranscobalamin", raw_name="Holo-TC")
    unknown = _t(canonical_name=None, raw_name="Holo-TC")
    out = lab_recognizer._reconcile([known], [unknown])
    assert len(out) == 1, (
        f"одна строка документа разошлась на {len(out)} после слияния: "
        f"{[r.get('canonical_name') or r.get('raw_name') for r in out]} — "
        "проход, не узнавший имя, попал под собственный ключ вместо согласования"
    )
    assert out[0]["canonical_name"] == "Holotranscobalamin", (
        f"строки слились, но canonical_name потерян ({out[0]['canonical_name']!r}) — "
        "основой взят проход, который аналит НЕ узнал; порядок проходов не должен "
        "решать, сохранится ли имя"
    )
    # Обратный порядок проходов обязан дать тот же результат — иначе слияние
    # зависит от того, какая модель отвечала первой.
    back = lab_recognizer._reconcile([unknown], [known])
    assert len(back) == 1 and back[0]["canonical_name"] == "Holotranscobalamin", (
        "слияние несимметрично по порядку проходов: "
        f"{[(r.get('canonical_name'), r.get('raw_name')) for r in back]}"
    )
