def test_vcf_plain_and_gz_are_accepted_fastq_and_zipped_vcf_are_not(tmp_path):
    """28.09: VCF полного генома принимается (решение владельца), в том числе .vcf.gz —
    сжатие узнаётся по сигнатуре. VCF внутри zip — нет: распаковка в память на гигабайты."""
    import gzip
    import zipfile
    import genome_intake as gi
    body = "##fileformat=VCFv4.2\n#CHROM\tPOS\tID\n"
    p = tmp_path / "x.vcf"
    p.write_text(body)
    assert gi.sniff(p) == {"format": "vcf", "supported": True, "member": None}
    g = tmp_path / "y.bin"
    with gzip.open(g, "wt") as fh:
        fh.write(body + "chr1\t1\t.\tA\tG\n" * 50_000)   # больше окна сниффа: усечённый gzip
    assert gi.sniff(g) == {"format": "vcf", "supported": True, "member": None}
    z = tmp_path / "v.zip"
    with zipfile.ZipFile(z, "w") as zf:
        zf.writestr("genome.vcf", body)
    assert gi.sniff(z)["supported"] is False and gi.sniff(z)["format"] == "vcf_in_zip"


def test_zip_member_name_never_becomes_a_path(tmp_path):
    """zip-slip: имя члена «../../evil.csv» не должно породить файл вне out."""
    import genome_intake as gi
    src = _tellmegen_zip(tmp_path / "a.zip", member="../../evil.csv")
    k = gi.sniff(src)
    gi._normalize(src, k["member"], tmp_path / "n.txt")
    assert not (tmp_path.parent.parent / "evil.csv").exists()
    assert sorted(x.name for x in tmp_path.iterdir()) == ["a.zip", "n.txt"]


