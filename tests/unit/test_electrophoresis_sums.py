"""Оракул датчика «электрофорез сходится сам с собой».

Датчик заведён потому, что маршрутизация фракций держится на правиле по ИМЕНИ,
а имя — свойство бланка. Тест `test_lab_specialized` ловит поломку правила;
этот датчик обязан поймать поломку бланка, которую правило проглотит молча.

Форма — как у настоящего бланка (шесть фракций, каждая дважды: % и г/л); числа
синтетические, но держат ту же арифметику, на которой стоит датчик:
Albumin 60.2% / 42.1 г/л, Alpha1 4.8 / 3.4, Alpha2 11.1 / 7.8, Beta1 7.0 / 4.9,
Beta2 4.4 / 3.1, Gamma 12.5 / 8.7. Суммы: 100.0% и 70.0 г/л = общий белок.
(До 2026-09-26 здесь лежали числа с бланка владельца — нить marker-guard.)
"""
import integrity_tests as it


D, S = "2020-01-29", "doc:CR/полная панель.pdf"

FULL_PCT = [(D, S, "Albumin", 60.2, "%"), (D, S, "Alpha 1", 4.8, "%"),
            (D, S, "Alpha 2", 11.1, "%"), (D, S, "Beta 1", 7.0, "%"),
            (D, S, "Beta 2", 4.4, "%"), (D, S, "Gamma", 12.5, "%")]
FULL_GL = [(D, S, "Albumin (г/л)", 42.1, "г/л"), (D, S, "Alpha 1 (г/л)", 3.4, "г/л"),
           (D, S, "Alpha 2 (г/л)", 7.8, "г/л"), (D, S, "Beta 1 (г/л)", 4.9, "г/л"),
           (D, S, "Beta 2 (г/л)", 3.1, "г/л"), (D, S, "Gamma (г/л)", 8.7, "г/л")]


# ── целый бланк молчит ──

def test_полный_электрофорез_сходится():
    assert it.electrophoresis_offenders(FULL_PCT + FULL_GL) == []


def test_сумма_ровно_сто_и_ровно_общий_белок():
    """Арифметика первоисточника — она и есть основание датчика."""
    assert round(sum(r[3] for r in FULL_PCT), 1) == 100.0
    assert round(sum(r[3] for r in FULL_GL), 1) == 70.0


# ── позитивный контроль: живой дефект 2026-07-30 ──

def test_потеря_фракции_в_процентах_покраснела():
    """Форма живого дефекта 2026-07-30: пять долей из шести, сумма 100 − альбумин."""
    found = it.electrophoresis_offenders(FULL_PCT[1:] + FULL_GL)
    kinds = {f[2] for f in found}
    assert "сумма долей" in kinds
    assert "число фракций %/масса" in kinds
    assert any(f[3] == 39.8 for f in found)


def test_фракция_уехала_в_другой_дом_покраснела():
    """Класс, ради которого датчик и заведён: имя перестало узнаваться правилом,
    строка ушла в биохимию крови. В спец-панелях остаётся дыра — она и видна.

    2026-08-13 (C5, решение владельца): сценарий сужен — уход ТОЛЬКО массовой
    формы при полной сумме % больше не дефект (форма выводима, см. тест ниже);
    дефектом остаётся уход строки ЦЕЛИКОМ — его выдаёт сумма долей."""
    found = it.electrophoresis_offenders(FULL_PCT[1:] + FULL_GL[1:])
    assert any(f[2] == "сумма долей" for f in found)


# ── граница с другой стороны: молчать там, где всё законно ──

def test_бланк_только_с_процентами_молчит():
    """Лаборатория вправе печатать одни доли. Требовать пару значило бы краснеть
    на здоровом бланке — а датчик, кричащий на норме, перестают читать."""
    assert it.electrophoresis_offenders(FULL_PCT) == []


def test_бланк_только_с_массой_молчит():
    assert it.electrophoresis_offenders(FULL_GL) == []


def test_полные_проценты_без_одной_массы_молчат():
    """⭐ C5 вариант 1 (решение владельца 2026-08-13): при сумме % = 100 каждая
    массовая форма выводима (m = p × общий белок / 100) — недостающая масса не
    потеря. Живой случай: датчик границы постановил, что Albumin (г/л) — одна
    идентичность с каноном, строка ушла из спец-слоя, и парность 6/5 стала бы
    вечным WARN об исполненном вердикте соседнего датчика."""
    assert it.electrophoresis_offenders(FULL_PCT + FULL_GL[1:]) == []


def test_потерянная_доля_не_маскируется_выводимостью():
    """Негативный контроль C5: потеря ДОЛИ рушит сумму (≠100) — и тогда судится
    и сумма, и парность, как раньше. Выводимость не глушит настоящие потери."""
    found = it.electrophoresis_offenders(FULL_PCT[1:] + FULL_GL)
    kinds = {f[2] for f in found}
    assert "сумма долей" in kinds and "число фракций %/масса" in kinds


def test_округления_бланка_не_считаются_дефектом():
    """Шесть слагаемых с одним знаком дают до ±0.3; допуск 1.5 их покрывает."""
    jitter = [(D, S, n, v + d, "%") for (_, _, n, v, _), d
              in zip(FULL_PCT, [0.1, -0.1, 0.2, -0.2, 0.1, 0.1])]
    assert it.electrophoresis_offenders(jitter) == []


def test_две_даты_судятся_порознь():
    """Иначе два разных анализа сложились бы в 200% и датчик молчал бы на обоих."""
    other = [(r[0].replace("29", "28"), *r[1:]) for r in FULL_PCT]
    assert it.electrophoresis_offenders(FULL_PCT + other) == []


def test_строка_без_значения_не_ломает_сумму():
    assert it.electrophoresis_offenders(FULL_PCT + [(D, S, "Прочее", None, "%")]) == []


def test_пустой_вход_молчит():
    assert it.electrophoresis_offenders([]) == []
