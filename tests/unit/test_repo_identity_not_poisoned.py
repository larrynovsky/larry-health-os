"""Оракул: личность НАСТОЯЩЕГО репозитория не подменена песочницей теста.

ЗАМЕР, РАДИ КОТОРОГО ЭТО НАПИСАНО (13.09.2026). В `.git/config` MacBook лежало
`user.name = t`, `user.email = t@t` — идентичность, которой подписываются
одноразовые репозитории тестов. Следствие: **61 коммит подряд**, с 12.09 14:07
по 13.09 13:19, ушёл в историю от автора `t <t@t>` вместо владельца. Глобальный
config при этом был верным — локальный его перебивал.

КЛАСС ОШИБКИ — НЕ «тест написал не туда», а «починку сделали, остаток не
убрали». Механизм нашли и вылечили в тот же день: коммит `6b03feb`, буквально
«оракул установщика писал в чужую историю — песочница стала fail-closed». Но
след, который он УЖЕ оставил в конфиге, никто не снял, потому что никто не
смотрел. Сам этот коммит подписан `t <t@t>` — подпись стоит на собственной
починке.

ЧТО ПРОВЕРЯЕТСЯ. Локальная идентичность репозитория не совпадает ни с одной из
тех, которыми подписываются песочницы ЭТОГО ЖЕ дерева тестов. Список песочных
идентичностей не зашит — он вычитывается из самих тестов, поэтому не устареет,
когда появится новая песочница с другим адресом.

ГРАНИЦА ЧЕСТНО. Тест ловит СЛЕД, а не момент его появления: если новый тест
испортит конфиг, узнать об этом можно будет только на следующем прогоне —
но узнать можно будет, а раньше нельзя было вовсе. Идентичность, не похожую
ни на одну песочную (например `ci@example.com`), он не отличит от настоящей.
"""
from __future__ import annotations

import re
import subprocess
from pathlib import Path

import pytest

pytestmark = [
    pytest.mark.test_meta(status="implemented", confirmation="confirmed"),
]

REPO_ROOT = Path(__file__).resolve().parents[2]

# Идентичности песочниц пишутся двумя способами — `config user.email <x>` и
# `-c user.email=<x>`; ловим оба, значение может быть в кавычках или без.
_ПЕСОЧНАЯ = re.compile(r'user\.(?:email|name)["\']?\s*[=,]\s*["\']([^"\']+)["\']')


def _песочные_личности() -> set[str]:
    найдено: set[str] = set()
    for f in (REPO_ROOT / "tests").rglob("*.py"):
        if f.name == Path(__file__).name:
            continue  # себя не читаем: примеры в докстроке не улики
        найдено.update(_ПЕСОЧНАЯ.findall(f.read_text(encoding="utf-8", errors="ignore")))
    return найдено


def _подпись(корень: Path | None = None) -> tuple[str, str]:
    """Чем РЕАЛЬНО подпишется следующий коммит В ЭТОМ дереве: имя и почта.

    КОРЕНЬ — ПАРАМЕТР, А НЕ КОНСТАНТА (F7 второго раунда ревью, 15.09).
    Подпись — свойство ДЕРЕВА, а не репозитория: git умеет worktree-локальный
    конфиг (`extensions.worktreeConfig` + `config --worktree`), и дерево нити
    может подписываться иначе, чем главная копия. Датчик обязан спрашивать то
    дерево, где коммит действительно произойдёт. По умолчанию это дерево, из
    которого запущен сам прогон, — оно же и есть то, где коммитят.

    ПОЧЕМУ НЕ `config --local` (внешнее ревью 14.09, F6). Прежняя редакция
    спрашивала только локальный конфиг — и была зелёной при отравлении
    ГЛОБАЛЬНОГО (`git config --global user.email t@t`), хотя коммит при этом
    подписывается ровно песочной личностью. Ревьюер воспроизвёл: датчик
    `1 passed`, а `git var GIT_AUTHOR_IDENT` отдаёт `t <t@t>`. Ущербный класс
    из замысла («61 коммит приехал за подписью песочницы») воспроизводился
    целиком при зелёном датчике.
    `git var` отвечает на вопрос ПОСТРАДАВШЕГО — «чем подписано», — а не на
    вопрос строителя «что лежит в этом конкретном файле конфига». Заодно он
    покрывает и те каналы, о которых я не подумал: env GIT_AUTHOR_*,
    includeIf, worktree-конфиг.
    """
    r = subprocess.run(["git", "-C", str(корень or REPO_ROOT), "var", "GIT_AUTHOR_IDENT"],
                       capture_output=True, text=True, timeout=30)
    # Формат: «Имя <почта> 1789378546 +0300»
    м = re.match(r"^(.*?)\s+<([^>]*)>", r.stdout.strip())
    return (м.group(1), м.group(2)) if м else ("", "")


def test_личность_репозитория_не_из_песочницы():
    if not (REPO_ROOT / ".git").exists():
        pytest.skip("не git-дерево — проверять нечего")

    песочные = _песочные_личности()
    assert песочные, (
        "не нашёл ни одной песочной идентичности в tests/ — тест перестал "
        "что-либо сверять именно тогда, когда это важнее всего")

    имя, почта = _подпись()
    for что, значение in (("имя", имя), ("почта", почта)):
        if not значение:
            continue
        assert значение not in песочные, (
            f"следующий коммит подпишется как {имя} <{почта}> — {что} взято из "
            f"ПЕСОЧНИЦЫ теста, а не у владельца. Значит какой-то тест написал в "
            f"конфиг (локальный, глобальный или окружение), и все коммиты с тех "
            f"пор подписаны им.\n"
            f"  Где искать: git config --show-origin --get-regexp '^user\\.'\n"
            f"  Найденные песочные идентичности: {sorted(песочные)}")


@pytest.mark.host_only
def test_подпись_судится_у_того_дерева_где_коммитят(tmp_path):
    """F7 второго раунда ревью (15.09): дерево нити может подписываться иначе.

    Git умеет worktree-локальный конфиг: `extensions.worktreeConfig=true` плюс
    `git config --worktree user.email ...`. Тогда главная копия подписывается
    владельцем, а дерево нити — чем угодно, и датчик, спрашивающий ГЛАВНУЮ
    копию, остаётся зелёным, пока коммиты нити уезжают за чужой подписью.
    Это тот же класс, что F6 (спрашивали не тот дом конфига), только осью
    ошиблись не вверх, а вбок.

    Судим ИСПОЛНЕНИЕМ: два дерева одного репозитория с разными подписями, и
    `_подпись` обязана отдать РАЗНОЕ, если спросить их порознь.
    """
    репо = tmp_path / "репо"; репо.mkdir()

    def g(*args, cwd=None):
        return subprocess.run(["git", "-C", str(cwd or репо), *args],
                              capture_output=True, text=True, timeout=60)

    g("init", "-q")
    g("config", "user.name", "владелец")
    g("config", "user.email", "owner@example.com")
    (репо / "f.txt").write_text("x\n", encoding="utf-8")
    g("add", "-A"); g("commit", "-qm", "base")

    дерево = tmp_path / "дерево-нити"
    r = g("worktree", "add", "-q", str(дерево), "-b", "thread/x")
    assert r.returncode == 0, r.stderr

    # Отравляем ТОЛЬКО дерево нити, главная копия остаётся чистой.
    g("config", "extensions.worktreeConfig", "true", cwd=дерево)
    r = g("config", "--worktree", "user.email", "t@t", cwd=дерево)
    assert r.returncode == 0, r.stderr

    _, почта_главной = _подпись(репо)
    _, почта_нити = _подпись(дерево)

    assert почта_главной == "owner@example.com", (
        f"обстановка не воспроизводится: главная копия уже отравлена "
        f"({почта_главной}) — тест ничего не судит")
    assert почта_нити == "t@t", (
        f"подпись дерева нити прочитана как {почта_нити!r}: датчик смотрит не "
        f"туда, где коммитят, и отравление дерева останется невидимым")


def test_датчик_читает_дерево_прогона_а_не_зашитый_путь():
    """Характеризация: у `_подпись` корень — параметр, и он работает.

    Без этого теста правка F7 держалась бы на том, что я передал аргумент;
    мутация «вернуть REPO_ROOT в теле» прошла бы мимо теста выше, потому что
    там сравниваются два ЯВНО переданных корня... нет, не прошла бы — но
    прошла бы мутация «игнорировать аргумент», и вот она краснеет здесь.
    """
    if not (REPO_ROOT / ".git").exists():
        pytest.skip("не git-дерево — проверять нечего")
    свой = _подпись(REPO_ROOT)
    по_умолчанию = _подпись()
    assert свой == по_умолчанию, (
        "явный корень и умолчание разошлись — значит аргумент не используется")
    assert свой[1], "подпись пуста: git var ничего не отдал, датчик слеп"
