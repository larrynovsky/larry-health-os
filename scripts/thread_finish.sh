#!/bin/bash
# Закрыть нить: слить её ветку в main, задеплоить, убрать дерево.
#
# ТРИ ВЕЩИ, КОТОРЫЕ ЗДЕСЬ НЕ СЛУЧАЙНЫ — каждая замерена пробой 12.09.
#
# 1. `--no-ff` обязателен. Fast-forward слияние не зовёт НИ ОДНОГО хука: ни
#    pre-commit, ни pre-merge-commit. То есть самый частый случай (main не
#    двигался, пока нить работала) прошёл бы мимо всех гейтов — ponytail,
#    дубль-гейта, гейта одноразовости, квитанции замысла, ruff и прогона
#    затронутых тестов. С `--no-ff` git создаёт merge-коммит и зовёт
#    pre-merge-commit, который установлен как тот же pre-commit.
#
# 2. Деплой — ЯВНЫМ шагом. При слиянии git не зовёт post-commit ни в каком
#    виде (зовёт post-merge, а деплой висит не на нём). Без этой строки работа
#    доехала бы до main на MacBook и молча остановилась: на Studio её нет, и в
#    deploy.log нет ни строки. Зовём тот же самый хук, а не копию его логики.
#
# 3. Дерево убирается ПОСЛЕ успешного деплоя, не раньше. Иначе при неудаче
#    работа осталась бы только в ветке, а дерева, где её чинить, уже нет.
#
# 4. Ребейз ПЕРЕД прогоном, прогон ПЕРЕД слиянием (15.09). Порядок здесь и есть
#    содержание правки: ребейз делает main предком ветки, поэтому дерево
#    merge-коммита совпадает с деревом ветки — и прогон, сделанный до слияния,
#    судит ровно то, что уедет. Переставь прогон после слияния — он станет
#    вторым прогоном того же; переставь до ребейза — он станет прогоном дерева,
#    которого не будет. Замер, из которого правка выросла: одна сессия 15.09,
#    main сдвинулся трижды, шесть полных прогонов, доказал последний.
#
# 5. Красный прогон НЕ глухая стена. Чужой красный — обычное состояние (15.09
#    два чужих прожили сутки), и глухой отказ сделал бы нить незакрываемой
#    из-за соседа; лечилось бы это обходом гейта. Обход есть и оставляет
#    квитанцию в истории: THREAD_FINISH_ACCEPT_RED='<причина>' уезжает в
#    сообщение merge-коммита. Пустая причина не принимается — отсутствие
#    суждения блокирует, его знак нет (та же норма, что у §15).
#
# 6. Дешёвое ДО дорогого (21.09). Гейты merge-коммита отвечают за секунды,
#    прогон — за пять минут, поэтому гейты пробуются ДО прогона (код 14), а
#    отбитое слияние скрипт отменяет сам: главная копия общая, и оставлять её
#    посреди слияния до чтения сообщения человеком нельзя.
#
# 7. Дрейф ЗАПИСКАМИ не сжигает прогон (21.09). Сосед, пишущий только
#    docs/handoff/**, за день сдвинул main во время прогона 2 раза из 4 — и
#    каждый раз пятиминутный прогон шёл заново. Единица согласованности была
#    «весь main», хотя прогон зависит не от всех его файлов (Таненбаум 7.2.1:
#    ложное разделение). Но и «записки тестов не касаются» — неправда: их читают
#    test_handoff_claims_not_stale, гейт квитанции замысла. Поэтому дрейф ТОЛЬКО в
#    docs/handoff/** → ребейз + ЗАТРОНУТЫЕ тесты по файлам дрейфа (секунды) →
#    слияние; любой другой дрейф — отказ 13, как прежде. Затронутые не ловят
#    тест, собирающий путь из переменных (граница affected_tests.py, названа там);
#    настоящий хук слияния прогоняет гейты ещё раз. Не больше 3 кругов.
#
# Оракул: tests/unit/test_thread_lifecycle.py
set -uo pipefail

SLUG="${1:-}"
[[ -n "$SLUG" ]] || { echo "thread_finish.sh: нужно имя нити" >&2; exit 2; }

REPO_ROOT="$(git rev-parse --show-toplevel 2>/dev/null)" || {
    echo "thread_finish.sh: не репозиторий" >&2; exit 2; }
# Главная копия — ТА, ОТКУДА ЗАПУЩЕНО. Раньше её вычисляли как «родитель
# каталога .git», и это молча врало на репозитории с ВЫНЕСЕННЫМ git-каталогом.
# Замер 13.09 на живом соседнем проекте: там `.git` — файл «gitdir: ~/.gitdirs/neighbour»,
# родитель даёт ~/.gitdirs, что вообще не репозиторий; закрытие нити падало
# с rc=3 «нет ветки thread/...» при живой ветке, и сообщение врало о причине.
# Заодно расходились имена: thread_start брал REPO_NAME из --show-toplevel
# (соседний проект), а здесь получалось «.gitdirs» — пути деревьев не сходились.
# Семь оракулов этого не видели: в песочнице .git лежит внутри дерева, где
# «родитель .git» и корень совпадают. Оракул формы — test_вынесенный_gitdir.
# Запуск из дерева нити отсекается ниже проверкой ветки: там HEAD на
# thread/<slug>, и скрипт скажет это вслух, а не подменит путь.
MAIN_TREE="$REPO_ROOT"
BRANCH="thread/$SLUG"
REPO_NAME="$(basename "$MAIN_TREE")"
TREE="$HOME/.worktrees/$REPO_NAME/$SLUG"
# Гейт квитанций при слиянии засчитывает квитанции ЭТОГО дерева по составу подсистемы
# (project_context/receipt.merge_credit). Имя дерева — через окружение: при настоящем
# `git merge` хук pre-merge-commit зовётся до записи MERGE_HEAD (замер 25.09).
export THREAD_MERGE_SOURCE="$TREE"

git -C "$MAIN_TREE" show-ref --verify --quiet "refs/heads/$BRANCH" || {
    echo "thread_finish.sh: нет ветки $BRANCH" >&2; exit 3; }

# Незакоммиченное в дереве нити — это работа, которую слияние не заберёт.
if [[ -d "$TREE" ]] && [[ -n "$(git -C "$TREE" status --porcelain)" ]]; then
    echo "thread_finish.sh: в дереве нити есть незакоммиченное — закоммить сначала:" >&2
    git -C "$TREE" status --short >&2
    exit 4
fi

CURRENT="$(git -C "$MAIN_TREE" rev-parse --abbrev-ref HEAD)"
[[ "$CURRENT" == "main" ]] || {
    echo "thread_finish.sh: не на main (сейчас '$CURRENT')." >&2
    echo "  закрывать нить нужно ИЗ ГЛАВНОЙ копии, не из дерева нити." >&2
    exit 5; }

# ── Третий случай отказа, найденный ЖИВЫМ прогоном 13.09 ─────────────────────
# Пять оракулов в песочнице его не нашли: там главная копия всегда чистая. На
# живом репозитории git отказал слиянием ещё до всяких гейтов —
#   «Your local changes to the following files would be overwritten by merge:
#    ARCH_SNAPSHOT.md CHANGELOG.md».
# Это не конфликт и не гейт: это незакоммиченное В ГЛАВНОЙ копии. И оно там
# почти всегда — doc_agent дописывает эти файлы в post-commit после КАЖДОГО
# коммита и оставляет застейдженными до следующего. То есть без этой ветки
# закрытие нити падало бы почти всегда, и сообщение врало бы про конфликт.
#
# Разделяем по происхождению, а не по «грязно/чисто»:
#   · только авто-генерируемые артефакты → коммитим их сами. Они и так
#     предназначены к коммиту и так же попадают в историю обычным путём;
#   · что-то ещё → это чужая работа (соседняя нить), решать за неё нельзя:
#     отказ с внятной причиной.
# ДОМ СПИСКА МАШИННЫХ АРТЕФАКТОВ ОДИН — `git_facts.MACHINE_REGENERATED_FILES`.
# Он существует с 07.09, его имена стережёт tests/consistency/test_machine_staged_files.py
# («имя без живого писателя = мёртвый фильтр»), и его же читает датчик
# незакоммиченного. До 14.09 здесь лежала ВТОРАЯ копия списка строкой, и копии
# успели разойтись в обе стороны: тут был лишний TESTING_CONTRACTS.md и
# ВЫДУМАННЫЙ docs/reference/dependency_graph.md (его нет в истории и не было
# никогда), а SECURITY.md не хватало. Найдено внешним ревью.
#
# Почему это ломало ВСЁ, а не портило список: `git add` с одним непопавшим
# pathspec возвращает 128 и НЕ СТЕЙДЖИТ НИЧЕГО — ни одного из совпавших путей.
# Отказ проглатывался `2>/dev/null || true`, ветка печатала сообщение об успехе
# и была no-op, а слияние следом падало дословно тем сообщением, против
# которого правка 13.09 и написана.
_PY=""
# ВНИМАНИЕ: имена переменных в bash — только ASCII. Кириллическое имя
# даёт «not a valid identifier», ветка уходит в пустой список и
# fail-closed срабатывает на ровном месте (поймано оракулом 14.09).
for _CAND in /opt/homebrew/bin/python3.11 python3.11 python3; do
    command -v "$_CAND" >/dev/null 2>&1 && { _PY="$_CAND"; break; }
done
# Список приходит ПОСТРОЧНО, а не через пробел: имя файла может содержать
# пробел (в этом репозитории есть каталог «Claude outputs»), и разбор по
# пробелам порезал бы такое имя на куски — артефакт перестал бы узнаваться и
# уехал бы в «чужую работу», то есть закрытие нити отказало бы на своём файле.
AUTO_ARTIFACTS=""
[[ -n "$_PY" ]] && AUTO_ARTIFACTS="$(cd "$MAIN_TREE" && "$_PY" -c \
    'import git_facts; print("\n".join(git_facts.MACHINE_REGENERATED_FILES))' 2>/dev/null)"
# Fail-closed, а не fail-open: без списка нельзя отличить машинный артефакт от
# чужой работы, а цена ошибки здесь — затёртая работа соседа на слиянии.
if [[ -z "$AUTO_ARTIFACTS" ]]; then
    echo "thread_finish.sh: не прочитан список машинных артефактов" >&2
    echo "  (git_facts.MACHINE_REGENERATED_FILES в $MAIN_TREE)." >&2
    echo "  Без него чужую работу от авто-артефакта не отличить — отказываюсь." >&2
    exit 9
fi

# ── ЗАМОК ГЛАВНОЙ КОПИИ (2026-09-23, нить finish-lock) ───────────────────────
# ЗАЧЕМ. 23.09 якорь закрытия first-miss лёг внутрь пробного слияния соседней
# нити, и git сделал из него merge-коммит ЧУЖОЙ нити (d15f91d). Песочница нашла
# и второе окно: внутри НАСТОЯЩЕГО слияния коммит соседа уносит чужой индекс с
# одним родителем. Главная копия общая, и отрезки, где она меняется, обязаны
# идти по одному. Имя и путь замка живут в scripts/git-hooks/finish_lock_guard.sh
# (он же судит прямые коммиты в main из pre-commit).
#
# КАК. flock ядра на дескрипторе 9 этой оболочки: python берёт замок на
# унаследованном дескрипторе и выходит, а замок остаётся за открытым описанием
# файла, то есть за этим процессом, и снимается ядром при его смерти. Держим
# ДВА отрезка, а не всё закрытие: на пятиминутный прогон замок отпускается —
# дрейф main во время прогона скрипт и так разбирает ниже.
#
# КЛЮЧЕВОЙ МОМЕНТ. Дескриптор 9 наследуют дети. Короткоживущие (git, хуки)
# выходят и не мешают; ребёнок, который переживёт скрипт, унёс бы замок с собой
# навсегда. Поэтому деплою дескриптор закрывается явно (`9>&-`).
LOCK_FILE="$("$MAIN_TREE/scripts/git-hooks/finish_lock_guard.sh" --path 2>/dev/null)"
_lock_take() {
    [[ -n "$LOCK_FILE" ]] || { echo "thread_finish.sh: путь замка не получен (finish_lock_guard.sh)" >&2; exit 15; }
    exec 9>>"$LOCK_FILE" || { echo "thread_finish.sh: не открыть $LOCK_FILE" >&2; exit 15; }
    if ! "$_PY" -c '
import fcntl, sys, time
end, said = time.time() + float(sys.argv[1]), False
while True:
    try:
        fcntl.flock(9, fcntl.LOCK_EX | fcntl.LOCK_NB)
        sys.exit(0)
    except BlockingIOError:
        if time.time() > end:
            sys.exit(1)
        if not said:
            print("⏳ главную копию меняет закрытие соседней нити — жду замок", file=sys.stderr)
            said = True
        time.sleep(0.5)
' "${THREAD_FINISH_LOCK_WAIT:-600}"; then
        echo "⛔ замок главной копии не получен за ${THREAD_FINISH_LOCK_WAIT:-600} с — сосед закрывает свою нить." >&2
        echo "   Ничего не тронуто. Повтори закрытие позже." >&2
        exit 15
    fi
    export THREAD_FINISH_HOLDS_LOCK=1
}
_lock_drop() { exec 9>&-; unset THREAD_FINISH_HOLDS_LOCK; }
# Вторая линия: коммит с --no-verify (артефакты, якорь) при ЧУЖОМ незаконченном
# слиянии стал бы его merge-коммитом. Под замком такого быть не должно, но замок
# не видит того, кто начал слияние руками мимо thread_finish.
_foreign_merge() { git -C "$MAIN_TREE" rev-parse -q --verify MERGE_HEAD >/dev/null 2>&1; }

_lock_take
# Судим ТОЛЬКО отслеживаемые файлы (--untracked-files=no, правка 13.09).
# Untracked исключены не из мягкости, а потому что слияние их НЕ ТРОГАЕТ: файл,
# о котором git не знает, перезаписать нечем. Единственное исключение — когда
# приносимый путь совпадает с чужим untracked; там git откажет САМ, своим
# точным сообщением «untracked working tree files would be overwritten».
# То есть точная проверка у git уже есть, и дублировать её грубой — вредно.
# Замерено живьём 13.09: закрытие нити упало с кодом 8 на чужом ЧЕРНОВИКЕ в
# plans/ и на csv в backups/ — ни того ни другого слияние не касалось бы.
# Песочница этого не показывала: там главная копия чистая по построению.
# Читаем имена по NUL (`-z`), а не построчно. Замерено 15.09 на git 2.54:
#   `status --porcelain`                → " M \"\\321\\201...\"" (октальные escape)
#   `-c core.quotepath=false` + porcelain → " M \"Claude outputs/файл с пробелом.md\""
#   `status -z --porcelain`              → " M Claude outputs/файл с пробелом.md\0"
# То есть построчный разбор отдаёт имя В КАВЫЧКАХ и, для кириллицы, ещё и
# экранированным. Такое имя не совпадает ни с одним машинным артефактом, и
# артефакт, чьё имя потребовало кавычек, уехал бы в ЧУЖОЕ — закрытие нити
# отказало бы на своём же файле. Живого ущерба пока нет (у всех четырёх
# артефактов имена без пробелов), но механизм был неверен, а сообщение
# человеку — нечитаемым. `-z` снимает и кавычки, и экранирование разом:
# quotepath к нему неприменим, потому что экранировать больше нечего.
# Переименования (R old -> new) приходят ДВУМЯ записями и в чужое попадут
# обе — это перестраховка в сторону отказа, не наоборот.
# Спрашиваем git ОДИН раз: первая редакция этой правки звала status дважды —
# для списка чужого и для признака «грязно ли». Из двух вызовов вышло не
# удобство, а дыра в оракуле: мутация, вернувшая untracked в ОДИН из них,
# оставляла второй прежним, блок целиком не исполнялся, и тест был зелёным на
# внесённом дефекте. Один источник — одна точка, где мутация обязана краснеть.
#
# ПОЧЕМУ БЕЗ ПРОМЕЖУТОЧНОЙ ПЕРЕМЕННОЙ. Bash не умеет хранить NUL: `$(...)`
# выбрасывает нулевые байты молча, и записи склеиваются в одну строку. Первая
# редакция этой правки так и сделала — `DIRTY="$(git status -z ...)"` — и чужая
# работа перестала находиться ВООБЩЕ: оракул покраснел сразу, но переменная
# выглядела совершенно обычно. Читаем прямо из процесса; «было ли грязно»
# несёт флаг, а не длина строки, поэтому git по-прежнему спрашивается ОДИН раз.
DIRTY_ANY=0
FOREIGN=""
while IFS= read -r -d '' LINE; do
    F="${LINE:3}"
    [[ -n "$F" ]] || continue
    DIRTY_ANY=1
    _IS_AUTO=0
    while IFS= read -r _A; do
        [[ -n "$_A" && "$_A" == "$F" ]] && { _IS_AUTO=1; break; }
    done <<< "$AUTO_ARTIFACTS"
    ((_IS_AUTO)) || FOREIGN="${FOREIGN}${F}"$'\n'
done < <(git -C "$MAIN_TREE" status -z --porcelain --untracked-files=no)
if ((DIRTY_ANY)); then
    if [[ -n "${FOREIGN//[$'\n' ]/}" ]]; then
        echo "thread_finish.sh: в главной копии есть незакоммиченная ЧУЖАЯ работа:" >&2
        while IFS= read -r F; do [[ -n "$F" ]] && echo "    $F" >&2; done <<< "$FOREIGN"
        echo "  Слияние её затрёт. Это работа соседней нити — решать за неё нельзя." >&2
        echo "  Дождись, пока сосед закоммитит, и повтори." >&2
        exit 8
    fi
    if _foreign_merge; then
        echo "thread_finish.sh: главная копия посреди ЧУЖОГО слияния (MERGE_HEAD) —" >&2
        echo "  коммит артефактов стал бы его merge-коммитом. Не трогаю; повтори позже." >&2
        exit 16
    fi
    echo "▶ коммичу артефакты doc_agent перед слиянием (их дописал post-commit)"
    # Стейджим ПОИМЁННО и только существующее: один непопавший путь обнуляет
    # весь `git add` целиком (rc=128, ничего не застейджено). Отказ больше не
    # глотаем — он означает, что слияние сейчас затрёт артефакт.
    _TO_STAGE=()
    while IFS= read -r _A; do
        [[ -n "$_A" ]] || continue
        [[ -e "$MAIN_TREE/$_A" ]] && _TO_STAGE+=("$_A")
    done <<< "$AUTO_ARTIFACTS"
    if ((${#_TO_STAGE[@]})); then
        if ! git -C "$MAIN_TREE" add -- "${_TO_STAGE[@]}"; then
            echo "thread_finish.sh: не удалось застейджить артефакты:" >&2
            printf '    %s\n' "${_TO_STAGE[@]}" >&2
            exit 10
        fi
        git -C "$MAIN_TREE" commit -q --no-verify \
            -m "docs: артефакты doc_agent перед слиянием нити $SLUG" \
            -- "${_TO_STAGE[@]}" || true
    fi
fi

# ── РЕБЕЙЗ И ЕДИНСТВЕННЫЙ ПОЛНЫЙ ПРОГОН (2026-09-15, решение владельца) ──────
# ЗАЧЕМ. До этой правки нить, жившая дольше пары часов, была обязана СЛИВАТЬ
# main внутрь себя всякий раз, когда сосед его двигал, и после каждого слияния
# перепроверяться заново: слитое дерево — новый предмет, и старый зелёный о нём
# не говорит ничего (§12, ось «не та версия»). Замер одной сессии 15.09: main
# сдвинулся трижды, полных прогонов вышло ШЕСТЬ по 5.5 минуты, и пять из них не
# доказали ничего — доказал последний.
#
