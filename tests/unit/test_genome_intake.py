def test_process_pending_spawns_once_and_notices_dead_run(tmp_path, monkeypatch):
    import genome_intake as gi
    told = []
    monkeypatch.setattr(gi, "_tell", lambda text, **kw: told.append(text))
    _23andme(tmp_path / "genome.txt")
    (tmp_path / "scan.pdf").write_bytes(b"%PDF-1.4")
    (tmp_path / "x.fastq").write_text("@r1\nACGT\n+\nIIII\n@r2\nACGT\n+\nIIII\n")
    spawned = []
    def spawn(p):
        spawned.append(p.name)
        return 999_999_999                          # такого pid нет → «процесс умер»
    assert gi.process_pending(tmp_path, spawn=spawn) == 2
    assert spawned == ["genome.txt"]
    assert gi._state(tmp_path / "x.fastq")["status"] == "unsupported"
    gi.process_pending(tmp_path, spawn=spawn)      # второй проход: мёртвый pid → громко
    assert spawned == ["genome.txt"]
    assert gi._state(tmp_path / "genome.txt")["status"] == "failed"
    assert told and "оборвалась" in told[-1]


def test_run_one_loads_raw_snps_then_refuses_second(db, tmp_path, monkeypatch):
    import genome_intake as gi, genome_pipeline, genome_parser, infra_config
    told = []
    monkeypatch.setattr(gi, "_tell", lambda text, **kw: told.append(text))
    monkeypatch.setattr(infra_config, "is_primary", lambda: True)
    got = []
    def fake_pipeline(filepath=None, **_):          # только S1: сеть и модель тесту не нужны
        got.append(filepath)
        genome_parser.import_raw_genome(Path(filepath))
        return {"raw_snps": N + 1}
    monkeypatch.setattr(genome_pipeline, "run_pipeline", fake_pipeline)
    src = _23andme(tmp_path / "genome.txt")
    res = gi.run_one(src)
    assert res["status"] == "done" and res["rows"] == N + 1, res
    with db.conn() as c:
        assert c.execute("SELECT COUNT(*) FROM raw_snps").fetchone()[0] == N + 1
    assert "Геном загружен" in told[-1]
    res2 = gi.run_one(_ancestry(tmp_path / "other.txt"))
    assert res2["status"] == "already_loaded" and len(got) == 1
    assert "уже загружен" in told[-1]


