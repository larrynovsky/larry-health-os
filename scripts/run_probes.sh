# (обесценивание даты при правке подсистемы) ловит дрейф КОДА; эта половина ловит дрейф
# ДАННЫХ и окружения, который коммит не видит.
#
# ГДЕ ИСПОЛНЯЕТСЯ. В `~/health_staging` на свежем снимке канона (Р-7). Пробы ПИШУТ —
# ставят пары в карантин, публикуют веру, двигают снимок pass-set; на боевой базе их не
# пустит предохранитель `health_db.assert_not_canonical` (Р-8), и это проверено замером
# У-2, включая подмену жёсткой ссылкой.
#
# КОДЫ ВЫХОДА ПРОБ — контракт (решение владельца 2026-07-29):
#   0 — держится
#   1 — сломан ИНВАРИАНТ  → статус обещания падает, строка в триаж
#   2 — сломана САМА ПРОБА → статус НЕ трогать, чинить оснастку
#   3 — СУДИТЬ НЕ НА ЧЕМ  → состояние ДАННЫХ (решение владельца 2026-08-12, вариант A):
#       статус НЕ трогать, чинить нечего; обещание стоит на датированном подтверждении,
#       возраст которого ежедневно предъявляет integrity_tests.check_probe_liveness.
# Без этих различий инфраструктурный сбой (или голод данных) понижал бы обещание зря,
# и после второго раза понижения перестали бы читать.
#
# РЕЗУЛЬТАТ — ДВА артефакта, и у них разные вопросы (28.09, BL-VERDICT-RUNNER-1):
#   · `logs/probe_verdicts.jsonl` — ЖУРНАЛ, строка на прогон, дописывается. Отвечает на
#     «был ли зелёный прогон НОСИТЕЛЯ после коммита X» — вопрос критериев закрытия
#     обещаний. Читается фильтром по `runner` (метка плиста носителя ≠ "manual") и `ran_at`.
#   · `logs/probe_verdicts.json` — СВОДКА последнего прогона, СОБИРАЕТСЯ из последней
#     строки журнала. Отвечает на «что сказал последний прогон» — вопрос сторожей. Её
#     читают `intent_registry.effective_status` (реестр перестаёт показывать holds
#     немедленно, без правки yaml человеком) и `integrity_tests.check_probe_liveness`
#     (протухший или красный вердикт → ночной монитор → триаж → Telegram).
# Источник ОДИН — журнал; сводка производная. Порядок записи обратный этому списку.
# Журнал не ротируется: `log_rotate.py` берёт только `*.log`, а рост тут 52 строки в год
# (~20 КБ). Обратная сторона того же имени названа честно: датчик слепого пятна ротации
# тоже смотрит только `*.log`, поэтому журнал вне его зрения.
