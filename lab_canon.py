#     lab_canon        → ничего из проекта
# Правило сведения материала и класса нужно ОБОИМ писателям канона. Пока оно
# жило у одного из них, второй импортировал первого — и общее знание держалось
# на зависимости писателя от писателя. Здесь у него честный общий предок, и
# цикла нет ПО ПОСТРОЕНИЮ, а не по аккуратности.
#
# Дом вердикта «класс → дом» — не тут: это ДАННЫЕ с оракулом-человеком
# (таблица `lab_domain_verdicts`, читатель `labs_db.domain_home`). Здесь только
# сведение сырой строки к КЛАССУ; куда класс едет — решает человек.

# Сырая строка бланка → класс материала. Классы КРУПНЫЕ намеренно: «Кровь с ЭДТА»
# и «Кровь (сыворотка)» — один забор в две пробирки, и разводить их значило бы
# получить два тренда одного аналита. Порядок проверок важен: «мазке из зева»
# содержит слово о материале, которого нет среди четырёх прежних классов, и он
# обязан сработать раньше общего разбора. Единственный дом; `lab_specimen`
# отдаёт сырую строку и сознательно ничего не классифицирует.
_SPECIMEN_BY_RAW = (
    ("зев", "throat_swab"), ("throat", "throat_swab"),
    ("моч", "urine"), ("urine", "urine"),
    ("кал", "stool"), ("фекал", "stool"), ("stool", "stool"), ("feces", "stool"),
    ("слюн", "saliva"), ("saliva", "saliva"),
    ("кров", "blood"), ("сыворотк", "blood"), ("плазм", "blood"),
    ("blood", "blood"), ("serum", "blood"), ("plasma", "blood"),
)


def specimen_class(raw: str) -> str | None:
    """Класс материала из СЫРОЙ строки бланка («Кровь с ЭДТА» → blood).

    None = строка есть, но не узнана. Это НЕ 'other': неузнанное имя материала
    обязано быть видно, а не слиться с «панель ничего не сказала». Возврат None
    уводит вызывающего на прежнюю ступень лестницы.

    Переехал из `lab_promote` 2026-08-01 (вердикт владельца 3). Прежний дом был
    честным ровно до появления второго писателя канона.
    """
    s = (raw or "").strip().lower()
    if not s:
        return None
    for needle, cls in _SPECIMEN_BY_RAW:
        if needle in s:
            return cls
    return None


# panel распознавателя → класс строки. `panel` — АРТЕФАКТ СТРАНИЦЫ, а не природы
