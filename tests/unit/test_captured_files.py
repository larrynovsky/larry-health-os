"""Оракул детектора захвата чужого файла в коммит.

КЛАСС, ПРОТИВ КОТОРОГО ЭТО. 12.09.2026 четыре раза файлы одной сессии уехали
внутри коммита другой (в том числе `c08d216` — staged-файлы одной сессии в
коммите второй). Причина не в неаккуратности: индекс git один на рабочее дерево,
а `git add` не знает, кто его звал. Долг BL-THREAD-GATE-1 ждал «следующего
зафиксированного случая» и ждал бы вечно: в самом коммите носителя понятия «эта
сессия» НЕТ — автор, коммиттер, трейлеры, notes и дерево одинаковы для своего
файла и для захваченного. Признак нашёл внешний тестировщик 14.09, и он лежит
СНАРУЖИ коммита — в ленте снимков рабочего дерева.

ЧТО ПРОВЕРЯЕТСЯ. Сценарий воспроизводится дословно: сессия A дописала файл и не
закоммитила, снимок это застал, сессия B закоммитила ОБА файла. Детектор обязан
назвать файл A и НЕ назвать файл B.

ГРАНИЦЫ — ЧАСТЬ ПРЕДМЕТА, И ОНИ ТОЖЕ ПОД ОРАКУЛОМ: захват внутри окна снимка не
виден (ложный пропуск), а своя давняя работа, закоммиченная без правок, от
захвата неотличима (ложное срабатывание). Оба случая зафиксированы тестами
ниже — чтобы следующий читатель не принял детектор за вердикт.
"""
from __future__ import annotations

import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

import pytest

pytestmark = [pytest.mark.unit, pytest.mark.host_only]
REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT))


def _env(home: Path) -> dict[str, str]:
    e = dict(os.environ)
    for v in ("GIT_DIR", "GIT_INDEX_FILE", "GIT_WORK_TREE", "GIT_COMMON_DIR",
              "GIT_AUTHOR_NAME", "GIT_AUTHOR_EMAIL", "GIT_COMMITTER_NAME",
              "GIT_COMMITTER_EMAIL"):
        e.pop(v, None)
    e["HOME"] = str(home)
    return e


@pytest.fixture()
def стенд():
    tmp = Path(tempfile.mkdtemp(prefix="captured_"))
    home = tmp / "home"; home.mkdir()
    repo = tmp / "repo"; repo.mkdir()
    e = _env(home)

    def g(*a):
        return subprocess.run(["git", "-C", str(repo), *a], capture_output=True,
                              text=True, timeout=60, env=e)

    g("init", "-q"); g("config", "user.email", "t@t"); g("config", "user.name", "t")
    (repo / "base.txt").write_text("base\n", encoding="utf-8")
    g("add", "-A"); g("commit", "-qm", "base", "--no-verify")

    def снимок():
        """То, что делает backup.sh --wip: дерево во временный индекс → ref."""
        idx = tmp / "idx"
        shutil.copy(repo / ".git" / "index", idx)
        e2 = dict(e); e2["GIT_INDEX_FILE"] = str(idx)
        subprocess.run(["git", "-C", str(repo), "add", "-A"], env=e2,
                       capture_output=True, timeout=60)
        tree = subprocess.run(["git", "-C", str(repo), "write-tree"], env=e2,
                              capture_output=True, text=True, timeout=60).stdout.strip()
        snap = g("commit-tree", tree, "-p", "HEAD", "-m", "snapshot").stdout.strip()
        g("update-ref", "refs/backups/wip", snap)

    import git_facts as gf
    старый = gf.ROOT

    def детектор(коммит="HEAD"):
        gf.ROOT = repo
        try:
            return gf.captured_files(коммит)
        finally:
            gf.ROOT = старый

    try:
        yield repo, g, снимок, детектор
    finally:
        gf.ROOT = старый
        shutil.rmtree(tmp, ignore_errors=True)


def test_захват_назван_а_своя_работа_нет(стенд):
    """Дословный сценарий `c08d216`: две сессии в одном дереве."""
    repo, g, снимок, детектор = стенд
    # Сессия A дописала и НЕ закоммитила.
    (repo / "a_module.py").write_text("# работа сессии A\n", encoding="utf-8")
    снимок()
    # Сессия B пишет своё и коммитит ОБА файла.
    (repo / "b_module.py").write_text("# работа сессии B\n", encoding="utf-8")
    g("add", "-A"); g("commit", "-qm", "feat(b): работа сессии B", "--no-verify")

    найдено = детектор()
    assert найдено == ["a_module.py"], (
        f"детектор обязан назвать ЧУЖОЙ файл и только его: {найдено}")


def test_машинные_артефакты_не_считаются_захватом(стенд):
    """CHANGELOG.md всегда грязный после post-commit — иначе датчик станет фоном."""
    repo, g, снимок, детектор = стенд
    (repo / "CHANGELOG.md").write_text("## запись doc_agent\n", encoding="utf-8")
    снимок()
    (repo / "b.py").write_text("x = 1\n", encoding="utf-8")
    g("add", "-A"); g("commit", "-qm", "работа", "--no-verify")
    assert детектор() == [], "машинный артефакт принят за чужую работу"


def test_правленный_после_снимка_файл_не_захват(стенд):
    """Побайтное совпадение — суть признака.

    Если коммиттер файл ПРАВИЛ после снимка, это его работа, а не подобранная
    чужая. Без этого условия детектор кричал бы на каждый обычный коммит.
    """
    repo, g, снимок, детектор = стенд
    (repo / "мой.py").write_text("v = 1\n", encoding="utf-8")
    снимок()
    (repo / "мой.py").write_text("v = 2\n", encoding="utf-8")  # правил сам
    g("add", "-A"); g("commit", "-qm", "доделал своё", "--no-verify")
    assert детектор() == [], "правленный после снимка файл принят за захват"


def test_без_снимка_детектор_говорит_не_знаю(стенд):
    """None — это «судить не на чем», и оно ОТЛИЧНО от пустого списка.

    Пустой список значит «захвата нет», None — «ленты снимков нет». Слить их в
    одно значило бы выдать отсутствие данных за отсутствие проблемы; ровно тот
    класс, из-за которого датчик незакоммиченного молчал «всё хорошо».
    """
    repo, g, снимок, детектор = стенд
    (repo / "x.py").write_text("x\n", encoding="utf-8")
    g("add", "-A"); g("commit", "-qm", "без снимка", "--no-verify")
    assert детектор() is None, "без снимка детектор обязан отвечать «не знаю»"


def test_граница_окна_захват_внутри_окна_не_виден(стенд):
    """Ложный пропуск назван оракулом, а не только прозой.

    Захват, случившийся ПОСЛЕ последнего снимка, в ленте не отражён — детектор
    молчит. Это не дефект реализации, это цена окна в 3 часа, и она обязана
    быть зафиксирована, чтобы никто не принял молчание за доказательство.
    """
    repo, g, снимок, детектор = стенд
    снимок()  # снимок ДО того, как сосед что-либо написал
    (repo / "чужой.py").write_text("# сосед\n", encoding="utf-8")
    g("add", "-A"); g("commit", "-qm", "захват внутри окна", "--no-verify")
    assert детектор() == [], (
        "детектор увидел захват внутри окна снимка — значит либо признак не тот, "
        "либо граница описана неверно; в обоих случаях документацию надо править")


def test_откат_правки_сделанной_после_снимка_не_захват(стенд):
    """ИСПРАВЛЕНИЕ МОЕГО ЖЕ УТВЕРЖДЕНИЯ (15.09, раунд 2 внешнего ревью, F3).

    14.09 я записал в квитанции, что мутация «убрать пересечение с грязным на
    снимке» пережила свёртку по-честному — то есть что пересечение ничего не
    решает. Ревьюер возразил: откат файла выглядел бы как захват. Проверяя
    это, я сначала построил сценарий, который НЕ воспроизводится (перезапись
    файла тем же содержимым просто не попадает в коммит), и ровно поэтому
    формулирую условие точно.

    Чтобы файл попал в подозреваемые БЕЗ пересечения, нужно всё сразу:
      • файл ЕСТЬ в коммите — значит его содержимое отличается от родителя;
      • его содержимое побайтно равно снимку;
      • на снимке он НЕ был грязным — иначе пересечение и так его пропустит.
    Это ровно откат правки, сделанной ПОСЛЕ снимка:
      v1 → снимок (дерево чистое) → v2 коммитом → обратно v1 коммитом.

    Итог: ревьюер прав, вчерашний я неправ. Пересечение несёт нагрузку.
    """
    repo, g, снимок, детектор = стенд
    (repo / "моё.py").write_text("v1\n", encoding="utf-8")
    g("add", "-A"); g("commit", "-qm", "v1", "--no-verify")
    снимок()                                   # дерево чистое: моё.py не грязный

    (repo / "моё.py").write_text("v2 — черновик\n", encoding="utf-8")
    g("add", "-A"); g("commit", "-qm", "v2", "--no-verify")

    (repo / "моё.py").write_text("v1\n", encoding="utf-8")   # откат
    g("add", "-A"); g("commit", "-qm", "откатил черновик", "--no-verify")

    найдено = детектор()
    assert "моё.py" not in найдено, (
        f"откат собственной правки принят за захват чужого файла: {найдено}")


def test_пересечение_с_грязным_несёт_нагрузку(стенд):
    """Характеризация утверждения выше — свёрткой, а не рассуждением.

    Воспроизводит ту же обстановку и показывает, что БЕЗ пересечения откат
    попал бы в подозреваемые. Первый assert — сторож самого теста: без него
    он был бы зелёным и когда обстановка не воспроизводит спорный случай,
    а это тот же класс ложного негатива, что О-14 и M3.
    """
    repo, g, снимок, детектор = стенд
    (repo / "моё.py").write_text("v1\n", encoding="utf-8")
    g("add", "-A"); g("commit", "-qm", "v1", "--no-verify")
    снимок()
    (repo / "моё.py").write_text("v2\n", encoding="utf-8")
    g("add", "-A"); g("commit", "-qm", "v2", "--no-verify")
    (repo / "моё.py").write_text("v1\n", encoding="utf-8")
    g("add", "-A"); g("commit", "-qm", "откат", "--no-verify")

    import git_facts as gf
    старый = gf.ROOT
    gf.ROOT = repo
    try:
        снимок_sha = gf._git(["rev-parse", "--verify", "refs/backups/wip^{commit}"]).strip()
        в_коммите = {x for x in (gf._git(
            ["show", "--name-only", "--format=", "HEAD"]) or "").split("\n") if x.strip()}
        без_пересечения = [
            f for f in sorted(в_коммите)
            if f not in gf.MACHINE_REGENERATED_FILES
            and (gf._git(["rev-parse", f"{снимок_sha}:{f}"]) or "x").strip()
            == (gf._git(["rev-parse", f"HEAD:{f}"]) or "y").strip()]
    finally:
        gf.ROOT = старый

    assert "моё.py" in без_пересечения, (
        "обстановка не воспроизводит спорный случай — тест ничего не судит")
    assert "моё.py" not in детектор(), (
        "настоящий детектор обязан это отсеять, а без пересечения — не отсеивает")
