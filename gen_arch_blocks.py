def arch_blocks_descriptions(only=None, *, signals_by_domain=None):
    """Collect full Russian strings before rendering limits; supply signals to avoid a DB read.

    `only="xfail_list"` needs source files only. With no selection both data-bearing
    blocks are collected; inventory prose is owned by this generator's literal table.
    """
    descriptions = DescriptionText()
    if only in (None, "xfail_list"):
        build_xfail_list(descriptions=descriptions)
    if only in (None, "domain_signals"):
        build_domain_signals(descriptions=descriptions, signals_by_domain=signals_by_domain)
    return descriptions.texts


def _apply_block(src: str, start: str, end: str, new_block: str) -> tuple[str, bool]:
    """Возвращает (new_src, changed). Если маркеров нет — добавляет в конец файла."""
    if start in src and end in src:
        before, _rest = src.split(start, 1)
        _old, after = _rest.split(end, 1)
        new_src = before + new_block + after
    else:
        # Первый коммит: добавляем в конец.
        new_src = src.rstrip() + "\n\n---\n\n" + new_block + "\n"
    return new_src, new_src != src


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--only", choices=list(GENERATORS.keys()), help="Запустить только один блок")
    parser.add_argument("--lang", choices=("ru", "en"), default="ru")
    args = parser.parse_args(argv)
    import infra_config
    hostname = socket.gethostname()
    if not infra_config.is_primary(hostname):
        sys.exit(f"gen_arch_blocks.py: запуск только на Studio (текущий: {hostname}). CLAUDE.md §8.")
    target = ARCH if args.lang == "ru" else ARCH.with_name("ARCH_SNAPSHOT.en.md")
    descriptions = DescriptionText(args.lang)
    try:
        return _write_blocks(target, args.only, args.lang, descriptions)
    finally:
        if args.lang == "en":
            print(f"untranslated: {descriptions.untranslated}")


def _write_blocks(target, only, lang, descriptions):
    if not target.exists():
        print(f"❌ {target} not found")
        return 2

    targets = [only] if only else list(GENERATORS.keys())
    src = target.read_text(encoding="utf-8")
    total_changed = 0
    for name in targets:
        start, end, builder = GENERATORS[name]
        block = builder(lang, descriptions=descriptions)
        src, changed = _apply_block(src, start, end, block)
        if changed:
            total_changed += 1
            print(f"✅ {name} regenerated")
        else:
            print(f"✅ {name} already up-to-date")

    if total_changed:
        target.write_text(src, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
