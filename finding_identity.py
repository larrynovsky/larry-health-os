#!/usr/bin/env python3.11
"""finding_identity.py — ИМЯ и КЛАСС находки. Один домен: «что это за находка», не
«как её доставить» и не «что с ней делать».

Зачем. Без устойчивого имени меняющиеся счётчики делают одну находку несколькими
несвязанными сообщениями. Например, «очередь растёт» сегодня и завтра — один предмет,
даже если длина очереди изменилась. Имя позволяет закрыть или отложить этот предмет,
сохраняя его историю.

ПРАВИЛО ИМЕНИ: метка находки (title из integrity_latest.json, БЕЗ detail), из неё убраны
значки, регистр снижен, любая группа цифр заменена на N, пробелы сжаты. Всё. Ни хэша, ни
обрезки по двоеточию: хэш всего текста ломается от смены счётчика (ровно случай выше), а
обрезка по первому двоеточию сливает `survivorship: конфликты` с `survivorship: опросники`
в один предмет — ложное разделение, когда закрытие одного гасит другой.

ГРАНИЦА, названная вслух: имя выводится из ТЕКСТА метки. Датчик, переформулировавший свою
метку, получит новое имя, и находка будет выглядеть новой. Это цена формы, и она не больше
той, что уже платит классификация по подстроке. Датчик, которому нужна устойчивость к
переформулировке, обязан передать `key=` явно — тогда текст перестаёт участвовать вовсе.

КЛАСС — что находка просит у читателя: decide (оракул только человек) · fix (инженерный
worklist) · standing (датированное состояние, действия сейчас нет).

Умолчание fix (решение владельца 30.09, до того было decide). Незнакомая находка идёт в
инженерную очередь, а не на стол владельца. Замер 13–30.09: через умолчание decide на
стол легло 12 карточек, из них 10 сняла сама система, не дождавшись ответа, на одну он
ответил, и она оказалась инженерной; настоящим его вопросом была одна («кран
литературы»: сработало условие пересмотра его же решения). В реестре не было ни одной
явной метки decide, то есть весь поток к владельцу шёл только через умолчание.
Fail-closed при этом не снят, а перенесён туда, где он осмыслен: инженерная очередь
ничего не исполняет сама (понизить к ней — не повысить права), а необратимое и
пишущее в домен владельца уходит ему по СТРУКТУРНОЙ причине
(night_cycle → owner_gate.owner_is_the_oracle) при любом классе. Вопрос, который
по природе принадлежит владельцу, помечается decide ЯВНО, поимённо.
"""
from __future__ import annotations

import re

_DIGITS = re.compile(r"\d+")
_LEAD = re.compile(r"^[^0-9A-Za-zА-Яа-яЁё\[]+")
_SPACE = re.compile(r"\s+")

CLASSES = ("decide", "fix", "standing")
DEFAULT_CLASS = "fix"   # 30.09, обоснование — в шапке модуля

# «Здесь не судимо» — не находка, а отказ судить: предмет датчика (репозиторий, launchd
# хоста) в этом рантайме не виден. Деталь предупреждения НАЧИНАЕТСЯ с этой строки — тогда
# класс standing при любой метке (night_cycle._load_warnings). Без этого 30.09 владельцу
# ушли «хуки исполняемы?» и «людей стало значительно больше» — оба от контейнера, который
# не видит ни .git, ни LaunchAgents. Один дом строки: пишут integrity_tests, читает цикл.
NOT_JUDGED_HERE = "не судимо в контейнере"


def class_of_warning(label: str, detail: str = "") -> str:
    """Класс предупреждения с учётом детали: «здесь не судимо» → standing."""
    if str(detail or "").strip().lower().startswith(NOT_JUDGED_HERE):
        return "standing"
    return finding_class(label)

# Подстрока метки (в нижнем регистре) → класс. Переехало из triage_agent.WARN_CLASSES
