def _key(name: str) -> str:
    s = (name or "").strip().lower()
    # ТУРЕЦКАЯ İ (2026-08-09). `"BİLİRUBİN".lower()` даёт `i` + U+0307 (combining dot
    # above), и имя перестаёт совпадать с ascii-синонимом. Проект уже платил за этот
    # класс отдельным алиасом AFP; здесь он закрыт целиком.
    #
    # СНИМАЕТСЯ ТОЛЬКО U+0307 И ТОЛЬКО ПОСЛЕ `.lower()`. Обе узости — результат
    # ЗАМЕРА, а не осторожности вообще:
    #   • снятие ВСЕХ комбинирующих ломает 84 сопоставления из снимка (`й`→`и`,
    #     `ё`→`е`, `ä`→`a`: «Билирубин общий» перестаёт быть Bilirubin_total, потому
    #     что словарь свёрнут не так же);
    #   • до `.lower()` снимать нечего: İ — precomposed U+0130, точка появляется
    #     только при понижении регистра.
    # Замер узкой правки: дрейф 5, опасных (канон A → канон B) — НОЛЬ. Все пять —
    # «имя не сводилось ни к чему → свелось»: BİLİRUBİN, FERRİTİN, HEMOGLOBİN(HGB),
    # VİTAMİN B12, GAİTADA GİZLİ KAN.
    #
    # ГРАНИЦА, названная честно: у мочевых турецких имён (GLUKOZ/PROTEİN/BİLİRUBİN)
    # эта ветка не используется — для не-крови промоут доверяет имени от модели
    # (`lab_promote.prepare`). Но если материал будет определён НЕВЕРНО как кровь,
    # мочевой билирубин теперь молча сведётся к кровяному вместо громкого
    # `unmapped-nonanalyte`. Обмен принят: раньше терялись ВСЕ турецкие имена.
    s = s.replace("̇", "")
    # Двуязычная подпись может нести перевод после прямого или обратного слэша.
    # Хвост срезается только при отсутствии в нём латиницы и кириллицы:
    # иначе разрушились бы составные имена и отношения величин.
    # Суффикс % сохраняется как признак процентной колонки.
    _sep = next((ch for ch in ("/", "\\") if ch in s), None)
    if _sep:
        head, _, tail = s.partition(_sep)
        if head.strip() and not re.search(r"[a-zа-я]", tail):
            s = head.strip() + (" %" if "%" in tail else "")
    s = re.sub(r"\([^)]*\)", "", s)          # убрать (RBC) и т.п.
    s = s.replace("ё", "е")
    # суффиксы лабораторий (нем. "i.S." = в сыворотке, метод LC-MS/MS, °, и т.п.)
    s = re.sub(r"[°\*]", "", s)
    s = re.sub(r"\bi\.?\s?s\.?", "", s)        # i.S. / i.s
    s = re.sub(r"\blc-ms/ms\b", "", s)
    s = re.sub(r"[.\s]+$", "", s)              # хвостовые точки/пробелы
    s = re.sub(r"\s+", " ", s).strip()
    return s


