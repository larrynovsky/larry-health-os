def normalize(name: str) -> str:
    """Любой вариант имени аналита → canonical. Если не знаем — возвращаем
    исходное (очищенное) имя, не теряя его."""
    if not name:
        return name
    # ионизированный кальций: дискриминатор "ca2+"/"ионизир" теряется при срезании
    # скобок в _key ("Кальций (Ca2+)"→"кальций"→Calcium). Ловим ДО _key.
    _low = name.lower()
    if "ca2+" in _low or ("ионизир" in _low and "кальц" in _low):
        return "Calcium_ionized"
    k = _key(name)
    if k in _LOOKUP:
        return _LOOKUP[k]
    # имя с процентом (в т.ч. "neutrophils %" с пробелом): процентный вариант
    # ПРИОРИТЕТНЕЕ абсолютного. Иначе "Neutrophils %" через голый base "neutrophils"
    # схлопывалось в Neutrophils_abs и конфликтовало с настоящим abs (баг ревью full2).
    if k.endswith("%") or k.startswith("%"):   # "neutrophils %" И "% neutrophils"
        base = k.strip("%").strip()
        if base + "%" in _LOOKUP:       # явный %-алиас → _pct
            return _LOOKUP[base + "%"]
        if base in _LOOKUP:
            return _LOOKUP[base]
    # Последняя попытка: сложить гомоглифы во входе так же, как в _LOOKUP.
    # Разные алфавиты одной визуальной буквы не должны порождать разные имена.
    #
    # Почему именно ПОСЛЕ основного поиска, а не вместо него: фолдинг входа уже
    # пробовали в этой нити и он ломал соседей — `С-реактивный белок` переставал
    # находить `CRP`, а русские предлоги превращались в латиницу. Здесь порядок
    # делает регрессию невозможной по построению: ветка достижима, только когда
    # обычный поиск УЖЕ промахнулся, поэтому она умеет превращать «не знаю» в имя
    # и не умеет менять уже найденное.
    _fk = _key(_fold_homoglyphs(name, keep_prepositions=False))
    if _fk in _LOOKUP:
        return _LOOKUP[_fk]
    # Для неизвестного имени тоже чистим гомоглифы и сноски,
    # иначе повторное чтение одного обозначения может создать дубль.
    return _fold_unknown(name)


