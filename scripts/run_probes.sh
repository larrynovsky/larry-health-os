chmod 600 "$STAGING/data/health.db"
# ВХОД ПРОБ ВОССТАНАВЛИВАЕТСЯ ПЕРЕД КАЖДОЙ ПРОБОЙ, а не один раз за прогон.
# Пробы могут менять staging-историю, а следующая проба — читать её хвост.
# Тогда вердикт зависит от порядка запуска, а не от проверяемого механизма.
# Восстановление входа перед каждой пробой обеспечивает изоляцию независимо
# от того, откатила ли предыдущая проба собственные изменения.
#
# Отказ копирования БОЛЬШЕ НЕ ГЛУШИТСЯ: `2>/dev/null || true` означало, что проба
# молча пойдёт с чужим входом, а её вердикт будет говорить об инварианте то, чего он
# не проверял. Отсутствие исходника — законное состояние (артефакт ещё не рождался),
# и оно спрашивается вопросом, а не ловится подавлением.
sync_gate_inputs() {
  for f in gate_passset_history.json gate_mc_gap_latest.json gate_run_receipt.json; do
    [ -f "$REPO/logs/$f" ] || continue
    cp "$REPO/logs/$f" "$STAGING/logs/$f" || {
      echo "⛔ вход проб не восстановлен ($f) — проба пошла бы с ЧУЖИМ снимком"; exit 2; }
  done
}
for f in anthropic_key healthcheck_url oura_token sync_token telegram_token; do
  [ -f "$SEC/$f" ] || printf 'STAGING_DUMMY' > "$SEC/$f"
done
[ -f "$SEC/telegram_chat_id" ] || printf '999999999' > "$SEC/telegram_chat_id"
chmod 600 "$SEC"/* 2>/dev/null || true

# ПАДЕНИЕ ПРОБЫ — НЕ ВЕРДИКТ ОБ ИНВАРИАНТЕ (2026-09-21). Непойманное исключение Python
# выходит с кодом 1, а 1 по контракту выше значит «сломан инвариант». Замер 21.09: проба
# Дополнения 3 упала на `import health_db` (ей нужен корень репо в sys.path, носитель его
# не давал), и владельцу ушло «ПРОБА КРАСНАЯ — сломан инвариант» про обещание, которое
# никто не проверял. Запуск через runpy: SystemExit пробы проходит как есть, любое
# непойманное исключение = 2 («сломана проба»). Попутно `-c` кладёт в sys.path текущий
# каталог (корень снимка) — проба без собственного sys.path.insert больше не падает.
# Контроль: tests/unit/test_probe_carrier.py::test_crash_is_broken_harness_not_invariant.
run_probe() {
  "$PY" -c 'import runpy, sys, traceback
sys.argv = sys.argv[1:]
try:
    runpy.run_path(sys.argv[0], run_name="__main__")
except SystemExit:
    raise
except BaseException:
    traceback.print_exc()
    sys.exit(2)' "$@"
}

RESULTS=""
for entry in "${PROBES[@]}"; do
  set -- $entry
  probe="$1"; shift
  echo
  echo "-- $probe $* --"
  sync_gate_inputs          # ← чистый вход КАЖДОЙ пробе (см. комментарий выше)
  ( cd "$STAGING" && HEALTH_DATA_DIR="$STAGING" HEALTH_SECRETS_DIR="$SEC" \
      run_probe "$probe" "$@" ) 2>&1 | tail -25
  rc=${PIPESTATUS[0]}
  echo "   код выхода: $rc"
  RESULTS="$RESULTS$probe=$rc"$'\n'
done


# ── Полоса живой модели ──────────────────────────────────────────────────────
# Свой каталог секретов, а не правка общего: общий переиспользуется между прогонами
# и пробами, и «на минуточку положить настоящий ключ» в него означало бы, что он там
# останется. Каталог создаётся здесь, умирает здесь.
if [ ${#LIVE_PROBES[@]} -gt 0 ]; then
  LIVE_SEC="$STAGING/.secrets_live"
  mkdir -p "$LIVE_SEC"
  for f in healthcheck_url oura_token sync_token telegram_token; do
    printf 'STAGING_DUMMY' > "$LIVE_SEC/$f"
  done
  printf '999999999' > "$LIVE_SEC/telegram_chat_id"
  printf '{}' > "$LIVE_SEC/google_calendar_token.json"
  # Единственный настоящий. Значение не печатается и не уезжает никуда, кроме файла
  # с правами 600 на том же диске, где оно уже лежит (§19).
  if [ -f "$REAL_SECRETS/anthropic_key" ]; then
    cp "$REAL_SECRETS/anthropic_key" "$LIVE_SEC/anthropic_key"
  else
    echo "⛔ настоящего anthropic_key нет — живые пробы пропущены, оснастка сломана"
    for probe in "${LIVE_PROBES[@]}"; do RESULTS="$RESULTS$probe=2"$'\n'; done
    LIVE_PROBES=()
  fi
  chmod 600 "$LIVE_SEC"/* 2>/dev/null || true
fi

for entry in "${LIVE_PROBES[@]:-}"; do
  [ -n "$entry" ] || continue
  set -- $entry
  probe="$1"; shift
  echo
  echo "-- $probe $* (живая модель) --"
  sync_gate_inputs
  ( cd "$STAGING" && HEALTH_DATA_DIR="$STAGING" HEALTH_SECRETS_DIR="$LIVE_SEC" \
      run_probe "$probe" "$@" ) 2>&1 | tail -25
  rc=${PIPESTATUS[0]}
  echo "   код выхода: $rc"
  RESULTS="$RESULTS$probe=$rc"$'\n'
done

echo
echo "-- запись вердиктов --"
if RESULTS="$RESULTS" STARTED="$STARTED" "$PY" - <<'PY'
import json, os, pathlib
lines = [l for l in os.environ["RESULTS"].splitlines() if "=" in l]
verdicts = {}
for l in lines:
    probe, _, rc = l.rpartition("=")
    rc = int(rc)
    verdicts[probe] = {
        "exit": rc,
        # Словами, а не только числом: артефакт читают и машины, и человек в триаже.
        "verdict": {0: "держится", 1: "СЛОМАН ИНВАРИАНТ", 2: "СЛОМАНА ПРОБА",
                    3: "СУДИТЬ НЕ НА ЧЕМ"}.get(rc, "неизвестно"),
    }
out = pathlib.Path(os.environ.get("PROBE_VERDICTS_OUT")
                   or os.path.expanduser("~/health_scripts/logs/probe_verdicts.json"))
jrn = out.with_suffix(".jsonl")
out.parent.mkdir(parents=True, exist_ok=True)
# КТО запустил (23.09, решение владельца «ок»). Критерий подъёма обещания говорит «первый
# зелёный прогон НОСИТЕЛЯ», а ручной прогон артефакт до сих пор не отличал: 21.09 ручной
# прогон соседа записал вердикт за 29 минут до коммита, который он должен был судить.
# launchd кладёт в окружение задачи её метку (XPC_SERVICE_NAME, замер 23.09 на Studio:
# у com.larry.health.bot.partner — своя метка, в ssh — не задано; Terminal ставит «0»).
# Пишется сырой факт без толкования: штатный ли прогон, судит читатель, сравнив с меткой
# плиста носителя.
_xpc = os.environ.get("XPC_SERVICE_NAME", "")
record = {
    "ran_at": os.environ["STARTED"],
    "where": "staging",          # Р-9: место прогона называется, а не подразумевается
    "runner": _xpc if _xpc not in ("", "0") else "manual",
    "probes": verdicts,
}

# ЖУРНАЛ ПЕРВЫМ, сводка — производная (решение владельца 28.09, BL-VERDICT-RUNNER-1).
# Сводка `probe_verdicts.json` хранит ОДИН прогон, и это верно для её читателей: и
# effective_status, и check_probe_liveness спрашивают «что сказал ПОСЛЕДНИЙ прогон».
# Ложно другое: у критериев закрытия обещаний вопрос иной — «был ли зелёный прогон
# НОСИТЕЛЯ после коммита X», а на него переменная ответить не может. 28.09 ручной прогон
# в 03:48Z затёр вердикт носителя от 03:20Z: в сводке остался exit 0 там, где носитель дал
# exit 1, и по одному ran_at + exit 0 подъём статуса выглядел бы законным (§12, ложная
# зелень на не том прогоне). Второй случай того же за восемь дней; первый — 21.09.
# Поэтому строка дописывается в журнал, а сводка берётся из его последней строки. Что
# здесь ПРАВДА обеспечено, без самообмана: журнал — ВОРОТА. Сводка не сдвигается, пока
# строка не легла в журнал и не прочиталась оттуда обратно. «Сводка собирается из журнала»
# как таковое непроверяемо: при исправной работе последняя строка и своя запись совпадают
# всегда, так что json.dumps(last) и json.dumps(record) неразличимы никаким тестом. Не
# оборачивать запись журнала в try/except «чтобы не ломать»: это снимет ворота и вернёт
# два дома одного значения. Сторож этого — test_summary_never_moves_without_the_journal.
with jrn.open("a", encoding="utf-8") as fh:
    fh.write(json.dumps(record, ensure_ascii=False) + "\n")

